test('W66 PostgreSQL readers: an ordinary single-output project is read through its sealed State', { skip: !enabled, timeout: 280_000 }, async () => {
  const run = randomUUID().replaceAll('-', '').slice(0, 10)
  const db = new PrismaClient()
  try {
    const project = await ordinaryProject(db, { run, tag: 'ord', aspectRatio: '4:5' })
    const { scope, head, workspaceId, projectId } = project
    assert.equal(head.state.document.entries[0].consumption.status, 'materialized', 'the head plays an observed recording')

    // The verdict every reader takes: the exact Version, its only output, the purpose.
    for (const purpose of ['render', 'critic', 'final']) {
      const admitted = await requirePersistedOutputConsumptionV3(db, { ...scope, versionId: head.version.id, purpose })
      assert.equal(admitted.aspectRatio, '4:5', purpose)
      assert.equal(admitted.seal.outputStateHash, head.state.stateHash, purpose)
    }

    // The render evidence of that output: a proxy render of the head Version and the review stored for it.
    const render = await insertProxyRender(db, { ...project, projectId, version: versionRef(head), label: 'ord', run })

    // The workspace read: the format is the ratio of the only output the head Version seals.
    const workspace = await new PrismaProjectWorkspaceQueryRepository(db).read(scope)
    assert.equal(workspace.project.format, '4:5')
    assert.equal(workspace.reviewAvailability.annotations.state, 'available')

    // The review preview and an annotation: the same ratio, and a critic seal of the exact Version, State and variant.
    const annotations = new PrismaReviewAnnotationRepository(db)
    const preview = await annotations.readPreviewContext(scope)
    assert.equal(preview.formatId, '4:5')
    assert.equal(preview.availableScopeCounts.formats, 1)
    assert.equal(preview.outputConsumption.seal.purpose, 'critic')
    assert.equal(preview.outputConsumption.seal.projectVersionId, head.version.id)
    assert.equal(preview.outputConsumption.seal.outputStateHash, head.state.stateHash)
    assert.equal(preview.outputConsumption.seal.variantId, project.world.variantId)
    assert.deepEqual((await annotations.readPreviewContext({ ...scope, variantId: project.world.variantId })).outputConsumption, preview.outputConsumption)
    await assert.rejects(() => annotations.readPreviewContext({ ...scope, variantId: 'no-such-variant' }), refused('output-variant-unknown'))
    const created = await createProjectReviewAnnotationService({ repository: annotations, clock: () => new Date(), createId: randomUUID })(annotationInput(project, preview, `w66rd-${run}-annotation`))
    assert.equal(created.replayed, false)
    assert.equal(created.annotation.projectVersionId, head.version.id)

    // The sidecar aligns that render, for the ratio the sealed entry carries and for no other.
    const sidecars = new PrismaSubtitleSidecarRepository(db)
    const alignment = await sidecars.readRenderedAlignment({ ...scope, variantId: '4:5' })
    assert.equal(alignment.outputKind, 'proxy')
    assert.equal(alignment.outputArtifactId, render.artifactId)
    assert.equal(alignment.projectVersionId, head.version.id)
    assert.equal(alignment.outputConsumption.render.seal.purpose, 'render')
    assert.equal(alignment.outputConsumption.render.seal.variantId, project.world.variantId)
    assert.equal(await sidecars.readRenderedAlignment({ ...scope, variantId: '16:9' }), null)
    assert.equal((await sidecars.readRenderedAlignment({ ...scope, variantId: '4:5', stateVariantId: project.world.variantId })).outputArtifactId, render.artifactId)
    await assert.rejects(() => sidecars.readRenderedAlignment({ ...scope, variantId: '4:5', stateVariantId: 'no-such-variant' }), refused('output-variant-unknown'))

    // The quality iteration context: the format of the sealed output of the reviewed Version, sealed for critic.
    const quality = new PrismaQualityIterationRepository(db)
    const qualityInput = { ...scope, projectVersionId: head.version.id, proxyReviewId: render.reviewId, assetSelectionIds: [] }
    const context = await quality.readContext(qualityInput)
    assert.equal(context.format, '4:5')
    assert.equal(context.projectVersionId, head.version.id)
    assert.equal(context.outputConsumption.seal.purpose, 'critic')
    assert.equal(context.outputConsumption.seal.outputStateId, head.state.document.id)
    await assert.rejects(() => quality.readContext({ ...qualityInput, variantId: 'no-such-variant' }), refused('output-variant-unknown'))

    // An older Version answers about itself, never about the head that superseded it.
    const child = await commitSealedChild(db, { workspaceId, projectId, actor: project.actor, suffix: `w66rd-${run}-ord-child` })
    assert.equal((await db.v2Project.findUniqueOrThrow({ where: { id: projectId } })).currentVersionId, child.version.id)
    const older = await annotations.readPreviewContext({ ...scope, projectVersionId: head.version.id })
    assert.equal(older.projectVersionId, head.version.id)
    assert.equal(older.currentProjectVersionId, child.version.id)
    assert.equal(older.stale, true)
    assert.equal(older.outputConsumption.seal.projectVersionId, head.version.id)
    assert.equal(older.outputConsumption.seal.outputStateHash, head.state.stateHash)
    const olderAlignment = await sidecars.readRenderedAlignment({ ...scope, variantId: '4:5', projectVersionId: head.version.id })
    assert.equal(olderAlignment.projectVersionId, head.version.id)
    assert.equal(olderAlignment.isCurrentVersion, false)
    assert.equal(olderAlignment.outputConsumption.render.seal.projectVersionId, head.version.id)
    assert.equal((await quality.readContext(qualityInput)).projectVersionId, child.version.id, 'the context names the head so the request is told it is stale')

    // A Version of another project, or of another workspace, is not answered.
    const sibling = await seedReviewProject(db, { workspaceId, actor: project.actor, prefix: 'w66rd-sib', ids: { project: `w66rd-${run}-sib-project` },
      name: 'Readers sibling', aspectRatio: '9:16' })
    await assert.rejects(() => requirePersistedOutputConsumptionV3(db, { ...scope, versionId: sibling.head.version.id, purpose: 'critic' }), refused('output-version-missing'))
    assert.equal(await sidecars.readRenderedAlignment({ ...scope, variantId: '4:5', projectVersionId: sibling.head.version.id }), null)
    const sister = await ordinaryProject(db, { run, tag: 'sis', aspectRatio: '9:16' })
    assert.equal(await annotations.readPreviewContext({ ...scope, projectVersionId: sister.head.version.id }), null)
    assert.equal(await sidecars.readRenderedAlignment({ ...scope, variantId: '4:5', projectVersionId: sister.head.version.id }), null)
    await assert.rejects(() => requirePersistedOutputConsumptionV3(db, { ...scope, versionId: sister.head.version.id, purpose: 'critic' }), refused('output-version-missing'))
    await assert.rejects(() => requirePersistedOutputConsumptionV3(db, { workspaceId: sister.workspaceId, projectId, versionId: head.version.id, purpose: 'critic' }),
      refused('output-version-missing'))
    assert.equal(await annotations.readPreviewContext({ workspaceId: sister.workspaceId, projectId }), null)
    assert.equal((await new PrismaProjectWorkspaceQueryRepository(db).read(sister.scope)).project.format, '9:16', 'each project is read through its own State')
  } finally { await db.$disconnect() }
})

test('W66 PostgreSQL readers: a copy no editorial cut materialized is refused with the published reason, and still shown with its format', { skip: !enabled, timeout: 280_000 }, async () => {
  const run = randomUUID().replaceAll('-', '').slice(0, 10)
  const db = new PrismaClient()
  try {
    const project = await ordinaryProject(db, { run, tag: 'cpy', aspectRatio: '4:5' })
    const { workspaceId, clientId, actor, head } = project
    let copyAllocations = 0
    const copy = await duplicateProjectService({ repository: new PrismaProjectDuplicationRepository(db), clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => kind === 'project-media-asset' ? randomUUID() : `w66rd-${run}-copy-${kind}-${++copyAllocations}` })({
      workspaceId, projectId: project.projectId, expectedVersionId: head.version.id, expectedVersionHash: head.version.baseHash, name: 'Readers copy', actor,
      idempotency: { clientId, key: `w66rd-${run}-dup` } })
    const copyScope = { workspaceId, projectId: copy.project.id }
    let childAllocations = 0
    const configured = await setProjectLutSelectionService({ repository: new PrismaProjectLutSelectionRepository(db), clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => `w66rd-${run}-copy-child-${kind}-${++childAllocations}` })({ ...copyScope, baseVersionId: copy.version.id, baseHash: copy.version.baseHash,
      selection: { mode: 'none' }, actor, idempotencyKey: `w66rd-${run}-copy-lut`, reason: 'Configuration of a copy.' })

    const annotations = new PrismaReviewAnnotationRepository(db)
    const sidecars = new PrismaSubtitleSidecarRepository(db)
    const quality = new PrismaQualityIterationRepository(db)
    // The copy's head is the configuration child (every entry blocked); the Creation fork root before it is blocked too.
    for (const [label, versionId] of [['fork root', copy.version.id], ['configuration child', configured.version.id]]) {
      for (const purpose of ['render', 'critic', 'final']) {
        await assert.rejects(() => requirePersistedOutputConsumptionV3(db, { ...copyScope, versionId, purpose }), refused('copy-requires-editorial-cut'), `${label}/${purpose}`)
      }
      await assert.rejects(() => annotations.readPreviewContext({ ...copyScope, projectVersionId: versionId }), refused('copy-requires-editorial-cut'), `${label}/preview`)
      await assert.rejects(() => sidecars.readRenderedAlignment({ ...copyScope, variantId: '4:5', projectVersionId: versionId }), refused('copy-requires-editorial-cut'), `${label}/sidecar`)
    }
    await assert.rejects(() => annotations.readPreviewContext(copyScope), refused('copy-requires-editorial-cut'))

    // The annotation: the use case reads the preview first; the repository's own gate refuses a write for the same Version.
    await assert.rejects(() => createProjectReviewAnnotationService({ repository: annotations, clock: () => new Date(), createId: randomUUID })(
      annotationInput({ ...project, ...copyScope }, { projectVersionId: configured.version.id, proxyArtifactId: 'x', proxyHash: 'a'.repeat(64) }, `w66rd-${run}-copy-annotation`)),
    refused('copy-requires-editorial-cut'))
    const annotationsBefore = await db.v2ReviewAnnotation.count({ where: copyScope })
    await assert.rejects(() => annotations.create({ ...copyScope, idempotencyKey: `w66rd-${run}-copy-gate`, requestFingerprint: 'f'.repeat(64),
      annotation: { projectVersionId: configured.version.id, proxyArtifactId: 'x', proxyHash: 'a'.repeat(64), authenticationAudit: { contextHash: 'c'.repeat(64) } } }),
    refused('copy-requires-editorial-cut'))
    assert.equal(await db.v2ReviewAnnotation.count({ where: copyScope }), annotationsBefore, 'the refusal wrote nothing')

    // The quality iteration: evidence stored for the copy's Version is not scored while the copy has no target authority.
    const render = await insertProxyRender(db, { workspaceId, clientId, projectId: copy.project.id, version: versionRef(await new PrismaOperationalOutputBundleRepositoryV3(db)
      .read({ ...copyScope, versionId: configured.version.id })), source: project.source, label: 'cpy', run })
    await assert.rejects(() => quality.readContext({ ...copyScope, projectVersionId: configured.version.id, proxyReviewId: render.reviewId, assetSelectionIds: [] }),
      refused('copy-requires-editorial-cut'))

    // The workspace describes the copy with the format it was copied with; it does not require the output to be consumable.
    const workspace = await new PrismaProjectWorkspaceQueryRepository(db).read(copyScope)
    assert.equal(workspace.project.format, '4:5')
    assert.equal(workspace.project.currentVersionId, configured.version.id)
  } finally { await db.$disconnect() }
})

