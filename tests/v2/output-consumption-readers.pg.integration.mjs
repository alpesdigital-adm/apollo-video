/**
 * The readers that critique or describe the output of a Version take their verdict from the one persisted consumption reader, against
 * a real PostgreSQL. Code for a SUPERVISED run (isolated database, migrated and generated by the owner); every identity is unique to
 * this invocation and nothing is cleaned up (sealed rows are append-only).
 *
 *   1. An ordinary project with one output (4:5): the workspace read shows `project.format` = '4:5', the review preview carries the
 *      same `formatId` and a `critic` seal of the exact Version/State/variant, an annotation persists, the sidecar aligns the render
 *      evidence of that output (and only for the ratio it carries), the quality iteration context carries the same format, and an
 *      older Version answers about itself (stale) while a Version of another project or workspace is not answered.
 *   2. Its copy that no editorial cut has materialized (the Creation fork root, and a configuration child): every reader refuses with the
 *      published `copy-requires-editorial-cut`, while the workspace still shows the copy with the format it was copied with.
 *   3. A Director project's copy after its editorial cut: render and critic are admitted (the preview, an annotation, the quality
 *      context, the sidecar of its proxy), and the final stays blocked with `derived-source-perception-authority-required`.
 */
const enabled = process.env.APOLLO_RUN_W66_CONSUMPTION_READERS_PG === '1'
const refused = (reason) => (error) => error?.code === 'PRECONDITION_REQUIRED' && error.details.reason === reason

/**
 * What a proxy render leaves for a Version, the way `prisma-workspace-review-availability` writes it: the output artifact and its
 * manifest, the succeeded render operation, its detail row, the RenderElementMap of the output and a proxy review. Controlled rows,
 * no rendered pixels.
 */
async function insertProxyRender(db, { workspaceId, clientId, projectId, version, source, label, run }) {
  const at = new Date()
  const audit = createApiAccessAuditContext({ clientId, credentialId: `${clientId}-credential`, workspaceId, environment: 'production', authenticationKind: 'bearer' })
  const id = `w66rd-${run}-${label}`, artifactId = `${id}-proxy`, manifestId = `${id}-proxy-manifest`, operationId = `${id}-operation`, reviewId = `${id}-review`
  const sha256 = hash({ artifactId })
  const manifest = createMediaArtifactManifest({ artifactKey: `controlled-readers/${run}/${label}.mp4`, artifactSha256: sha256, byteSize: 4096, mediaType: 'video',
    container: 'mp4', recipe: { id: 'editorial-proxy', version: '1.0.0', parameters: { label, run } }, probe: { width: 540, height: 960, duration: 2, fps: 30 } })
  await db.v2MediaArtifact.create({ data: { id: artifactId, workspaceId, artifactKey: manifest.artifact.artifactKey, sha256, byteSize: 4096n, mediaType: 'video',
    container: 'mp4', status: 'available', createdAt: at } })
  await db.v2MediaArtifactManifest.create({ data: { id: manifestId, workspaceId, artifactId, schemaVersion: manifest.schemaVersion, manifestHash: manifest.manifestHash,
    recipeId: manifest.recipe.id, recipeVersion: manifest.recipe.version, parametersHash: manifest.recipe.parametersHash, manifestJson: stableSerialize(manifest), createdAt: at } })
  const inputHash = hash({ operationId, versionId: version.id })
  // Explicit controlled references: the stored binding syntax a render leaves, no compiled pixels.
  const binding = { sourceArtifactId: source.artifactId, sourceManifestId: source.manifestId, compilationId: `controlled-color-${operationId}`,
    compilationHash: hash({ operationId, kind: 'compilation' }), pipelineHash: hash({ operationId, kind: 'pipeline' }) }
  await db.v2PublicOperation.create({ data: { id: operationId, workspaceId, projectId, clientId, actorCredentialId: audit.credentialId, actorEnvironment: audit.environment,
    actorAuthenticationKind: audit.authenticationKind, actorContextHash: audit.contextHash, type: 'project-proxy-render', status: 'succeeded', phase: 'completed',
    targetType: 'media-artifact', targetId: artifactId, progressCompleted: 4, progressTotal: 4, progressUnit: 'render', cancelable: false, retryable: false, attempt: 1,
    maxAttempts: 3, idempotencyKey: `${operationId}-request`, requestFingerprint: inputHash, createdAt: at, updatedAt: at, startedAt: at, completedAt: at,
    resultJson: stableSerialize({ resource: { type: 'media-artifact', id: artifactId, manifestId } }) } })
  await db.v2ProjectProxyRenderOperation.create({ data: { operationId, workspaceId, projectId, projectVersionId: version.id, editPlanSnapshotId: version.editPlanSnapshotId,
    sourceArtifactId: source.artifactId, sourceManifestId: source.manifestId, colorPipelineBindingsJson: stableSerialize([binding]), inputHash, outputArtifactId: artifactId,
    outputManifestId: manifestId, originalFileName: `${label}.mp4`, createdAt: at } })
  // The project links the proxy the way the worker does, which is what a review annotation checks before it is written.
  await db.v2ProjectMediaAsset.create({ data: { id: randomUUID(), workspaceId, projectId, artifactId, role: 'editorial-proxy', originalFileName: `${label}.mp4`, createdAt: at } })
  const map = validateRenderElementMap({ schemaVersion: 'render-element-map/v1', proxyHash: sha256, fps: 30, durationFrames: 60, canvas: { width: 540, height: 960 }, elements: [] }, sha256)
  await db.v2RenderElementMap.create({ data: { id: randomUUID(), workspaceId, projectId, projectVersionId: version.id, proxyArtifactId: artifactId, proxyHash: sha256,
    mapHash: renderElementMapHash(map), schemaVersion: map.schemaVersion, fps: map.fps, durationFrames: map.durationFrames, canvasWidth: 540, canvasHeight: 960,
    elementsJson: '[]', createdAt: at } })
  const body = { schemaVersion: 'proxy-review/v1', projectVersionId: version.id, proxyArtifactId: artifactId, proxyManifestId: manifestId, inputHash,
    outputSpecId: 'proxy-review-readers-1', rangeCacheKey: hash({ operationId, range: true }),
    spec: { width: 540, height: 960, codec: 'h264', container: 'mp4', quality: 'review', reusableRanges: true }, status: 'ready-for-final', technicalIssues: [],
    criticIssues: [], warningsAcknowledged: false, finalAllowed: true, uploadReceivedAt: at.toISOString(), renderCompletedAt: at.toISOString(), timeToFirstProxyMs: 2_000 }
  await db.v2ProxyReview.create({ data: { id: reviewId, workspaceId, projectId, projectVersionId: version.id, operationId, proxyArtifactId: artifactId,
    proxyManifestId: manifestId, inputHash, outputSpecId: body.outputSpecId, rangeCacheKey: body.rangeCacheKey, specJson: stableSerialize(body.spec), status: body.status,
    technicalIssuesJson: '[]', criticIssuesJson: '[]', warningsAcknowledged: false, finalAllowed: true, reviewHash: calculateProxyReviewHash(body), revision: 1,
    uploadReceivedAt: at, renderCompletedAt: at, timeToFirstProxyMs: 2_000n, createdAt: at, updatedAt: at } })
  return Object.freeze({ artifactId, manifestId, operationId, reviewId })
}

const versionRef = (bundle) => ({ id: bundle.version.id, editPlanSnapshotId: bundle.editPlanSnapshot.id })

/** One project with one explicit output variant (`aspectRatio`) whose head plays one observed recording: a consumable output. */
async function ordinaryProject(db, { run, tag, aspectRatio }) {
  const workspaceId = `w66rd-${run}-${tag}-ws`, clientId = `w66rd-${run}-${tag}-client`
  const actor = testActor({ workspaceId, clientId, credentialId: `${clientId}-credential`, environment: 'production', scopes: ['projects:write', 'projects:read', 'media:write'] })
  const world = await seedReviewProject(db, { workspaceId, actor, prefix: `w66rd-${tag}`, ids: { project: `w66rd-${run}-${tag}-project` }, name: `Readers ${tag}`,
    aspectRatio, status: 'reviewing-proxy' })
  const recording = await persistRecording(db, { workspaceId, projectId: world.projectId, actor, slug: `w66rd-${run}-${tag}-recording` })
  const head = await commitSealedChild(db, { workspaceId, projectId: world.projectId, actor, suffix: `w66rd-${run}-${tag}-ingested`,
    mutatePlan: planPlayingRecordings([recording]), adopt: [recording.names.sourceArtifactId] })
  const source = { artifactId: recording.names.sourceArtifactId, manifestId: recording.names.sourceManifestId }
  return { workspaceId, clientId, actor, world, recording, head, source, projectId: world.projectId, scope: { workspaceId, projectId: world.projectId } }
}

