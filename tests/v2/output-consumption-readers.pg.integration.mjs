test('W66 PostgreSQL readers: a cut copy is critiqued and rendered, and its final export stays blocked', { skip: !enabled, timeout: 280_000 }, async () => {
  const run = randomUUID().replaceAll('-', '').slice(0, 10)
  const workspaceId = `w66rdcut-${run}-ws`, clientId = `w66rdcut-${run}-client`
  const actor = testActor({ workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production', scopes: ['projects:write', 'projects:read', 'media:write'] })
  const db = new PrismaClient()
  try {
    const world = await seedSealedProject(db, { workspaceId, actor, prefix: 'w66rdcut', ids: { project: `w66rdcut-${run}-project` }, name: 'Readers cut world' })
    const directed = await seedDirectedProject(db, { workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production', projectId: world.projectId,
      suffix: `w66rdcut${run}`, words: WORDS })
    const operational = new PrismaOperationalOutputBundleRepositoryV3(db)
    const head = await operational.read({ workspaceId, projectId: world.projectId, versionId: directed.versions.directed })
    const plan = JSON.parse(head.editPlanSnapshot.contentJson)
    let copyAllocations = 0
    const copy = await duplicateProjectService({ repository: new PrismaProjectDuplicationRepository(db), clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => kind === 'project-media-asset' ? randomUUID() : `w66rdcut-${run}-copy-${kind}-${++copyAllocations}` })({
      workspaceId, projectId: world.projectId, expectedVersionId: head.version.id, expectedVersionHash: head.version.baseHash, name: 'Readers cut copy', actor,
      idempotency: { clientId, key: `w66rdcut-${run}-dup` } })
    const copyScope = { workspaceId, projectId: copy.project.id }
    let childAllocations = 0
    const configured = await setProjectLutSelectionService({ repository: new PrismaProjectLutSelectionRepository(db), clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => `w66rdcut-${run}-child-${kind}-${++childAllocations}` })({ ...copyScope, baseVersionId: copy.version.id, baseHash: copy.version.baseHash,
      selection: { mode: 'none' }, actor, idempotencyKey: `w66rdcut-${run}-lut`, reason: 'Configuration of a copy.' })
    const configuredBundle = await operational.read({ ...copyScope, versionId: configured.version.id })
    let allocations = 0
    const cut = await applyEditorialCutCommandService({ repository: new PrismaEditorialCommandRepository(db), clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => `w66rdcut-${run}-${kind}-${++allocations}` })({ ...copyScope, baseVersionId: configuredBundle.version.id, baseHash: configuredBundle.version.baseHash,
      sourceTranscriptId: plan.retimedTranscript.sourceTranscriptId, variantId: configuredBundle.state.document.entries[0].variantId,
      rules: [{ id: 'termina', label: 'termina', alternatives: ['termina'] }],
      exclusionOverrides: [{ sourceStartSeconds: 1.1, sourceEndSeconds: 2.0, ruleIds: ['termina'], reason: 'The reviewer cuts "termina aqui." and keeps the rest.' }],
      reason: 'Cut a copy for the readers.', actor, idempotency: { clientId, key: `w66rdcut-${run}-cut` } })
    const versionId = cut.version.id

    // The verdict: a cut copy is consumable to render and critic; the final export waits for the target's own perception authority.
    const ratio = outputEntryAspectRatio(head.state.document.entries[0])
    for (const purpose of ['render', 'critic']) {
      const admitted = await requirePersistedOutputConsumptionV3(db, { ...copyScope, versionId, purpose })
      assert.equal(admitted.aspectRatio, ratio, purpose)
      assert.equal(admitted.entry.consumption.materialization.document.schemaVersion, 'editorial-derived-materialization/v1', purpose)
    }
    await assert.rejects(() => requirePersistedOutputConsumptionV3(db, { ...copyScope, versionId, purpose: 'final' }), refused('derived-source-perception-authority-required'))

    // The workspace shows the cut copy with its format.
    const workspace = await new PrismaProjectWorkspaceQueryRepository(db).read(copyScope)
    assert.equal(workspace.project.format, ratio)
    assert.equal(workspace.project.currentVersionId, versionId)

    // A proxy render of the cut Version, over a source the copy links.
    const sourceLink = await db.v2ProjectMediaAsset.findFirstOrThrow({ where: { ...copyScope, role: 'source-master' } })
    const sourceManifest = await db.v2MediaArtifactManifest.findFirstOrThrow({ where: { workspaceId, artifactId: sourceLink.artifactId }, orderBy: { createdAt: 'asc' } })
    const render = await insertProxyRender(db, { workspaceId, clientId, projectId: copy.project.id, version: versionRef(await operational.read({ ...copyScope, versionId })),
      source: { artifactId: sourceLink.artifactId, manifestId: sourceManifest.id }, label: 'cut', run })

    // The review preview and an annotation read the cut copy as a project like any other, and the seal names the cut Version.
    const annotations = new PrismaReviewAnnotationRepository(db)
    const preview = await annotations.readPreviewContext(copyScope)
    assert.ok(preview, 'the cut copy has a proxy to review')
    assert.equal(preview.formatId, ratio)
    assert.equal(preview.outputConsumption.seal.purpose, 'critic')
    assert.equal(preview.outputConsumption.seal.projectVersionId, versionId)
    const created = await createProjectReviewAnnotationService({ repository: annotations, clock: () => new Date(), createId: randomUUID })(
      annotationInput({ ...copyScope, actor }, preview, `w66rdcut-${run}-annotation`))
    assert.equal(created.annotation.projectVersionId, versionId)

    // The sidecar aligns the proxy of the cut copy, and the quality context is sealed for critic.
    const alignment = await new PrismaSubtitleSidecarRepository(db).readRenderedAlignment({ ...copyScope, variantId: ratio })
    assert.equal(alignment.outputKind, 'proxy')
    assert.equal(alignment.outputArtifactId, render.artifactId)
    assert.equal(alignment.outputConsumption.render.seal.projectVersionId, versionId)
    const context = await new PrismaQualityIterationRepository(db).readContext({ ...copyScope, projectVersionId: versionId, proxyReviewId: render.reviewId, assetSelectionIds: [] })
    assert.equal(context.format, ratio)
    assert.equal(context.outputConsumption.seal.projectVersionId, versionId)
  } finally { await db.$disconnect() }
})
