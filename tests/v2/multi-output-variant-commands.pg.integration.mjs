import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import test from 'node:test'

import { PrismaClient } from '../../generated/prisma-v2/index.js'
import { setProjectSubtitleConfigurationService } from '../../src/v2/application/project-subtitle-configurations.ts'
import { createProjectReviewAnnotationService } from '../../src/v2/application/review-project.ts'
import { applySubtitleSegmentOverrideService } from '../../src/v2/application/subtitle-segment-overrides.ts'
import { readPersistedOperationalOutputBundleV3 } from '../../src/v2/infrastructure/prisma/output-state-consumption.ts'
import { PrismaProjectSubtitleConfigurationRepository } from '../../src/v2/infrastructure/prisma/project-subtitle-configuration-repository.ts'
import { PrismaProjectWorkspaceQueryRepository } from '../../src/v2/infrastructure/prisma/project-workspace-query-repository.ts'
import { PrismaReviewAnnotationRepository } from '../../src/v2/infrastructure/prisma/review-annotation-repository.ts'
import { PrismaSubtitleSegmentOverrideRepository } from '../../src/v2/infrastructure/prisma/subtitle-segment-override-repository.ts'
import { PrismaSubtitleSidecarRepository } from '../../src/v2/infrastructure/prisma/subtitle-sidecar-repository.ts'
import { insertOutputRender, seedTwoOutputSubtitleProject } from './helpers/m3-multi-output-pg-world.mjs'
import { testActor } from './helpers/pg-output-world.mjs'
import { untouchedFacts } from './helpers/m3-two-output-world.mjs'

/**
 * Variant-specific Commands and readers on a project with TWO outputs (9:16 and 16:9), against a real PostgreSQL (slice S3,
 * workstream 3). Code for a SUPERVISED run (isolated database, migrated and generated by the owner); every identity is unique to this
 * invocation and nothing is cleaned up (sealed rows are append-only).
 *
 * Every request names the output by its STABLE State variant id, never an aspect ratio. It proves, on the real repositories:
 *   1. A segment override on the 9:16 output lists only the 9:16 renders in its impact, and the 16:9 entry keeps its output spec
 *      revision, spec hash and geometry byte-identical in the child State (its materialization is re-bound to the new Version, as in
 *      every child).
 *   2. The same for a subtitle configuration on the 16:9 output (the 9:16 entry is the untouched one), and its head is per output.
 *   3. An unknown variant (and an aspect ratio, the old spelling) and a missing one are refused with their published reasons, and a
 *      refused Command writes nothing (the head does not move).
 *   4. The sidecar of each output aligns the render made for that output; the review preview takes the render of the requested output
 *      (the other output's older render makes only that preview stale); an annotation critiques the output it names and its scope holds
 *      stable variant ids.
 *   5. The workspace read lists both outputs with their verdicts and no single project format.
 */
const enabled = process.env.APOLLO_RUN_W66_MULTI_OUTPUT_VARIANT_PG === '1'
const refusal = (reason) => (error) => error?.code === 'PRECONDITION_REQUIRED' && error.details?.reason === reason
const ids = (run, tag) => (kind) => `m3-${run}-${tag}-${kind}-${randomUUID()}`
const SCREENSHOT = 'data:image/jpeg;base64,/9j/2Q=='

test('W66 PostgreSQL variant-specific Commands and readers act on the output they name', { skip: !enabled, timeout: 280_000 }, async () => {
  const run = randomUUID().replaceAll('-', '').slice(0, 10)
  const workspaceId = `m3mo-${run}-ws`, clientId = `m3mo-${run}-client`
  const actor = testActor({ workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production', scopes: ['projects:write', 'projects:read', 'media:write'] })
  const db = new PrismaClient()
  try {
    const world = await seedTwoOutputSubtitleProject(db, { workspaceId, actor, prefix: 'm3mo', run, ids: { project: `m3mo-${run}-project` } })
    const { projectId, wideVariantId: WIDE, verticalVariantId: VERTICAL } = world
    const scope = { workspaceId, projectId }
    const source = { artifactId: world.recording.names.sourceArtifactId, manifestId: world.recording.names.sourceManifestId }
    const versionRow = async (versionId) => db.v2ProjectVersion.findUniqueOrThrow({ where: { id: versionId } })
    const render = async (versionId, outputVariantId, label) => insertOutputRender(db, { ...scope, clientId, version: await versionRow(versionId), source, outputVariantId, label: `${label}-${run}`, run })
    const headId = async () => (await db.v2Project.findUniqueOrThrow({ where: { id: projectId } })).currentVersionId
    const bundleOf = async (versionId) => readPersistedOperationalOutputBundleV3(db, { ...scope, versionId })
    const H1 = world.head
    assert.equal(H1.state.document.entries.length, 2)
    assert.equal(await headId(), H1.version.id)

    // ---- 1. a segment override on the 9:16 output
    const R1 = { wide: await render(H1.version.id, WIDE, 'h1wide'), vertical: await render(H1.version.id, VERTICAL, 'h1vertical') }
    const overrides = applySubtitleSegmentOverrideService({ repository: new PrismaSubtitleSegmentOverrideRepository(db), createId: ids(run, 'ovr'), clock: () => new Date() })
    const override = await overrides({ ...scope, baseVersionId: H1.version.id, baseHash: H1.version.baseHash, variantId: VERTICAL, segmentId: 'cue-hook',
      dimensions: [{ kind: 'position', anchor: 'top' }], actor, idempotencyKey: `m3mo-${run}-override-1` })
    assert.equal(override.subtitleOverride.variantId, VERTICAL, 'the exception names the stable variant')
    assert.deepEqual(override.command.scope.outputVariantIds, [VERTICAL])
    assert.deepEqual(override.impact.affectedArtifacts.map((item) => [item.artifactId, item.variantId]), [[R1.vertical.artifactId, VERTICAL]], 'only the 9:16 render is stale')
    assert.deepEqual([...override.impact.affectedVariantIds], [VERTICAL])
    assert.equal(await headId(), override.version.id)
    const H2 = await bundleOf(override.version.id)
    assert.deepEqual(untouchedFacts(H2, WIDE), untouchedFacts(H1, WIDE), 'the 16:9 entry is byte-identical in revision, spec and geometry')
    assert.deepEqual(untouchedFacts(H2, VERTICAL), untouchedFacts(H1, VERTICAL), 'a subtitle exception changes no output spec')
    assert.equal(H2.state.document.entries.find((entry) => entry.variantId === WIDE).consumption.materialization.document.resultVersionId, H2.version.id, 're-bound to the new Version')
    const overrideRepository = new PrismaSubtitleSegmentOverrideRepository(db)
    assert.equal((await overrideRepository.listCurrentByVariant({ ...scope, variantId: VERTICAL })).length, 1)
    assert.equal((await overrideRepository.listCurrentByVariant({ ...scope, variantId: WIDE })).length, 0, 'the 16:9 output has no exception')

    // ---- 3. refusals (before the next Command): nothing is written
    const refuse = (promise, reason) => assert.rejects(() => promise, refusal(reason))
    await refuse(overrides({ ...scope, baseVersionId: H2.version.id, baseHash: H2.version.baseHash, variantId: `${VERTICAL}-stranger`, segmentId: 'cue-hook',
      dimensions: [{ kind: 'position', anchor: 'top' }], actor, idempotencyKey: `m3mo-${run}-override-stranger` }), 'output-variant-unknown')
    await refuse(overrides({ ...scope, baseVersionId: H2.version.id, baseHash: H2.version.baseHash, variantId: '9:16', segmentId: 'cue-hook',
      dimensions: [{ kind: 'position', anchor: 'top' }], actor, idempotencyKey: `m3mo-${run}-override-ratio` }), 'output-variant-unknown')
    assert.equal(await headId(), H2.version.id, 'a refused variant writes nothing')

    // ---- 2. a subtitle configuration on the 16:9 output
    const R2 = { wide: await render(H2.version.id, WIDE, 'h2wide'), vertical: await render(H2.version.id, VERTICAL, 'h2vertical') }
    const configure = setProjectSubtitleConfigurationService({ repository: new PrismaProjectSubtitleConfigurationRepository(db), createId: ids(run, 'cfg'), clock: () => new Date() })
    const configuredRequest = { ...scope, baseVersionId: H2.version.id, baseHash: H2.version.baseHash, action: 'set', requested: { mode: 'none' }, actor }
    await refuse(configure({ ...configuredRequest, variantId: '16:9', idempotencyKey: `m3mo-${run}-cfg-ratio` }), 'output-variant-unknown')
    await assert.rejects(() => configure({ ...configuredRequest, variantId: '', idempotencyKey: `m3mo-${run}-cfg-empty` }), (error) => error?.code === 'INVALID_ARGUMENT')
    assert.equal(await headId(), H2.version.id)
    const configured = await configure({ ...configuredRequest, variantId: WIDE, idempotencyKey: `m3mo-${run}-cfg-1` })
    assert.equal(configured.configuration.variantId, WIDE)
    assert.deepEqual(configured.command.scope.outputVariantIds, [WIDE])
    assert.deepEqual(configured.impact.affectedArtifacts.map((item) => [item.artifactId, item.variantId]), [[R2.wide.artifactId, WIDE]], 'only the 16:9 render is stale')
    assert.deepEqual([...configured.impact.affectedVariantIds], [WIDE])
    assert.deepEqual(configured.impact.minimalRenders.map((item) => item.variantId), [WIDE])
    const H3 = await bundleOf(configured.version.id)
    assert.deepEqual(untouchedFacts(H3, VERTICAL), untouchedFacts(H2, VERTICAL), 'the 9:16 entry is byte-identical in revision, spec and geometry')
    assert.deepEqual(untouchedFacts(H3, WIDE), untouchedFacts(H2, WIDE))
    const configurations = new PrismaProjectSubtitleConfigurationRepository(db)
    assert.equal((await configurations.readCurrent({ ...scope, variantId: WIDE })).configuration.id, configured.configuration.id)
    assert.equal(await configurations.readCurrent({ ...scope, variantId: VERTICAL }), null, 'the 9:16 output stays inherited')
    const replay = await configure({ ...configuredRequest, variantId: WIDE, idempotencyKey: `m3mo-${run}-cfg-1` })
    assert.equal(replay.replayed, true)

    // ---- 4a. the sidecar of each output aligns the render made for that output (both outputs have a render at H2)
    const sidecars = new PrismaSubtitleSidecarRepository(db)
    const wideAlignment = await sidecars.readRenderedAlignment({ ...scope, variantId: WIDE, projectVersionId: H2.version.id })
    const verticalAlignment = await sidecars.readRenderedAlignment({ ...scope, variantId: VERTICAL, projectVersionId: H2.version.id })
    assert.equal(wideAlignment.outputArtifactId, R2.wide.artifactId)
    assert.equal(verticalAlignment.outputArtifactId, R2.vertical.artifactId)
    assert.equal(wideAlignment.variantId, WIDE)
    assert.equal(verticalAlignment.variantId, VERTICAL)
    assert.equal(wideAlignment.outputConsumption.render.seal.variantId, WIDE)
    assert.notEqual(wideAlignment.outputConsumption.render.sealHash, verticalAlignment.outputConsumption.render.sealHash)
    assert.equal(wideAlignment.cueTexts['cue-hook'], 'O dono vira o gargalo')
    await refuse(sidecars.readRenderedAlignment({ ...scope, variantId: '16:9', projectVersionId: H2.version.id }), 'output-variant-unknown')
    // At the head (H3) neither output has a render yet: there is nothing to align, for either. Both outputs have a render of H2, which is
    // NOT the Version the head plays, so the answer is the precise one - the render is stale for this Version - not a borrowed alignment.
    for (const variantId of [WIDE, VERTICAL]) {
      await assert.rejects(sidecars.readRenderedAlignment({ ...scope, variantId }), (error) => error.code === 'SUBTITLE_SIDECAR_ALIGNMENT_MISMATCH' &&
        error.details.reason === 'render-stale' && error.details.renderedVersionId === H2.version.id && error.details.requestedVersionId === H3.version.id)
    }

    // ---- 4b. the review preview takes the render of the requested output; only the output with an older render is stale
    const R3 = { wide: await render(H3.version.id, WIDE, 'h3wide') }
    const annotations = new PrismaReviewAnnotationRepository(db)
    const widePreview = await annotations.readPreviewContext({ ...scope, variantId: WIDE })
    assert.equal(widePreview.proxyArtifactId, R3.wide.artifactId)
    assert.equal(widePreview.stale, false)
    assert.equal(widePreview.variantId, WIDE)
    assert.equal(widePreview.formatId, '16:9')
    assert.deepEqual([...widePreview.variantIds].toSorted(), [VERTICAL, WIDE].toSorted())
    assert.equal(widePreview.availableScopeCounts.formats, 2)
    assert.equal(widePreview.outputConsumption.seal.variantId, WIDE)
    const verticalPreview = await annotations.readPreviewContext({ ...scope, variantId: VERTICAL })
    assert.equal(verticalPreview.proxyArtifactId, R2.vertical.artifactId, 'the 9:16 preview is its own older render, not the 16:9 one')
    assert.equal(verticalPreview.stale, true)
    assert.equal(verticalPreview.sourceVersionId, H2.version.id)
    assert.equal(verticalPreview.formatId, '9:16')
    await refuse(annotations.readPreviewContext(scope), 'output-variant-required')
    await refuse(annotations.readPreviewContext({ ...scope, variantId: `${WIDE}-stranger` }), 'output-variant-unknown')
    await refuse(annotations.readPreviewContext({ ...scope, variantId: '9:16' }), 'output-variant-unknown')

    // ---- 4c. an annotation critiques the output it names; its format scope holds stable variant ids
    const annotate = createProjectReviewAnnotationService({ repository: annotations, clock: () => new Date(), createId: randomUUID })
    const annotationRequest = (preview, extra) => ({ ...scope, projectVersionId: preview.projectVersionId, proxyArtifactId: preview.proxyArtifactId, proxyHash: preview.proxyHash,
      frame: 0, timeRangeMs: [0, 0], screenshotRef: SCREENSHOT, scope: 'point', targetIds: [], text: 'Manter a legenda abaixo do rosto.', actor, ...extra })
    const created = await annotate(annotationRequest(widePreview, { variantId: WIDE, idempotencyKey: `m3mo-${run}-annotation-1` }))
    assert.deepEqual([...created.annotation.applicationScope.formatIds], [WIDE])
    assert.equal(created.annotation.proxyArtifactId, R3.wide.artifactId)
    const global = await annotate(annotationRequest(widePreview, { variantId: WIDE, idempotencyKey: `m3mo-${run}-annotation-2`,
      applicationScope: { kind: 'formats', global: true, formatIds: [WIDE, VERTICAL] }, confirmedGlobal: true }))
    assert.deepEqual([...global.annotation.applicationScope.formatIds].toSorted(), [VERTICAL, WIDE].toSorted())
    assert.equal(global.annotation.affectedCount, 2)
    await assert.rejects(() => annotate(annotationRequest(widePreview, { variantId: WIDE, idempotencyKey: `m3mo-${run}-annotation-3`,
      applicationScope: { kind: 'formats', global: true, formatIds: ['16:9'] }, confirmedGlobal: true })), (error) => error?.code === 'INVALID_SCOPE')
    // The 9:16 preview is stale (rendered from H2): the critique of that output is refused on its own, whatever the 16:9 output has.
    await assert.rejects(() => annotate(annotationRequest(verticalPreview, { variantId: VERTICAL, idempotencyKey: `m3mo-${run}-annotation-4` })), (error) => error?.code === 'VERSION_CONFLICT')
    // Naming none is refused for a project with several outputs; the proxy of one output is no preview of the other.
    await refuse(annotate(annotationRequest(widePreview, { idempotencyKey: `m3mo-${run}-annotation-5` })), 'output-variant-required')
    const listed = await annotations.list({ ...scope, projectVersionId: H3.version.id, limit: 20 })
    assert.equal(listed.length, 2)

    // ---- 5. the workspace read lists both outputs with their verdicts and no single format
    const workspace = await new PrismaProjectWorkspaceQueryRepository(db).read(scope)
    assert.equal('format' in workspace.project, false, 'two outputs have no single project format')
    assert.deepEqual(workspace.outputs.map((output) => [output.variantId, output.aspectRatio]).toSorted(), [[VERTICAL, '9:16'], [WIDE, '16:9']].toSorted())
    for (const output of workspace.outputs) {
      assert.deepEqual(output.consumption, { render: { status: 'allowed' }, critic: { status: 'allowed' }, final: { status: 'allowed' } }, output.variantId)
    }
    assert.equal(workspace.project.currentVersionId, H3.version.id)
  } finally { await db.$disconnect() }
})
