import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import test from 'node:test'

import { PrismaClient } from '../../generated/prisma-v2/index.js'
import { createProjectOutputVariantService } from '../../src/v2/application/create-project.ts'
import { listProjectsService } from '../../src/v2/application/list-projects.ts'
import { PrismaOperationalOutputBundleRepositoryV3 } from '../../src/v2/infrastructure/prisma/output-version-bundle-repository.ts'
import { PrismaProjectQueryRepository } from '../../src/v2/infrastructure/prisma/project-query-repository.ts'
import { variantBodyFor } from './helpers/explicit-project-http.mjs'
import { seedSealedProject, testActor } from './helpers/pg-output-world.mjs'

/**
 * apollo.projects.list 6.1.0 against a real PostgreSQL: the `format` facet finds a project by the aspect ratio of the outputs in
 * the State of its head Version, and still finds a row that stores that format itself. Code for a SUPERVISED run: isolated
 * database, migrated and generated by the owner. Sealed rows are append-only and every identity is unique to this invocation
 * (two workspaces of its own), so nothing is cleaned up and every answer below is scoped to those workspaces.
 *
 * What it proves:
 *   1. A project created without a format is found by its explicit output (9:16), and only by that ratio.
 *   2. A project with several outputs is found by any of them (16:9 and 1:1), through the State its head Version carries.
 *   3. A project whose Version carries no output is found by no ratio; a pre-6.0.0 row is found by the format it stores.
 *   4. Another workspace's projects with the same ratios never appear, in either direction.
 *   5. The facet composes with the keyset cursor (page by page the answer is the whole answer, once) and with the other facets.
 *   6. The answer equals an independent SQL oracle that reads the sealed spec through a jsonb path.
 */
const enabled = process.env.APOLLO_RUN_W66_PROJECT_LIST_FORMAT_PG === '1'

test('W66 PostgreSQL project list format facet reads the outputs of the head State', { skip: !enabled, timeout: 300_000 }, async () => {
  const run = randomUUID().replaceAll('-', '').slice(0, 12)
  const workspaceA = `w66fmt-${run}-a`, workspaceB = `w66fmt-${run}-b`
  const actorA = testActor({ workspaceId: workspaceA, clientId: `${workspaceA}-client` })
  const actorB = testActor({ workspaceId: workspaceB, clientId: `${workspaceB}-client` })
  const db = new PrismaClient()
  try {
    const list = listProjectsService({ projects: new PrismaProjectQueryRepository(db) })
    const ids = async (workspaceId, filters = {}, options = {}) =>
      (await list({ workspaceId, ...filters, ...options })).projects.map((project) => project.id)

    const seed = (workspaceId, actor, name, extra = {}) => seedSealedProject(db, {
      workspaceId, actor, prefix: `w66fmt-${run}`, name, objective: 'discovery', locale: 'pt-BR', ...extra,
    })
    const addVariant = async (world, workspaceId, actor, aspectRatio) => (await createProjectOutputVariantService({
      repository: new PrismaOperationalOutputBundleRepositoryV3(db), clock: () => new Date(), createId: world.createId, createEventId: randomUUID,
    })({
      ...variantBodyFor({ aspectRatio }), workspaceId, projectId: world.projectId, baseVersionId: world.head.version.id,
      baseHash: world.head.version.baseHash, actor, idempotencyKey: `${world.projectId}-${aspectRatio}-variant`,
    })).bundle

    // Workspace A. Names carry the intent; creation order is the order the list must give back (newest first).
    const nine = await seed(workspaceA, actorA, 'W66 fmt nine', { variant: variantBodyFor({ aspectRatio: '9:16' }) })
    const wide = await seed(workspaceA, actorA, 'W66 fmt wide')
    const multi = await seed(workspaceA, actorA, 'W66 fmt multi')
    const multiHead = await addVariant(multi, workspaceA, actorA, '1:1')
    const bare = await seed(workspaceA, actorA, 'W66 fmt bare', { variant: false })
    const wideTwo = await seed(workspaceA, actorA, 'W66 fmt wide two')
    // A row from before 6.0.0: it stores its format and has no Version at all (such a row is still insertable).
    const legacyId = `w66fmt-${run}-legacy`
    await db.v2Project.create({ data: {
      id: legacyId, workspaceId: workspaceA, name: 'W66 fmt legacy', status: 'draft', objective: 'sale', format: '4:5', locale: 'en-US',
      createdByType: 'api-client', createdById: actorA.clientId, createdAt: new Date(), updatedAt: new Date(),
    } })

    // Workspace B has projects with the same ratios; they must stay on their side.
    const otherNine = await seed(workspaceB, actorB, 'W66 fmt other nine', { variant: variantBodyFor({ aspectRatio: '9:16' }) })
    const otherWide = await seed(workspaceB, actorB, 'W66 fmt other wide')

    // The sealed world is what the facet reads: stored format null for every 6.0.0 project, the outputs in the head State.
    const stored = await db.v2Project.findMany({ where: { workspaceId: workspaceA }, select: { id: true, format: true, currentVersionId: true } })
    assert.equal(stored.length, 6)
    assert.deepEqual(stored.filter((row) => row.id !== legacyId).map((row) => row.format), [null, null, null, null, null])
    assert.equal(stored.find((row) => row.id === legacyId).format, '4:5')
    assert.equal(stored.find((row) => row.id === multi.projectId).currentVersionId, multiHead.version.id)
    assert.equal(multiHead.state.document.entries.length, 2, 'the head State of the multi-output project carries both outputs')
    const bareHead = await db.v2ProjectVersion.findUnique({
      where: { id: bare.head.version.id },
      select: { outputContractVersion: true, outputState: { select: { entries: { select: { variantId: true } } } } },
    })
    assert.equal(bareHead.outputContractVersion, 2, 'the creation Version is contract two')
    assert.deepEqual(bareHead.outputState.entries, [], 'and its State carries no output')

    // The expected order of any answer: createdAt desc, id desc, read from the rows (never assumed from creation order).
    const rows = await db.v2Project.findMany({ where: { workspaceId: workspaceA }, select: { id: true, createdAt: true } })
    const newestFirst = (members) => rows.filter((row) => members.includes(row.id))
      .sort((left, right) => right.createdAt.getTime() - left.createdAt.getTime() || (left.id < right.id ? 1 : left.id > right.id ? -1 : 0))
      .map((row) => row.id)

    assert.deepEqual(new Set(await ids(workspaceA)), new Set([nine, wide, multi, bare, wideTwo].map((world) => world.projectId).concat(legacyId)))

    // 1-3. The facet in workspace A.
    assert.deepEqual(await ids(workspaceA, { format: '9:16' }), [nine.projectId])
    assert.deepEqual(await ids(workspaceA, { format: '16:9' }), newestFirst([wide.projectId, multi.projectId, wideTwo.projectId]))
    assert.deepEqual(await ids(workspaceA, { format: '1:1' }), [multi.projectId])
    assert.deepEqual(await ids(workspaceA, { format: '4:5' }), [legacyId], 'a row that stores its format is still found by it')
    assert.deepEqual(await ids(workspaceA, { format: '21:9' }), [])
    for (const ratio of ['9:16', '16:9', '4:5', '1:1', '21:9']) {
      assert.equal((await ids(workspaceA, { format: ratio })).includes(bare.projectId), false, `a Version with no output is not found by ${ratio}`)
    }

    // 4. Isolation, both ways.
    assert.deepEqual(await ids(workspaceB, { format: '9:16' }), [otherNine.projectId])
    assert.deepEqual(await ids(workspaceB, { format: '16:9' }), [otherWide.projectId])
    assert.deepEqual(await ids(workspaceB, { format: '1:1' }), [])
    assert.deepEqual(await ids(workspaceB, { format: '4:5' }), [])
    for (const ratio of ['9:16', '16:9']) {
      const mine = await ids(workspaceA, { format: ratio })
      assert.equal(mine.includes(otherNine.projectId) || mine.includes(otherWide.projectId), false)
    }

    // 5. The keyset cursor and the facet each own an OR; one page at a time gives the whole answer, once.
    const wideAll = newestFirst([wide.projectId, multi.projectId, wideTwo.projectId])
    const paged = []
    let after
    for (let page = 0; page < 5; page += 1) {
      const answer = await list({ workspaceId: workspaceA, format: '16:9', limit: 1, ...(after ? { after } : {}) })
      paged.push(...answer.projects.map((project) => project.id))
      after = answer.nextCursor
      if (!after) break
    }
    assert.deepEqual(paged, wideAll)
    assert.equal(after, undefined, 'the last page carries no cursor')
    const firstPage = await list({ workspaceId: workspaceA, format: '16:9', limit: 2 })
    assert.deepEqual(firstPage.projects.map((project) => project.id), wideAll.slice(0, 2))
    assert.deepEqual(await ids(workspaceA, { format: '16:9' }, { limit: 2, after: firstPage.nextCursor }), wideAll.slice(2))
    await assert.rejects(() => ids(workspaceA, { format: '1:1' }, { limit: 2, after: firstPage.nextCursor }), /after does not match this project query/)

    // Composition with the other facets.
    assert.deepEqual(await ids(workspaceA, { format: '16:9', text: 'multi' }), [multi.projectId])
    assert.deepEqual(await ids(workspaceA, { format: '16:9', text: 'nine' }), [])
    assert.deepEqual(await ids(workspaceA, { format: '16:9', objective: 'discovery', locale: 'pt-BR', status: 'draft' }), wideAll)
    assert.deepEqual(await ids(workspaceA, { format: '4:5', objective: 'sale', locale: 'en-US' }), [legacyId])
    assert.deepEqual(await ids(workspaceA, { format: '4:5', objective: 'discovery' }), [])
    const lastCreated = rows.reduce((latest, row) => (row.createdAt > latest ? row.createdAt : latest), rows[0].createdAt)
    assert.deepEqual(await ids(workspaceA, { format: '16:9', createdFrom: new Date(lastCreated.getTime() + 1000).toISOString() }), [])
    assert.deepEqual(await ids(workspaceA, { format: '16:9', createdTo: lastCreated.toISOString() }), wideAll)
    // The date bounds are inclusive to the millisecond, as in the Prisma query every other facet uses.
    const wideCreatedAt = rows.find((row) => row.id === wide.projectId).createdAt
    const laterWide = wideAll.filter((id) => id !== wide.projectId)
    assert.deepEqual(await ids(workspaceA, { format: '16:9', createdTo: wideCreatedAt.toISOString() }), [wide.projectId])
    assert.deepEqual(await ids(workspaceA, { format: '16:9', createdFrom: wideCreatedAt.toISOString() }), wideAll)
    assert.deepEqual(await ids(workspaceA, { format: '16:9', createdFrom: new Date(wideCreatedAt.getTime() + 1).toISOString() }), laterWide)
    assert.deepEqual(await ids(workspaceA, { format: '16:9', createdTo: new Date(wideCreatedAt.getTime() - 1).toISOString() }), [])
    // The text facet reads the same way with and without the format facet: case-insensitive, wrapped in %, wildcards not escaped.
    assert.deepEqual(await ids(workspaceA, { text: 'FMT N_NE' }), [nine.projectId])
    assert.deepEqual(await ids(workspaceA, { text: 'FMT N_NE', format: '9:16' }), [nine.projectId])
    assert.deepEqual(await ids(workspaceA, { text: 'fmt w%e', format: '16:9' }), await ids(workspaceA, { text: 'fmt w%e' }).then((found) => found.filter((id) => wideAll.includes(id))))

    // 6. An independent oracle: the sealed spec of every output of the head State, read through a jsonb path.
    for (const workspaceId of [workspaceA, workspaceB]) {
      for (const ratio of ['9:16', '16:9', '4:5', '1:1', '21:9']) {
        const oracle = await db.$queryRawUnsafe(
          `SELECT p.id FROM projects p WHERE p."workspaceId" = $1 AND (p.format = $2 OR EXISTS (
             SELECT 1 FROM project_versions v
             JOIN project_output_state_entries e ON e."stateId" = v."outputStateId" AND e."projectId" = v."projectId" AND e."workspaceId" = v."workspaceId"
             JOIN output_spec_revisions r ON r.id = e."outputSpecRevisionId" AND r."variantId" = e."variantId" AND r."projectId" = e."projectId" AND r."workspaceId" = e."workspaceId"
             WHERE v.id = p."currentVersionId" AND v."projectId" = p.id AND v."workspaceId" = p."workspaceId"
               AND r."specJson"::jsonb #>> '{output,aspectRatio}' = $2))
           ORDER BY p."createdAt" DESC, p.id DESC`, workspaceId, ratio)
        assert.deepEqual(await ids(workspaceId, { format: ratio }), oracle.map((row) => row.id), `${workspaceId} ${ratio}: product answer vs SQL oracle`)
      }
    }
  } finally {
    await db.$disconnect()
  }
})
