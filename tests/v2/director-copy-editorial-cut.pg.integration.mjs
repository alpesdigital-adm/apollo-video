/**
 * A Director-planned project, and its copy, take an editorial cut that ends INSIDE a Director caption, against a real PostgreSQL.
 * Code for a SUPERVISED run (isolated database, migrated and generated by the owner); every identity is unique to this invocation and
 * nothing is cleaned up (sealed rows are append-only).
 *
 * What it proves:
 *   1. The real Director run names, for each caption cue it generated, the transcript words the cue is made of, in the ingest cue
 *      track shape (`source-transcript-cue-track/v1`, per-cue `sourceWordIndices`), from the observed transcript it read.
 *   2. A cut whose reviewed range ends inside the first cue ("Primeira frase termina aqui.") is admitted by the real service and the
 *      database guards, on the project itself and on its copy (a Creation fork over the Director Version), and what remains of the
 *      cue is rebuilt from the transcript words ("Primeira frase", indices [0, 1]); the second cue is untouched.
 *   0. Before any cut, the copy takes two LUT selections as children (it keeps the fork's posture: every entry blocked, nothing observed),
 *      refuses a new output with the published reason, and its cut still takes its authority from the Creation fork.
 *   3. Both Versions read back from PostgreSQL exactly as they were built (the factual reconstruction), and the copy's carries the
 *      Creation fork's authority.
 *   4. The cut copy takes the normal children: two LUT selections and a real Director re-run (which recompiles the plan and reads the
 *      transcript from the cut's binding), each materialized under that binding carried to it, each read back rebuilt from the original
 *      project's receipts, and the Director's captions still name their words after the re-run.
 */
const enabled = process.env.APOLLO_RUN_W66_DIRECTOR_COPY_CUT_PG === '1'

const WORDS = [
  { word: 'Primeira', start: 0.2, end: 0.7 }, { word: 'frase', start: 0.7, end: 1.1 },
  { word: 'termina', start: 1.1, end: 1.6 }, { word: 'aqui.', start: 1.6, end: 2.0 },
  { word: 'Segunda', start: 3.0, end: 3.5 }, { word: 'frase', start: 3.5, end: 3.9 },
  { word: 'continua', start: 3.9, end: 4.5 }, { word: 'ainda.', start: 4.5, end: 5.0 },
]

test('W66 PostgreSQL Director project and its copy take an editorial cut that ends inside a Director caption', { skip: !enabled, timeout: 280_000 }, async () => {
  const run = randomUUID().replaceAll('-', '').slice(0, 10)
  const workspaceId = `w66dcut-${run}-ws`, clientId = `w66dcut-${run}-client`
  const actor = testActor({ workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production', scopes: ['projects:write', 'projects:read', 'media:write'] })
  const db = new PrismaClient()
  try {
    const world = await seedSealedProject(db, { workspaceId, actor, prefix: 'w66dcut', ids: { project: `w66dcut-${run}-project` }, name: 'Director cut world' })
    const directed = await seedDirectedProject(db, { workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production',
      projectId: world.projectId, suffix: `w66dcut${run}`, words: WORDS })
    const operational = new PrismaOperationalOutputBundleRepositoryV3(db)
    const head = await operational.read({ workspaceId, projectId: world.projectId, versionId: directed.versions.directed })
    const plan = JSON.parse(head.editPlanSnapshot.contentJson)

    // 1. The Director's caption track names the transcript words of every cue.
    const [track] = plan.subtitleTracks
    assert.equal(track.schemaVersion, 'source-transcript-cue-track/v1')
    assert.equal(track.sourceTranscriptId, plan.retimedTranscript.sourceTranscriptId)
    assert.equal(track.sourceTranscriptHash, plan.retimedTranscript.sourceTranscriptHash)
    assert.deepEqual(track.cues.map((cue) => [cue.text, cue.sourceWordIndices]),
      [['Primeira frase termina aqui.', [0, 1, 2, 3]], ['Segunda frase continua ainda.', [4, 5, 6, 7]]])

    // The reviewed range: "termina aqui." only. It ends inside the first cue.
    const request = (projectId, base, label) => ({ workspaceId, projectId, baseVersionId: base.version.id, baseHash: base.version.baseHash,
      sourceTranscriptId: plan.retimedTranscript.sourceTranscriptId, variantId: base.state.document.entries[0].variantId,
      rules: [{ id: 'termina', label: 'termina', alternatives: ['termina'] }],
      exclusionOverrides: [{ sourceStartSeconds: 1.1, sourceEndSeconds: 2.0, ruleIds: ['termina'], reason: 'The reviewer cuts "termina aqui." and keeps the rest of the sentence.' }],
      reason: 'Cut inside a Director caption.', actor, idempotency: { clientId, key: `w66dcut-${run}-cut-${label}` } })
    let allocations = 0
    const cut = applyEditorialCutCommandService({ repository: new PrismaEditorialCommandRepository(db), clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => `w66dcut-${run}-${kind}-${++allocations}` })
    const expectCues = (editPlan, label) => {
      const cues = editPlan.subtitleTracks[0].cues
      assert.equal(cues[0].text, 'Primeira frase', label)
      assert.deepEqual(cues[0].sourceWordIndices, [0, 1], label)
      assert.deepEqual([cues[1].text, cues[1].sourceWordIndices], ['Segunda frase continua ainda.', [4, 5, 6, 7]], label)
      assert.equal(editPlan.subtitleTracks[0].schemaVersion, 'source-transcript-cue-track/v1', label)
    }

    // The copy forks the head Version, so it is made before the project's own cut moves that head.
    let copyAllocations = 0
    const copy = await duplicateProjectService({ repository: new PrismaProjectDuplicationRepository(db), clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => kind === 'project-media-asset' ? randomUUID() : `w66dcut-${run}-copy-${kind}-${++copyAllocations}` })({
      workspaceId, projectId: world.projectId, expectedVersionId: head.version.id, expectedVersionHash: head.version.baseHash, name: 'Director copy', actor,
      idempotency: { clientId, key: `w66dcut-${run}-dup` } })
    // The copy is configured before any cut: the configuration Commands are its children, it keeps the fork's posture (every entry blocked,
    // nothing observed), and a new output is refused with the reason the operator can act on.
    const copyScope = { workspaceId, projectId: copy.project.id }
    let childAllocations = 0
    const selectLut = setProjectLutSelectionService({ repository: new PrismaProjectLutSelectionRepository(db), clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => `w66dcut-${run}-child-${kind}-${++childAllocations}` })
    const lut = (base, key) => selectLut({ ...copyScope, baseVersionId: base.id, baseHash: base.baseHash, selection: { mode: 'none' }, actor,
      idempotencyKey: `w66dcut-${run}-${key}`, reason: 'Configuration of a copy.' })
    const configuredOne = await lut(copy.version, 'configure-1')
    const configuredTwo = await lut(configuredOne.version, 'configure-2')
    assert.deepEqual([configuredOne.version.sequence, configuredTwo.version.sequence], [2, 3])
    const configured = await operational.read({ ...copyScope, versionId: configuredTwo.version.id })
    assert.equal(forkAuthorityPendingV3(configured), true, 'configuring a copy leaves it without target authority')
    assert.ok(configured.state.document.entries.every((entry) => entry.consumption.status === 'blocked' &&
      entry.consumption.reasons.join() === 'fork-target-materialization-required'))
    assert.equal(await db.v2OutputNormalizationReceipt.count({ where: copyScope }), 0)
    const versionsBefore = await db.v2ProjectVersion.count({ where: copyScope })
    await assert.rejects(() => createProjectOutputVariantService({ repository: operational, clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => `w66dcut-${run}-variant-${kind}-${++childAllocations}` })({ ...variantBodyFor({ aspectRatio: '1:1' }), ...copyScope,
      baseVersionId: configuredTwo.version.id, baseHash: configuredTwo.version.baseHash, actor, idempotencyKey: `w66dcut-${run}-variant` }),
    (error) => error.code === 'PRECONDITION_REQUIRED' && error.details.reason === 'copy-requires-editorial-cut')
    assert.equal(await db.v2ProjectVersion.count({ where: copyScope }), versionsBefore, 'the refused Command wrote nothing')

    // 2a. The project itself.
    const own = await cut(request(world.projectId, head, 'own'))
    expectCues(own.editPlan, 'own')
    assert.equal(own.version.parentVersionId, head.version.id)
    assert.equal(serializeOutputCanonicalJson(await operational.read({ workspaceId, projectId: world.projectId, versionId: own.version.id })),
      serializeOutputCanonicalJson(own.outputBundle), 'the cut reads back exactly as it was built')

    // 2b. The copy of the Director Version.
    const copyCut = await cut(request(copy.project.id, configured, 'copy'))
    assert.equal(copyCut.version.parentVersionId, configuredTwo.version.id)
    expectCues(copyCut.editPlan, 'copy')
    const binding = editorialDerivedBindingV3(copyCut.outputBundle)
    assert.equal(binding.document.authority.kind, 'fork-derivation3')
    assert.equal(binding.document.authority.forkRootVersionId, copy.version.id, 'the authority is the Creation fork, not a configuration child')
    assert.equal(serializeOutputCanonicalJson(await operational.read({ workspaceId, projectId: copy.project.id, versionId: copyCut.version.id })),
      serializeOutputCanonicalJson(copyCut.outputBundle), 'the copy cut reads back exactly as it was built')
    assert.equal(await db.v2OutputNormalizationReceipt.count({ where: { workspaceId, projectId: copy.project.id } }), 0, 'the copy owns no receipt')
    assert.ok(copyCut.editPlan.durationFrames < plan.durationFrames, 'the reviewed range left the timeline')

    // 4. A cut copy is a project like any other once it has its authority: the normal Commands are its children, materialized from the very
    // receipts the cut bound under the cut's binding carried to each new Version (configuration, and a Director re-run that recompiles the
    // plan and reads the transcript from that binding), and each reads back rebuilt from the original project's receipts.
    const lutOne = await lut(copyCut.version, 'lut-1')
    const lutTwo = await lut(lutOne.version, 'lut-2')
    const rerun = await runProjectDirectorService({ repository: new PrismaDirectorRunRepository(db), clock: () => new Date(), createEventId: randomUUID,
      compileBrief: createEvidenceBoundBriefCompiler(), createId: (kind) => `w66dcut-${run}-rerun-${kind}-${++childAllocations}` })({
      ...copyScope, baseVersionId: lutTwo.version.id, baseHash: lutTwo.version.baseHash, actor, idempotency: { key: `w66dcut-${run}-rerun` },
      reason: 'Director re-run over a cut copy.' })
    assert.deepEqual([lutOne.version.sequence, lutTwo.version.sequence, rerun.version.sequence],
      [copyCut.version.sequence + 1, copyCut.version.sequence + 2, copyCut.version.sequence + 3])
    let carried = copyCut.outputBundle
    for (const child of [lutOne, lutTwo, rerun]) {
      const stored = await operational.read({ ...copyScope, versionId: child.version.id }), carriedBinding = editorialDerivedBindingV3(stored)
      assert.equal(stored.origin.kind, 'child-command')
      assert.equal(forkAuthorityPendingV3(stored), false)
      assert.notEqual(carriedBinding, null, 'every entry of a child of a cut copy carries the editorial binding')
      assert.equal(carriedBinding.document.authority.forkRootVersionId, copy.version.id)
      assert.equal(carriedBinding.document.parentVersionId, carried.version.id)
      assert.equal(carriedBinding.document.resultVersionId, child.version.id)
      assert.deepEqual(stored.state.document.entries[0].consumption.materialization.document.normalizations,
        carried.state.document.entries[0].consumption.materialization.document.normalizations, 'the very receipts of the original project')
      carried = stored
    }
    expectCues(JSON.parse(carried.editPlanSnapshot.contentJson), 'after the Director re-run')
    assert.equal(rerun.run.baseVersionId, lutTwo.version.id)
    assert.equal((await db.v2Project.findUnique({ where: { id: copy.project.id } })).currentVersionId, rerun.version.id)
    assert.equal(await db.v2OutputNormalizationReceipt.count({ where: { workspaceId, projectId: copy.project.id } }), 0)
  } finally { await db.$disconnect() }
})
