const framesOf = (ticks) => Number(ticks) / (TICKS_PER_SECOND / FPS)

test('T-F4.015 a real react recording resolves into playing, paused, commentary, replay, seek, rewind and a stretch only a person can answer', async (t) => {
  const workRoot = await mkdtemp(join(tmpdir(), 'apollo-playback-fingerprint-'))
  t.after(async () => {
    // AGENTS.md: an ephemeral artefact of a test is cleaned up by the test that
    // made it, and the cleanup reports rather than throws.
    await rm(workRoot, { recursive: true, force: true }).catch((error) => {
      console.log(`playback fixture cleanup failed for ${workRoot}: ${String(error)}`)
    })
  })

  const { referencePath, reactionPath, watchedPath } = await buildFixture(workRoot)
  const [referenceProbe, reactionProbe] = await Promise.all([
    probeVideo(referencePath, { requireAudio: true }),
    probeVideo(reactionPath, { requireAudio: true }),
  ])

  // The two durations are measured, not assumed, and they are different.
  assert.ok(Math.abs(referenceProbe.duration - REFERENCE_SECONDS) < 0.5, 'reference is ~30 s')
  assert.ok(Math.abs(reactionProbe.duration - REACTION_SECONDS) < 0.5, `reaction is ~${REACTION_SECONDS} s`)
  assert.ok(reactionProbe.duration > referenceProbe.duration * 1.9, 'the reaction is twice the reference')

  const media = mediaFor(REFERENCE_SECONDS, REACTION_SECONDS)
  const track = tracks()
  const session = reactSession(track)
  const fingerprinter = new FfmpegPlaybackFingerprinter({ workRoot })

  const started = Date.now()
  const observations = await fingerprinter.detectPlaybackObservations({
    referencePath,
    reactionPath,
    reactionTimebase: TIMEBASE,
    referenceTimebase: TIMEBASE,
    sampleRate: SAMPLE_RATE,
    windowMs: 1_000,
    hopMs: 500,
  })
  const elapsedMs = Date.now() - started
  const locked = observations.filter((observation) => observation.referenceTick !== null).length

  const map = buildPlaybackMap({
    mapId: 'playback-map-fixture',
    session,
    reactionTrack: track.reaction,
    referenceTrack: track.reference,
    referenceMedia: media.reference,
    reactionMedia: media.reaction,
    observations,
    policy: POLICY,
  })

  console.log(
    `playback fingerprint: ref ${referenceProbe.duration.toFixed(2)}s/${referenceProbe.codec}/${referenceProbe.audioCodec}, ` +
    `reaction ${reactionProbe.duration.toFixed(2)}s, ${observations.length} windows (${locked} locked) in ${elapsedMs} ms, ` +
    `${map.pieces.length} pieces, ${map.uncovered.length} uncovered, status ${map.status}`,
  )

  const detected = [
    ...map.pieces.map((piece) => ({ start: piece.reactionRange.start, label: piece.mode })),
    ...map.uncovered.map((entry) => ({ start: entry.range.start, label: `uncovered/${entry.reason}` })),
  ].sort((left, right) => (left.start < right.start ? -1 : 1))

  // One line per boundary, with the error against TRUTH in frames.
  let worstFrames = 0
  for (const [index, boundary] of detected.entries()) {
    const truth = seconds(TRUTH[index] ? TRUTH[index].from : 0)
    const errorFrames = Math.abs(framesOf(boundary.start - truth))
    worstFrames = Math.max(worstFrames, errorFrames)
    console.log(`playback: ${boundary.label} @ ${boundary.start} erro ${errorFrames} frames`)
  }

  assert.deepEqual(detected.map((entry) => entry.label), [
    'playing',
    'paused',
    'playing',
    'commentary-only',
    'playing',
    'replay',
    'seek',
    'uncovered/manual-anchor-required',
    'playing',
    'rewind',
  ])
  assert.ok(
    worstFrames <= BOUNDARY_TOLERANCE_FRAMES,
    `worst boundary error ${worstFrames} frames exceeds the declared ${BOUNDARY_TOLERANCE_FRAMES}`,
  )

  const [opening, paused, resumed, commentary, resumedAgain, replay, seek, tail, rewound] = map.pieces

  // During the pause the reference does not advance, and playback resumes from
  // the tick it left — measured in frames, not asserted in prose.
  assert.equal(paused.mode, 'paused')
  assert.equal(paused.referenceRange, null)
  assert.ok(
    Math.abs(framesOf(resumed.referenceRange.start - opening.referenceRange.end)) <= BOUNDARY_TOLERANCE_FRAMES,
    'the reference resumed where it stopped',
  )

  assert.equal(commentary.mode, 'commentary-only')
  assert.equal(commentary.referenceRange, null)
  assert.ok(
    Math.abs(framesOf(resumedAgain.referenceRange.start - resumed.referenceRange.end)) <= BOUNDARY_TOLERANCE_FRAMES,
    'the reference resumed where it stopped after the commentary too',
  )

  // Back to reference ground already covered: a replay, not a rewind, because
  // nothing past what had been played is reached.
  assert.equal(replay.mode, 'replay')
  assert.equal(replay.direction, 'backward')
  assert.equal(replay.discontinuityReason, 'rewind')
  assert.ok(replay.referenceRange.start < resumedAgain.referenceRange.start, 'the reference went back')
  assert.ok(replay.referenceRange.end <= resumedAgain.referenceRange.end, 'and did not reach new ground')

  assert.equal(seek.discontinuityReason, 'seek')
  assert.ok(seek.referenceRange.start > replay.referenceRange.end)

  // And back into the ground the seek skipped: a REWIND, which the replay above
  // is not. Both are backward and both carry `discontinuityReason: 'rewind'`;
  // the mode is what separates "watched it again" from "went back for the part
  // they had not watched", and only the second one reaches reference time no
  // played interval covers.
  assert.equal(rewound.mode, 'rewind')
  assert.equal(rewound.direction, 'backward')
  assert.equal(rewound.discontinuityReason, 'rewind')
  assert.ok(rewound.referenceRange.start < tail.referenceRange.start, 'the reference went back')
  // What makes it a rewind rather than a replay, in the domain's own terms: no
  // interval played BEFORE it contains the range it landed on.
  const playedBeforeRewind = [opening, resumed, resumedAgain, replay, seek, tail]
    .map((piece) => piece.referenceRange)
  assert.ok(
    !playedBeforeRewind.some((played) =>
      played.start <= rewound.referenceRange.start && rewound.referenceRange.end <= played.end),
    'a rewind whose range was already played is a replay, and this fixture would prove nothing',
  )
  assert.ok(
    rewound.referenceRange.end > seek.referenceRange.end,
    'the rewind has to run past the ground the seek reached, or the domain calls it a replay',
  )

  // Every window the detector refused reports confidence in the ABSENCE, never
  // the peak-over-runner-up ratio of the match it rejected. Measured here rather
  // than asserted: the fixture's reactor noise routinely produces sharp ratios
  // over correlations far under the floor, which is the exact shape that used to
  // travel as a high confidence and land on the `paused` piece.
  const refused = observations.filter((entry) => entry.referenceTick === null)
  const sharpButRefused = refused.filter((entry) => entry.peakRatio >= 1.2)
  assert.ok(refused.length > 0 && sharpButRefused.length > 0, 'the fixture contains refused windows with sharp ratios')
  for (const entry of refused) assert.ok(entry.confidence <= MAXIMUM_ABSENCE_CONFIDENCE)
  for (const entry of sharpButRefused) {
    assert.notEqual(
      entry.confidence,
      confidenceFromPeakRatio(entry.peakRatio),
      'a refused window carried the confidence of the match it refused',
    )
  }
  console.log(
    `playback refused windows: ${refused.length} (${sharpButRefused.length} with ratio >= 1.2), ` +
    `confidence ${Math.min(...refused.map((entry) => entry.confidence)).toFixed(3)}` +
    `-${Math.max(...refused.map((entry) => entry.confidence)).toFixed(3)}`,
  )

  assert.equal(map.status, 'needs-input')
  assert.equal(map.uncovered.length, 1)
  assert.equal(map.uncovered[0].reason, 'manual-anchor-required')
  assert.ok(tail.referenceRange.end <= media.reference.durationTicks)

  // No field of the map equals the other recording's duration.
  assert.notEqual(map.referenceMedia.durationTicks, map.reactionMedia.durationTicks)
  for (const piece of map.pieces) {
    if (piece.referenceRange === null) continue
    assert.notEqual(piece.referenceRange.end, map.reactionMedia.durationTicks)
  }

  // ------------------------------------------------------------------
  // The person answers the one thing the audio could not.
  // ------------------------------------------------------------------
  const hidden = TRUTH.find((segment) => segment.mode === 'hidden')
  // Deliberately NOT the head of the uncovered stretch. An operator reads the
  // clock off whatever frame is legible, and an anchor placed anywhere but the
  // head used to shift the whole resolved piece by the distance between the two.
  const hiddenRange = map.uncovered[0].range
  const anchorTick = hiddenRange.start + (hiddenRange.end - hiddenRange.start) / 2n
  const anchorReference = seconds(hidden.reference) + (anchorTick - hiddenRange.start)
  const resolved = applyPlaybackAnchor(map, {
    expectedVersion: map.version,
    expectedHash: map.mapHash,
    anchor: {
      anchorId: 'anchor-hidden-player',
      reactionTick: anchorTick,
      referenceTick: anchorReference,
      mode: 'playing',
      actorId: 'operator-7',
      note: 'player overlay hid the video; read the clock from the frame',
      createdAt: at(900),
    },
  })
  // The instant the operator named resolves to the instant they named, and the
  // piece starts where the truth says the hidden stretch started.
  const atAnchor = resolveReactionTick(resolved, anchorTick)
  assert.equal(atAnchor.status, 'resolved')
  assert.equal(atAnchor.referenceTick, anchorReference)
  assert.equal(resolved.status, 'resolved')
  assert.equal(resolved.uncovered.length, 0)
  assert.equal(resolved.version, map.version + 1)
  assert.equal(resolved.previousVersionHash, map.mapHash)
  const answered = resolved.pieces.find((piece) => piece.detectionMethod === 'manual-anchor')
  assert.equal(answered.mode, 'playing')
  assert.equal(answered.rate, null, 'one anchor is a point, not a slope')
  assert.equal(
    resolved.anchors[0].evidenceRef,
    'operator:operator-7 (player overlay hid the video; read the clock from the frame)',
  )

  // ------------------------------------------------------------------
  // Determinism: the same bytes produce the same map, hash included.
  // ------------------------------------------------------------------
  const second = await fingerprinter.detectPlaybackObservations({
    referencePath,
    reactionPath,
    reactionTimebase: TIMEBASE,
    referenceTimebase: TIMEBASE,
    sampleRate: SAMPLE_RATE,
    windowMs: 1_000,
    hopMs: 500,
  })
  const again = buildPlaybackMap({
    mapId: 'playback-map-fixture',
    session,
    reactionTrack: track.reaction,
    referenceTrack: track.reference,
    referenceMedia: media.reference,
    reactionMedia: media.reaction,
    observations: second,
    policy: POLICY,
  })
  const observationDigest = (list) => createHash('sha256')
    .update(list.map((entry) => `${entry.reactionTick}:${entry.referenceTick}`).join('|'))
    .digest('hex')
  assert.equal(observationDigest(second), observationDigest(observations))
  assert.equal(again.mapHash, map.mapHash)
  console.log(`playback determinism: mapHash ${map.mapHash.slice(0, 16)} on both runs`)

  // ------------------------------------------------------------------
  // The reference's own end, on the second recording.
  // ------------------------------------------------------------------
  //
  // The golden table stops mid-rewind at reference 26.5 and cannot say whether
  // the domain notices a reactor reaching the reference's LAST tick. This
  // recording can: four seconds of talking, then the reference played straight
  // through to its end.
  const watchedProbe = await probeVideo(watchedPath, { requireAudio: true })
  assert.ok(
    Math.abs(watchedProbe.duration - WATCHED_SECONDS) < 0.5,
    `the watched reaction measured ${watchedProbe.duration.toFixed(2)}s`,
  )
  assert.ok(
    watchedProbe.duration > referenceProbe.duration,
    'the watched reaction has to outlast the reference for the copied duration below to be a lie',
  )
  const watchedObservations = await fingerprinter.detectPlaybackObservations({
    referencePath,
    reactionPath: watchedPath,
    reactionTimebase: TIMEBASE,
    referenceTimebase: TIMEBASE,
    sampleRate: SAMPLE_RATE,
    windowMs: 1_000,
    hopMs: 500,
  })
  const watchedTrack = tracks(WATCHED_SECONDS)
  const watchedSession = reactSession(watchedTrack, 'capture-session-react-watched')
  const watchedReaction = { ...media.reaction, durationTicks: seconds(WATCHED_SECONDS) }
  const buildWatched = (referenceMedia) => buildPlaybackMap({
    mapId: 'playback-map-watched',
    session: watchedSession,
    reactionTrack: watchedTrack.reaction,
    referenceTrack: watchedTrack.reference,
    referenceMedia,
    reactionMedia: watchedReaction,
    observations: watchedObservations,
    policy: POLICY,
  })
  const watched = buildWatched(media.reference)
  const watchedLast = watched.pieces[watched.pieces.length - 1]
  assert.deepEqual(watched.pieces.map((piece) => piece.mode), ['commentary-only', 'playing'])
  assert.equal(
    watchedLast.referenceRange.end,
    media.reference.durationTicks,
    'the run that plays to the end of the reaction has to land on the reference\'s last tick',
  )
  assert.ok(
    watched.warnings.includes('reference-exhausted'),
    'a piece that ends on the reference duration is the reference being exhausted, and the map has to say so',
  )

  // The same lie as (b) below, on the recording that can feel it: declaring the
  // reference as long as this reaction moves the end a reactor would have to
  // reach, and the map stops saying they reached it. Same bytes, same windows,
  // same pieces — a different ANSWER, not a different digest.
  const watchedLie = buildWatched({ ...media.reference, durationTicks: watchedReaction.durationTicks })
  assert.ok(
    !watchedLie.warnings.includes('reference-exhausted'),
    'a reference declared longer than it is was not watched to its end, whatever the audio matched',
  )
  const watchedLieLast = watchedLie.pieces[watchedLie.pieces.length - 1]
  assert.ok(
    watchedLieLast.referenceRange.end >= watchedLast.referenceRange.end,
    'the measured duration can only cap the last range, never extend it',
  )
  console.log(
    `playback exhaustion: ${watchedObservations.length} windows over ${watchedProbe.duration.toFixed(2)}s, ` +
    `${watched.pieces.length} pieces, last ${watchedLast.mode} reference ` +
    `${(Number(watchedLast.referenceRange.start) / TICKS_PER_SECOND).toFixed(2)}-` +
    `${(Number(watchedLast.referenceRange.end) / TICKS_PER_SECOND).toFixed(2)}s of ` +
    `${(Number(media.reference.durationTicks) / TICKS_PER_SECOND).toFixed(2)}s; warnings ` +
    `[${watched.warnings.join(' ')}] vs copied-duration [${watchedLie.warnings.join(' ')}]`,
  )

  // ------------------------------------------------------------------
  // Falsification (a): the naive linearisation.
  // ------------------------------------------------------------------
  assert.throws(
    () => createPlaybackMap({
      mapId: 'playback-map-linear',
      workspaceId: session.workspaceId,
      sessionId: session.sessionId,
      sessionVersion: session.version,
      referenceEpoch: session.referenceEpoch,
      reactionTrackId: track.reaction.trackId,
      referenceTrackId: track.reference.trackId,
      referenceMedia: media.reference,
      reactionMedia: media.reaction,
      pieces: [{
        pieceId: 'piece-000',
        mode: 'playing',
        reactionRange: createTickInterval(0n, media.reaction.durationTicks),
        referenceRange: createTickInterval(0n, media.reaction.durationTicks),
        direction: 'forward',
        confidence: 0.9,
        evidenceRefs: ['fingerprint:0'],
        detectionMethod: 'audio-fingerprint',
      }],
    }),
    (error) => error.code === 'INVALID_ARGUMENT' &&
      /plays reference time the reference does not have/.test(error.message),
  )

  // ------------------------------------------------------------------
  // Falsification (b): assuming the reference is as long as the reaction.
  // ------------------------------------------------------------------
  const lied = buildPlaybackMap({
    mapId: 'playback-map-fixture',
    session,
    reactionTrack: track.reaction,
    referenceTrack: track.reference,
    referenceMedia: { ...media.reference, durationTicks: media.reaction.durationTicks },
    reactionMedia: media.reaction,
    observations,
    policy: POLICY,
  })
  // The measured duration, from ffprobe, is the only authority for how long the
  // reference is — and it is half the reaction.
  const measuredReference = seconds(Math.round(referenceProbe.duration))
  assert.equal(media.reference.durationTicks, measuredReference)
  assert.notEqual(measuredReference, media.reaction.durationTicks)

  // The lie is not caught at construction, because in this phase nothing
  // measures the reference for `buildPlaybackMap` — the duration is declared by
  // the caller, and that is a stated limitation of the domain slice. What the
  // fixture can prove is that the declared duration is load-bearing, and that
  // ffprobe's number is the one that refuses.
  //
  // The lie made concrete: the last piece extended to play reference time only a
  // seventy-second reference would have. The same body is refused under the
  // measured thirty seconds and accepted under the copied seventy.
  // The LAST piece, read off the map rather than named: `tail` stopped being it
  // when the rewind was appended, and slicing the last one off while re-adding
  // `tail` produced two pieces with the same id instead of the overreach this
  // block is about.
  const last = map.pieces[map.pieces.length - 1]
  const overreaching = [
    ...map.pieces.slice(0, -1),
    { ...last, rate: null, referenceRange: createTickInterval(last.referenceRange.start, media.reaction.durationTicks) },
  ]
  const assemble = (referenceMedia) => () => createPlaybackMap({
    mapId: 'playback-map-lie-checked',
    workspaceId: session.workspaceId,
    sessionId: session.sessionId,
    sessionVersion: session.version,
    referenceEpoch: session.referenceEpoch,
    reactionTrackId: track.reaction.trackId,
    referenceTrackId: track.reference.trackId,
    referenceMedia,
    reactionMedia: media.reaction,
    pieces: overreaching,
    uncovered: map.uncovered,
  })
  assert.throws(
    assemble(media.reference),
    (error) => error.code === 'INVALID_ARGUMENT' &&
      /plays reference time the reference does not have/.test(error.message) &&
      error.details.referenceDurationTicks === measuredReference.toString(),
  )
  assert.doesNotThrow(
    assemble({ ...media.reference, durationTicks: media.reaction.durationTicks }),
    'only the copied duration makes the overreaching piece legal, which is what makes the lie a lie',
  )
  // The lie is also a different map, and the hash says so because the declared
  // duration is part of the map's identity rather than a note beside it. That
  // check SUPPORTS the two above and cannot replace them:
  // `calculatePlaybackMapHash` hashes `referenceMedia.durationTicks`
  // (playback-map.ts:455) and the lie IS a different durationTicks, so the
  // digests differ whether or not the answer moved. Where the answer itself
  // moves is the watched recording above — `reference-exhausted` under the
  // measured thirty seconds, gone under the copied one.
  assert.notEqual(lied.mapHash, map.mapHash)
  // On THIS recording neither map warns: it ends mid-rewind at reference 26.5,
  // so no piece reaches either declared end. Asserted rather than left unsaid,
  // because `reference-exhausted` used to be this fixture's answer here — the
  // carrier moved to the recording that can hold it, it did not vanish.
  assert.ok(!map.warnings.includes('reference-exhausted'))
  assert.ok(!lied.warnings.includes('reference-exhausted'))

  // ------------------------------------------------------------------
  // Falsification (c): contradictory evidence in one window.
  // ------------------------------------------------------------------
  const contested = observations.find((entry) =>
    entry.reactionTick === seconds(4) && entry.referenceTick !== null)
  assert.ok(contested, 'the fourth second of the reaction locked onto the reference')
  const conflicted = buildPlaybackMap({
    mapId: 'playback-map-conflict',
    session,
    reactionTrack: track.reaction,
    referenceTrack: track.reference,
    referenceMedia: media.reference,
    reactionMedia: media.reaction,
    observations: [
      ...observations,
      {
        reactionTick: contested.reactionTick,
        referenceTick: contested.referenceTick + seconds(9),
        confidence: 0.87,
        method: 'audio-fingerprint',
        evidenceRef: 'fingerprint:rival',
        peakRatio: 3.1,
      },
    ],
    policy: POLICY,
  })
  const conflict = conflicted.uncovered.find((entry) => entry.reason === 'conflicting-evidence')
  assert.ok(conflict, 'two plausible references in one window leave the window uncovered')
  assert.ok(conflicted.warnings.includes('conflicting-evidence'))
  assert.ok(
    !conflicted.pieces.some((piece) =>
      piece.reactionRange.start <= contested.reactionTick &&
      piece.reactionRange.end > contested.reactionTick),
    'no piece is invented over evidence that refused to choose',
  )
})
