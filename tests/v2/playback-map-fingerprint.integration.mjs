/**
 * Boundary tolerance, declared rather than discovered.
 *
 * The detector hops every 500 ms and each window is 1 s long, so a piece
 * boundary can only be located to within one hop plus the window that straddles
 * it. At 30 fps that is 45 frames; the assertion below uses 45 and prints the
 * measured error for every boundary so a regression shows up as a number, not a
 * pass.
 */
const BOUNDARY_TOLERANCE_FRAMES = 45

