/**
 * T-F4.015 — the react playback map against real recordings.
 *
 * A thirty-second reference, a seventy-second reaction that is the fixture's
 * golden recording, and a second thirty-four-second reaction that watches the
 * reference to its last tick — the one thing the golden table cannot express,
 * for the reason written on `WATCHED_TRUTH` below.
 *
 * All three files are generated by FFmpeg at test time and removed afterwards, so
 * nothing large lives in the repository and the inputs are reproducible from the
 * code that describes them (AGENTS.md: a committed MP4 is not evidence).
 *
 * **Why the reference audio is a different chirp every second.** The Wave 19
 * filler was a constant 300 Hz sine (`marker-robustness.integration.mjs:54-64`),
 * which is exactly the wrong signal here: correlated against a thirty-second
 * reference it peaks equally at every second, so the fingerprint could say that
 * *something* matched and never *which* second matched. Two signals agreeing
 * corroborate the instant, not the identity (ADR-151, generalised). Every second
 * of this reference is a distinct linear sweep, and consecutive seconds sweep in
 * opposite directions, so a locked window names one second and no other.
 *
 * The reaction is seventy seconds against a thirty-second reference — deliberately
 * unequal, because "the recording duration never implies the reference duration"
 * (ADR-135) is the invariant this fixture exists to falsify.
 */

const SAMPLE_RATE = 16_000
const TICKS_PER_SECOND = 90_000
const TIMEBASE = timebaseFromRate(TICKS_PER_SECOND)
const FPS = 30
const REFERENCE_SECONDS = 30
const REACTION_SECONDS = 70

const seconds = (value) => BigInt(Math.round(value * TICKS_PER_SECOND))
const digest = (character) => character.repeat(64)
const at = (second) => new Date(Date.parse('2029-04-01T09:00:00.000Z') + second * 1000).toISOString()

/**
 * What actually happened in the golden recording, second by second. Every
 * assertion about it below is measured against this table and nothing else, and
 * `buildReactionSamples` refuses a table that is not a contiguous partition of
 * the recording it describes — a row starting where the one before it ended,
 * the last row ending on the recording's last second. That guard exists because
 * a duplicated row once sat here and was silently invisible: it repainted a span
 * an earlier row had already written and had its overhanging seconds dropped
 * past the end of the sample buffer, changing nothing anybody asserted except
 * the noise draw.
 */
const TRUTH = Object.freeze([
  { mode: 'playing', from: 0, to: 10, reference: 0 },
  { mode: 'paused', from: 10, to: 18, reference: null },
  { mode: 'playing', from: 18, to: 23, reference: 10 },
  { mode: 'commentary-only', from: 23, to: 37, reference: null },
  // The reference resumes at the tick it left (15), which is the only thing
  // that makes the stretch before it a pause-class gap at all. Without this
  // segment the commentary was followed by a reference resuming BEHIND, and the
  // aggregate refuses to call that a pause: "paused then rewound" and "played on
  // unobserved then rewound further back" both fit the same evidence.
  { mode: 'playing', from: 37, to: 41, reference: 15 },
  { mode: 'replay', from: 41, to: 49, reference: 8 },
  { mode: 'seek', from: 49, to: 53, reference: 19 },
  { mode: 'hidden', from: 53, to: 57, reference: 23 },
  { mode: 'playing', from: 57, to: 60, reference: 27 },
  // The rewind — the MODE, not the `'rewind'` discontinuity reason the replay
  // above also carries.
  //
  // `PLAYBACK_MODES` has six values and this fixture reached five of them.
  // `deriveReactionPlaybackMap` calls a backward move a `replay` when the range
  // it lands on is already covered by everything played so far, and a `rewind`
  // only when it is not (playback-map.ts:1256-1259) — so the difference is not
  // the direction and not the distance. The backward move at 41 s goes back to
  // reference 8 and stops at 16, inside the played union, and is a replay.
  // This one goes back to 16 and runs on to 26, past the 23 the seek reached:
  // the reactor rewinds and then watches THROUGH into ground nobody had seen.
  // By this table the played union entering the segment is [0, 23] u [27, 30];
  // measured, with the detector's half-second boundaries, [0, 23.5] u
  // [26.5, 29.5] — and no interval of either contains the [16, 26.5] it lands
  // on.
  //
  // Ten seconds, and both ends of that number are load-bearing:
  //
  // - stop short of the 23 the seek reached and the domain calls this a replay,
  //   which the segment at 41 s already proves;
  // - run on to 30 and the range gets CAPPED. The reference range of a run is
  //   `referenceStart + reactionSpan` capped at the reference duration
  //   (playback-map.ts:1237-1243), and a capped range spans fewer reference
  //   frames than timeline frames, which `compilePlaybackToShots` refuses
  //   outright — measured while writing this: "piece piece-009 spans 420
  //   reference frames over 435 timeline frames". So the reference's own END is
  //   carried by the second recording below, where nothing has to be cut.
  { mode: 'rewind', from: 60, to: 70, reference: 16 },
])

/**
 * A second recording: four seconds of talking, then the reference watched
 * straight through to its last tick.
 *
 * `reference-exhausted` is the map's answer to "did the reactor reach the end
 * of the reference" (playback-map.ts:824-826), and the table above cannot carry
 * it: its last run is a rewind that stops at 26.5 s, because a run ending ON the
 * reference duration gets its range capped and a capped piece is one
 * `compilePlaybackToShots` refuses. Without a recording of its own the warning
 * had no assertion anywhere in the repository — deleting the three lines that
 * raise it broke no test, measured.
 *
 * The shape is what makes the number robust rather than tuned. The playing run
 * extends to the end of the reaction media and the reactor plays at 1:1, so
 * wherever the detector puts the boundary, `referenceStart + reactionSpan`
 * comes out at the reference's thirty seconds: a boundary half a second early
 * starts half a second earlier in the reference and spans half a second more.
 * The opening gap has no locked run before it, which is what makes it
 * commentary rather than a pause (playback-map.ts:1196-1201) — four seconds is
 * enough, and every second of it keeps the reaction longer than the reference,
 * which is what the lie below needs to be a lie.
 */
const WATCHED_SECONDS = 34
const WATCHED_TRUTH = Object.freeze([
  { mode: 'commentary-only', from: 0, to: 4, reference: null },
  { mode: 'playing', from: 4, to: WATCHED_SECONDS, reference: 0 },
])

