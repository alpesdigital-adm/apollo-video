function tracks() {
  const device = (id) => ({ deviceId: id, recorderId: `${id}-1`, make: null, model: null, serial: null })
  const evidence = (character) => ({
    ingestArtifactId: `artifact-${character}`,
    ingestSha256: digest(character),
    probeHash: digest('b'),
    probeSource: 'packet-scan',
    observedAt: at(1),
  })
  return {
    reaction: {
      trackId: 'track-reaction',
      role: 'reaction',
      device: device('device-webcam'),
      sourceAssetId: 'asset-reaction-1',
      timebase: TIMEBASE,
      streamIndex: 0,
      syncAudioPolicy: 'final-candidate',
      includeInFinalMix: true,
      parts: [{
        partId: 'part-reaction-1',
        ordinal: 0,
        sourceAssetId: 'asset-reaction-1',
        timebase: TIMEBASE,
        coverage: createTickInterval(0n, seconds(REACTION_SECONDS)),
        streamIndex: 0,
        splitReason: 'single-file',
        evidence: evidence('a'),
      }],
    },
    reference: {
      trackId: 'track-reference',
      role: 'reference-video',
      device: device('device-screen'),
      sourceAssetId: 'asset-reference-1',
      timebase: TIMEBASE,
      streamIndex: 0,
      syncAudioPolicy: 'sync-only',
      includeInFinalMix: false,
      parts: [{
        partId: 'part-reference-1',
        ordinal: 0,
        sourceAssetId: 'asset-reference-1',
        timebase: TIMEBASE,
        coverage: createTickInterval(0n, seconds(REFERENCE_SECONDS)),
        streamIndex: 0,
        splitReason: 'single-file',
        evidence: evidence('c'),
      }],
    },
  }
}

function reactSession(track) {
  return createCaptureSession({
    workspaceId: 'workspace-1',
    projectId: 'project-1',
    sessionId: 'capture-session-react-fixture',
    clock: { timebase: TIMEBASE, rounding: 'nearest-half-even' },
    referenceTrackId: 'track-reference',
    tracks: [track.reaction, track.reference],
    lineage: {
      commandId: 'command-create-session',
      operation: 'create-session',
      actorKind: 'human',
      actorId: 'operator-1',
      occurredAt: at(0),
      note: null,
    },
    createdAt: at(0),
  })
}

function mediaFor(probedReferenceSeconds, probedReactionSeconds) {
  return {
    reference: {
      assetId: 'asset-reference-1',
      sha256: digest('c'),
      durationTicks: seconds(probedReferenceSeconds),
      timebase: TIMEBASE,
    },
    reaction: {
      assetId: 'asset-reaction-1',
      sha256: digest('a'),
      durationTicks: seconds(probedReactionSeconds),
    },
  }
}

const framesOf = (ticks) => Number(ticks) / (TICKS_PER_SECOND / FPS)

test('T-F4.015 a real react recording resolves into playing, paused, commentary, rewind, seek and a stretch only a person can answer', async (t) => {
  const workRoot = await mkdtemp(join(tmpdir(), 'apollo-playback-fingerprint-'))
  t.after(async () => {
    // AGENTS.md: an ephemeral artefact of a test is cleaned up by the test that
    // made it, and the cleanup reports rather than throws.
    await rm(workRoot, { recursive: true, force: true }).catch((error) => {
      console.log(`playback fixture cleanup failed for ${workRoot}: ${String(error)}`)
    })
  })

  const { referencePath, reactionPath } = await buildFixture(workRoot)
  const [referenceProbe, reactionProbe] = await Promise.all([
    probeVideo(referencePath, { requireAudio: true }),
    probeVideo(reactionPath, { requireAudio: true }),
  ])

  // The two durations are measured, not assumed, and they are different.
  assert.ok(Math.abs(referenceProbe.duration - REFERENCE_SECONDS) < 0.5, 'reference is ~30 s')
  assert.ok(Math.abs(reactionProbe.duration - REACTION_SECONDS) < 0.5, 'reaction is ~60 s')
  assert.ok(reactionProbe.duration > referenceProbe.duration * 1.9, 'the reaction is twice the reference')

  const media = mediaFor(REFERENCE_SECONDS, REACTION_SECONDS)
  const track = tracks()
  const session = reactSession(track)
  const fingerprinter = new FfmpegPlaybackFingerprinter({ workRoot })

  const started = Date.now()
  const observations = await fingerprinter.detectPlaybackObservations({
    referencePath,
    reactionPath,
    reactionTimebase: TIMEBASE,
    referenceTimebase: TIMEBASE,
    sampleRate: SAMPLE_RATE,
    windowMs: 1_000,
    hopMs: 500,
  })
  const elapsedMs = Date.now() - started
  const locked = observations.filter((observation) => observation.referenceTick !== null).length

  const map = buildPlaybackMap({
    mapId: 'playback-map-fixture',
    session,
    reactionTrack: track.reaction,
    referenceTrack: track.reference,
    referenceMedia: media.reference,
    reactionMedia: media.reaction,
    observations,
    policy: POLICY,
  })

  console.log(
    `playback fingerprint: ref ${referenceProbe.duration.toFixed(2)}s/${referenceProbe.codec}/${referenceProbe.audioCodec}, ` +
    `reaction ${reactionProbe.duration.toFixed(2)}s, ${observations.length} windows (${locked} locked) in ${elapsedMs} ms, ` +
    `${map.pieces.length} pieces, ${map.uncovered.length} uncovered, status ${map.status}`,
  )

  const detected = [
    ...map.pieces.map((piece) => ({ start: piece.reactionRange.start, label: piece.mode })),
    ...map.uncovered.map((entry) => ({ start: entry.range.start, label: `uncovered/${entry.reason}` })),
  ].sort((left, right) => (left.start < right.start ? -1 : 1))

  // One line per boundary, with the error against TRUTH in frames.
  let worstFrames = 0
  for (const [index, boundary] of detected.entries()) {
    const truth = seconds(TRUTH[index] ? TRUTH[index].from : 0)
    const errorFrames = Math.abs(framesOf(boundary.start - truth))
    worstFrames = Math.max(worstFrames, errorFrames)
    console.log(`playback: ${boundary.label} @ ${boundary.start} erro ${errorFrames} frames`)
  }

  assert.deepEqual(detected.map((entry) => entry.label), [
    'playing',
    'paused',
    'playing',
    'commentary-only',
    'rewind',
    'seek',
    'uncovered/manual-anchor-required',
    'playing',
  ])
  assert.ok(
    worstFrames <= BOUNDARY_TOLERANCE_FRAMES,
    `worst boundary error ${worstFrames} frames exceeds the declared ${BOUNDARY_TOLERANCE_FRAMES}`,
  )

  const [opening, paused, resumed, commentary, rewind, seek, tail] = map.pieces

  // During the pause the reference does not advance, and playback resumes from
  // the tick it left — measured in frames, not asserted in prose.
  assert.equal(paused.mode, 'paused')
  assert.equal(paused.referenceRange, null)
  assert.ok(
    Math.abs(framesOf(resumed.referenceRange.start - opening.referenceRange.end)) <= BOUNDARY_TOLERANCE_FRAMES,
    'the reference resumed where it stopped',
  )

  assert.equal(commentary.mode, 'commentary-only')
  assert.equal(commentary.referenceRange, null)

  assert.equal(rewind.direction, 'backward')
  assert.equal(rewind.discontinuityReason, 'rewind')
  assert.ok(rewind.referenceRange.start < resumed.referenceRange.start, 'the reference went back')

  assert.equal(seek.discontinuityReason, 'seek')
  assert.ok(seek.referenceRange.start > rewind.referenceRange.end)

  assert.equal(map.status, 'needs-input')
  assert.equal(map.uncovered.length, 1)
  assert.equal(map.uncovered[0].reason, 'manual-anchor-required')
  assert.ok(tail.referenceRange.end <= media.reference.durationTicks)

  // No field of the map equals the other recording's duration.
  assert.notEqual(map.referenceMedia.durationTicks, map.reactionMedia.durationTicks)
  for (const piece of map.pieces) {
    if (piece.referenceRange === null) continue
    assert.notEqual(piece.referenceRange.end, map.reactionMedia.durationTicks)
  }

  // ------------------------------------------------------------------
  // The person answers the one thing the audio could not.
  // ------------------------------------------------------------------
  const hidden = TRUTH.find((segment) => segment.mode === 'hidden')
  const resolved = applyPlaybackAnchor(map, {
    expectedVersion: map.version,
    expectedHash: map.mapHash,
    anchor: {
      anchorId: 'anchor-hidden-player',
      reactionTick: map.uncovered[0].range.start,
      referenceTick: seconds(hidden.reference),
      mode: 'playing',
      actorId: 'operator-7',
      note: 'player overlay hid the video; read the clock from the frame',
      createdAt: at(900),
    },
  })
  assert.equal(resolved.status, 'resolved')
  assert.equal(resolved.uncovered.length, 0)
  assert.equal(resolved.version, map.version + 1)
  assert.equal(resolved.previousVersionHash, map.mapHash)
  const answered = resolved.pieces.find((piece) => piece.detectionMethod === 'manual-anchor')
  assert.equal(answered.mode, 'playing')
  assert.equal(answered.rate, null, 'one anchor is a point, not a slope')
  assert.equal(
    resolved.anchors[0].evidenceRef,
    'operator:operator-7 (player overlay hid the video; read the clock from the frame)',
  )

  // ------------------------------------------------------------------
  // Determinism: the same bytes produce the same map, hash included.
  // ------------------------------------------------------------------
  const second = await fingerprinter.detectPlaybackObservations({
    referencePath,
    reactionPath,
    reactionTimebase: TIMEBASE,
    referenceTimebase: TIMEBASE,
    sampleRate: SAMPLE_RATE,
    windowMs: 1_000,
    hopMs: 500,
  })
  const again = buildPlaybackMap({
    mapId: 'playback-map-fixture',
    session,
    reactionTrack: track.reaction,
    referenceTrack: track.reference,
    referenceMedia: media.reference,
    reactionMedia: media.reaction,
    observations: second,
    policy: POLICY,
  })
  const observationDigest = (list) => createHash('sha256')
    .update(list.map((entry) => `${entry.reactionTick}:${entry.referenceTick}`).join('|'))
    .digest('hex')
  assert.equal(observationDigest(second), observationDigest(observations))
  assert.equal(again.mapHash, map.mapHash)
  console.log(`playback determinism: mapHash ${map.mapHash.slice(0, 16)} on both runs`)

  // ------------------------------------------------------------------
  // Falsification (a): the naive linearisation.
  // ------------------------------------------------------------------
  assert.throws(
    () => createPlaybackMap({
      mapId: 'playback-map-linear',
      workspaceId: session.workspaceId,
      sessionId: session.sessionId,
      sessionVersion: session.version,
      referenceEpoch: session.referenceEpoch,
      reactionTrackId: track.reaction.trackId,
      referenceTrackId: track.reference.trackId,
      referenceMedia: media.reference,
      reactionMedia: media.reaction,
      pieces: [{
        pieceId: 'piece-000',
        mode: 'playing',
        reactionRange: createTickInterval(0n, media.reaction.durationTicks),
        referenceRange: createTickInterval(0n, media.reaction.durationTicks),
        direction: 'forward',
        confidence: 0.9,
        evidenceRefs: ['fingerprint:0'],
        detectionMethod: 'audio-fingerprint',
      }],
    }),
    (error) => error.code === 'INVALID_ARGUMENT' &&
      /plays reference time the reference does not have/.test(error.message),
  )

  // ------------------------------------------------------------------
  // Falsification (b): assuming the reference is as long as the reaction.
  // ------------------------------------------------------------------
  const lied = buildPlaybackMap({
    mapId: 'playback-map-fixture',
    session,
    reactionTrack: track.reaction,
    referenceTrack: track.reference,
    referenceMedia: { ...media.reference, durationTicks: media.reaction.durationTicks },
    reactionMedia: media.reaction,
    observations,
    policy: POLICY,
  })
  assert.throws(
    () => assert.equal(lied.referenceMedia.durationTicks, seconds(Math.round(referenceProbe.duration))),
    'a reference duration copied from the reaction contradicts what ffprobe measured',
  )
  // And the lie changes the answer: the honest map knows the last piece runs to
  // the end of the reference, the lying one does not.
  assert.ok(map.warnings.includes('reference-exhausted'))
  assert.ok(!lied.warnings.includes('reference-exhausted'))
  assert.notEqual(lied.mapHash, map.mapHash)

  // ------------------------------------------------------------------
  // Falsification (c): contradictory evidence in one window.
  // ------------------------------------------------------------------
  const contested = observations.find((entry) =>
    entry.reactionTick === seconds(4) && entry.referenceTick !== null)
  assert.ok(contested, 'the fourth second of the reaction locked onto the reference')
  const conflicted = buildPlaybackMap({
    mapId: 'playback-map-conflict',
    session,
    reactionTrack: track.reaction,
    referenceTrack: track.reference,
    referenceMedia: media.reference,
    reactionMedia: media.reaction,
    observations: [
      ...observations,
      {
        reactionTick: contested.reactionTick,
        referenceTick: contested.referenceTick + seconds(9),
        confidence: 0.87,
        method: 'audio-fingerprint',
        evidenceRef: 'fingerprint:rival',
        peakRatio: 3.1,
      },
    ],
    policy: POLICY,
  })
  const conflict = conflicted.uncovered.find((entry) => entry.reason === 'conflicting-evidence')
  assert.ok(conflict, 'two plausible references in one window leave the window uncovered')
  assert.ok(conflicted.warnings.includes('conflicting-evidence'))
  assert.ok(
    !conflicted.pieces.some((piece) =>
      piece.reactionRange.start <= contested.reactionTick &&
      piece.reactionRange.end > contested.reactionTick),
    'no piece is invented over evidence that refused to choose',
  )
})
