/** Deterministic noise. `Math.random` would make the sha256 assertions a lie. */
function lcg(seed) {
  let state = seed >>> 0
  return () => {
    state = (Math.imul(state, 1_664_525) + 1_013_904_223) >>> 0
    return state / 4_294_967_296 - 0.5
  }
}

/**
 * One second of the reference: a linear sweep whose start frequency is a
 * permutation of the second index and whose direction alternates.
 *
 * Everything stays under 950 Hz because the correlator decimates to 2 kHz before
 * searching; content above the new Nyquist would alias and the sweep would stop
 * being the identity of its second.
 */
function referenceSecond(index, into, offsetSamples) {
  const start = 180 + 20 * ((index * 7) % REFERENCE_SECONDS)
  const span = index % 2 === 0 ? 150 : -150
  for (let sample = 0; sample < SAMPLE_RATE; sample += 1) {
    const t = sample / SAMPLE_RATE
    const phase = 2 * Math.PI * (start * t + (span * t * t) / 2)
    into[offsetSamples + sample] = 0.55 * Math.sin(phase)
  }
}

function buildReferenceSamples() {
  const samples = new Float64Array(REFERENCE_SECONDS * SAMPLE_RATE)
  for (let second = 0; second < REFERENCE_SECONDS; second += 1) {
    referenceSecond(second, samples, second * SAMPLE_RATE)
  }
  return samples
}

/**
 * The reaction: the reference where it was playing, the reactor's own tone where
 * it was not, and near-silence where the player was hidden.
 *
 * The reactor's voice is broadband noise. Measured on this fixture, that is what
 * separates: a noise window's normalised correlation against the reference peaks
 * between 0.055 and 0.485, while a window that really contains the reference
 * peaks between 0.699 and 1.000. Its *ratio* does not separate at all — noise
 * reaches 8.5, higher than some genuine matches — which is why the detector
 * carries a correlation floor as well as a runner-up test. A steady tone was
 * tried first and was worse: a tone inside the reference's own frequency band
 * correlates strongly with whichever sweep passes through it.
 */
function buildReactionSamples(reference, {
  truth = TRUTH,
  totalSeconds = REACTION_SECONDS,
  seed = 20_260_904,
} = {}) {
  // The table has to tile the recording: every row starts where the previous
  // one ended, and the last ends on the recording's last second. A row that
  // overlapped another would silently repaint it, and a row reaching past
  // `totalSeconds` would have its overhang dropped by TypedArray semantics with
  // nothing raised — both happened here, and both are now a failure.
  let cursor = 0
  for (const segment of truth) {
    assert.equal(
      segment.from,
      cursor,
      `segment ${segment.mode} starts at ${segment.from}s where ${cursor}s was still unwritten`,
    )
    assert.ok(segment.to > segment.from, `segment ${segment.mode} at ${segment.from}s spans nothing`)
    cursor = segment.to
  }
  assert.equal(cursor, totalSeconds, `the table describes ${cursor}s of a ${totalSeconds}s recording`)

  const samples = new Float64Array(totalSeconds * SAMPLE_RATE)
  const noise = lcg(seed)
  for (const segment of truth) {
    const from = segment.from * SAMPLE_RATE
    const to = segment.to * SAMPLE_RATE
    for (let sample = from; sample < to; sample += 1) {
      const t = sample / SAMPLE_RATE
      if (segment.mode === 'hidden') {
        // The player is on screen but muted behind an overlay: room tone only,
        // below the detector's energy floor.
        samples[sample] = 0.004 * noise()
        continue
      }
      if (segment.reference === null) {
        samples[sample] = 0.55 * noise()
        continue
      }
      const referenceSample = Math.round(
        (segment.reference + (sample - from) / SAMPLE_RATE) * SAMPLE_RATE,
      )
      samples[sample] = (reference[referenceSample] ?? 0) + 0.10 * noise()
    }
  }
  return samples
}

function toPcm(samples) {
  const buffer = Buffer.alloc(samples.length * 2)
  for (let index = 0; index < samples.length; index += 1) {
    const value = Math.round(Math.max(-1, Math.min(1, samples[index])) * 32_767)
    buffer.writeInt16LE(value, index * 2)
  }
  return buffer
}

async function encode(input) {
  await execFileAsync(FFMPEG, [
    '-hide_banner', '-nostdin', '-y',
    '-f', 'lavfi', '-i',
    `${input.videoSource}${input.videoSourceSeparator ?? '='}s=320x180:r=${FPS}:d=${input.durationSeconds}`,
    '-f', 's16le', '-ar', String(SAMPLE_RATE), '-ac', '1', '-i', input.pcmPath,
    '-c:v', 'libx264', '-preset', 'ultrafast', '-pix_fmt', 'yuv420p',
    '-c:a', 'aac', '-b:a', '96k', '-ar', String(SAMPLE_RATE), '-ac', '1',
    '-shortest',
    input.outputPath,
  ], { maxBuffer: 64 * 1024 * 1024, timeout: 300_000 })
  return input.outputPath
}

async function buildFixture(workRoot) {
  const referenceSamples = buildReferenceSamples()
  const reactionSamples = buildReactionSamples(referenceSamples)
  const watchedSamples = buildReactionSamples(referenceSamples, {
    truth: WATCHED_TRUTH,
    totalSeconds: WATCHED_SECONDS,
    seed: 20_260_907,
  })
  const referencePcm = join(workRoot, 'reference.pcm')
  const reactionPcm = join(workRoot, 'reaction.pcm')
  const watchedPcm = join(workRoot, 'watched.pcm')
  await writeFile(referencePcm, toPcm(referenceSamples))
  await writeFile(reactionPcm, toPcm(reactionSamples))
  await writeFile(watchedPcm, toPcm(watchedSamples))
  const referencePath = await encode({
    videoSource: 'testsrc2',
    durationSeconds: REFERENCE_SECONDS,
    pcmPath: referencePcm,
    outputPath: join(workRoot, 'reference.mp4'),
  })
  const reactionPath = await encode({
    videoSource: 'color=c=gray',
    // `color` already carries an option, so the size and rate append with ':'.
    videoSourceSeparator: ':',
    durationSeconds: REACTION_SECONDS,
    pcmPath: reactionPcm,
    outputPath: join(workRoot, 'reaction.mp4'),
  })
  const watchedPath = await encode({
    videoSource: 'color=c=gray',
    videoSourceSeparator: ':',
    durationSeconds: WATCHED_SECONDS,
    pcmPath: watchedPcm,
    outputPath: join(workRoot, 'watched.mp4'),
  })
  return { referencePath, reactionPath, watchedPath }
}

