/**
 * Slice S3 against a real PostgreSQL: the proxy render and the final export consume ONE persisted verdict (the sealed State of the
 * exact Version, its sole output's entry, the purpose) and seal what they read into their input hash. Code for a SUPERVISED run
 * (isolated database, migrated and generated by the owner); every identity is unique to this invocation and nothing is cleaned up
 * (sealed rows are append-only).
 *
 * What it proves:
 *   1. An ordinary project: the proxy source read with the light reader (sealed Version + State rows) carries exactly the seal the
 *      full factual rebuild yields; its format is the sealed entry's aspect ratio (the stored `projects.format` is null); the final
 *      source is allowed and seals differently (the purpose is sealed); the immutable read of the Version returns the same seal.
 *   2. A copy never cut is refused for render and for final with `copy-requires-editorial-cut`, by the source readers, by the final
 *      repository before it looks at any approval, and by the owner transaction that admits an operation.
 *   3. The same copy after its editorial cut: the proxy source reads (render verdict allowed); the final export is refused with
 *      `derived-source-perception-authority-required` by the source reader, the final repository (before any approval) and the owner
 *      transaction.
 *   4. A project with several outputs is refused without an explicit variant (`output-variant-required`), served with one, and an
 *      unknown variant is refused; a project whose only output is empty is refused with `empty-project`.
 *   5. A real enqueue seals the State into the operation's input hash; the worker reaches the renderer while the head is that Version
 *      and, once the head moved to a newer Version (a new State), refuses with PERSISTENCE_CONFLICT before it renders anything. The
 *      final repository refuses the same stale Version. The new head's seal differs from the old one, and the old Version still
 *      reads its own seal.
 */
const enabled = process.env.APOLLO_RUN_W66_CONSUMPTION_PROXY_PG === '1'

const WORDS = [
  { word: 'Primeira', start: 0.2, end: 0.7 }, { word: 'frase', start: 0.7, end: 1.1 },
  { word: 'termina', start: 1.1, end: 1.6 }, { word: 'aqui.', start: 1.6, end: 2.0 },
  { word: 'Segunda', start: 3.0, end: 3.5 }, { word: 'frase', start: 3.5, end: 3.9 },
  { word: 'continua', start: 3.9, end: 4.5 }, { word: 'ainda.', start: 4.5, end: 5.0 },
]
const sha = (value) => createHash('sha256').update(String(value)).digest('hex')

test('W66 PostgreSQL proxy render and final export consume one persisted verdict and seal it', { skip: !enabled, timeout: 280_000 }, async () => {
  const run = randomUUID().replaceAll('-', '').slice(0, 10)
  const workspaceId = `w66cpf-${run}-ws`, clientId = `w66cpf-${run}-client`
  const actor = testActor({ workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production', scopes: ['projects:write', 'projects:read', 'media:write'] })
  const db = new PrismaClient()
  try {
    const world = await seedSealedProject(db, { workspaceId, actor, prefix: 'w66cpf', ids: { project: `w66cpf-${run}-project` }, name: 'Consumption world' })
    const directed = await seedDirectedProject(db, { workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production',
      projectId: world.projectId, suffix: `w66cpf${run}`, words: WORDS })
    const projectId = world.projectId
    const operational = new PrismaOperationalOutputBundleRepositoryV3(db)
    const proxy = new PrismaProjectProxyRenderRepository(db)
    const finalRepository = new PrismaProjectFinalExportRepository(db)
    const operations = new PrismaPublicOperationRepository(db)
    const head = await operational.read({ workspaceId, projectId, versionId: directed.versions.directed })
    const headEntry = head.state.document.entries[0]
    const headRow = await db.v2ProjectVersion.findUniqueOrThrow({ where: { id: directed.versions.directed } })
    const refusal = (reason, purpose) => (error) => error?.code === 'PRECONDITION_REQUIRED' && error.details?.reason === reason &&
      (purpose === undefined || error.details?.purpose === purpose)
    const sourceRef = { sourceArtifactId: directed.source.artifactId, sourceManifestId: directed.source.manifestId }

    // The copy forks the head Version, so it is made (and cut) before the project's own head moves in section 5.
    let copyAllocations = 0
    const copy = await duplicateProjectService({ repository: new PrismaProjectDuplicationRepository(db), clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => kind === 'project-media-asset' ? randomUUID() : `w66cpf-${run}-copy-${kind}-${++copyAllocations}` })({
      workspaceId, projectId, expectedVersionId: head.version.id, expectedVersionHash: head.version.baseHash, name: 'Consumption copy', actor,
      idempotency: { clientId, key: `w66cpf-${run}-dup` } })
    const copyScope = { workspaceId, projectId: copy.project.id }
    let childAllocations = 0
    const selectLut = setProjectLutSelectionService({ repository: new PrismaProjectLutSelectionRepository(db), clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => `w66cpf-${run}-child-${kind}-${++childAllocations}` })
    const lut = (base, key) => selectLut({ ...copyScope, baseVersionId: base.id, baseHash: base.baseHash, selection: { mode: 'none' }, actor,
      idempotencyKey: `w66cpf-${run}-${key}`, reason: 'Configuration of a copy.' })
    const configuredOne = await lut(copy.version, 'configure-1')
    const configuredTwo = await lut(configuredOne.version, 'configure-2')
    const configured = await operational.read({ ...copyScope, versionId: configuredTwo.version.id })

    // Admissions the owner transaction refuses, built by hand (the verdict is the first thing it reads; nothing else is looked up).
    const fakeBinding = { ...sourceRef, compilationId: `w66cpf-${run}-compilation`, compilationHash: sha('compilation'), pipelineHash: sha('pipeline') }
    const admit = async (type, project, version, key) => {
      const outputArtifactId = `w66cpf-${run}-out-${key}`, outputManifestId = `w66cpf-${run}-manifest-${key}`
      const editPlanSnapshotId = (await db.v2ProjectVersion.findUniqueOrThrow({ where: { id: version.id } })).editPlanSnapshotId
      const operation = createQueuedPublicOperation({ id: `w66cpf-${run}-op-${key}`, workspaceId, projectId: project, clientId, type,
        target: { type: 'media-artifact', id: outputArtifactId, manifestId: outputManifestId }, createdAt: new Date().toISOString() })
      const common = { projectId: project, projectVersionId: version.id, editPlanSnapshotId, ...sourceRef,
        colorPipelineBindings: [fakeBinding], inputHash: sha(`input-${key}`), outputArtifactId, outputManifestId }
      const context = type === 'project-proxy-render'
        ? { kind: type, ...common, originalFileName: 'w66cpf.mp4' }
        : { kind: type, ...common, projectVersionHash: version.baseHash, directorRunId: `w66cpf-${run}-director`, qualitySnapshotId: `w66cpf-${run}-quality`,
          qualitySnapshotHash: sha('quality'), proxyReviewId: `w66cpf-${run}-review`, proxyReviewHash: sha('review'), proxyArtifactId: `w66cpf-${run}-proxy`,
          outputSpec: { aspectRatio: '16:9', width: 1920, height: 1080, fps: 30, codec: 'h264', audioCodec: 'aac', container: 'mp4', quality: 'final' },
          approval: { actorType: 'api-client', actorId: clientId, approvedAt: new Date().toISOString() }, originalFileName: 'w66cpf-final.mp4' }
      return operations.createOrReplay({ operation, context, authenticationAudit: materializeActorAuditContext(actor),
        idempotencyKey: `w66cpf-${run}-${key}`, requestFingerprint: sha(`request-${key}`) })
    }

    // 2. A copy never cut (it only took configuration children): neither render nor final, from every reader.
    assert.ok(configured.state.document.entries.every((entry) => entry.consumption.status === 'blocked'))
    for (const purpose of ['render', 'final']) {
      await assert.rejects(proxy.readCurrentSource({ ...copyScope, purpose }), refusal('copy-requires-editorial-cut', purpose), `never cut: ${purpose}`)
    }
    await assert.rejects(finalRepository.readApprovedCurrentSource({ ...copyScope, projectVersionId: configuredTwo.version.id, projectVersionHash: configuredTwo.version.baseHash }),
      refusal('copy-requires-editorial-cut', 'final'), 'the final repository refuses before it looks at an approval')
    await assert.rejects(admit('project-proxy-render', copy.project.id, configuredTwo.version, 'never-cut-proxy'), refusal('copy-requires-editorial-cut', 'render'))
    await assert.rejects(admit('project-final-export', copy.project.id, configuredTwo.version, 'never-cut-final'), refusal('copy-requires-editorial-cut', 'final'))
    assert.equal(await db.v2PublicOperation.count({ where: { workspaceId, projectId: copy.project.id, type: { in: ['project-proxy-render', 'project-final-export'] } } }), 0,
      'a refused admission wrote nothing')

    // 3. The cut copy: renderable, never exportable (until it owns perception authority).
    const plan = JSON.parse(head.editPlanSnapshot.contentJson)
    let cutAllocations = 0
    const cut = applyEditorialCutCommandService({ repository: new PrismaEditorialCommandRepository(db), clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => `w66cpf-${run}-cut-${kind}-${++cutAllocations}` })
    const copyCut = await cut({ ...copyScope, baseVersionId: configured.version.id, baseHash: configured.version.baseHash,
      sourceTranscriptId: plan.retimedTranscript.sourceTranscriptId, variantId: configured.state.document.entries[0].variantId,
      rules: [{ id: 'termina', label: 'termina', alternatives: ['termina'] }],
      exclusionOverrides: [{ sourceStartSeconds: 1.1, sourceEndSeconds: 2.0, ruleIds: ['termina'], reason: 'The reviewer cuts "termina aqui."' }],
      reason: 'Cut a copy.', actor, idempotency: { clientId, key: `w66cpf-${run}-cut` } })
    const copyHead = copyCut.version
    const copyHeadSnapshotId = (await db.v2ProjectVersion.findUniqueOrThrow({ where: { id: copyHead.id } })).editPlanSnapshotId
    const copyRender = await proxy.readCurrentSource({ ...copyScope, purpose: 'render' })
    assert.equal(copyRender.projectVersionId, copyHead.id)
    assert.equal(copyRender.outputConsumption.seal.purpose, 'render')
    assert.equal(copyRender.outputConsumption.seal.projectVersionHash, copyHead.baseHash)
    assert.equal(copyRender.format, outputEntryAspectRatio(copyCut.outputBundle.state.document.entries[0]))
    await assert.rejects(proxy.readCurrentSource({ ...copyScope, purpose: 'final' }), refusal('derived-source-perception-authority-required', 'final'))
    await assert.rejects(finalRepository.readApprovedCurrentSource({ ...copyScope, projectVersionId: copyHead.id, projectVersionHash: copyHead.baseHash }),
      refusal('derived-source-perception-authority-required', 'final'), 'the final repository refuses before it looks at an approval')
    await assert.rejects(finalRepository.readImmutableApprovedSource({ ...copyScope, projectVersionId: copyHead.id, projectVersionHash: copyHead.baseHash,
      editPlanSnapshotId: copyHeadSnapshotId, directorRunId: 'unused', qualitySnapshotId: 'unused', qualitySnapshotHash: sha('q'), proxyReviewId: 'unused',
      proxyReviewHash: sha('r'), proxyArtifactId: 'unused', ...sourceRef }), refusal('derived-source-perception-authority-required', 'final'))
    await assert.rejects(admit('project-final-export', copy.project.id, copyHead, 'cut-final'), refusal('derived-source-perception-authority-required', 'final'))
    assert.equal(await db.v2PublicOperation.count({ where: { workspaceId, projectId: copy.project.id, type: 'project-final-export' } }), 0)

    // 1. The ordinary project: the light reader yields the very seal the factual rebuild yields.
    const render = await proxy.readCurrentSource({ workspaceId, projectId })
    const expectedSeal = outputConsumptionSealV3(head.version, head.state, headEntry, 'render')
    assert.equal(render.projectVersionId, directed.versions.directed)
    assert.deepEqual(render.outputConsumption.seal, expectedSeal)
    assert.equal(render.outputConsumption.sealHash, outputConsumptionSealHashV3(expectedSeal))
    assert.equal(render.format, headEntry.spec.output.aspectRatio, 'the sealed entry names the format')
    assert.equal((await db.v2Project.findUniqueOrThrow({ where: { id: projectId } })).format, null, 'the stored project format is not an authority')
    const audit = await requirePersistedOutputConsumptionV3(db, { workspaceId, projectId, versionId: directed.versions.directed, purpose: 'render', reconstruct: true })
    assert.equal(audit.sealHash, render.outputConsumption.sealHash, 'the cheap read is as authoritative as the full factual rebuild')
    const inTransaction = await db.$transaction((tx) => requirePersistedOutputConsumptionV3(tx, { workspaceId, projectId, versionId: directed.versions.directed, purpose: 'render' }),
      { timeout: 5000 })
    assert.equal(inTransaction.sealHash, render.outputConsumption.sealHash, 'the light reader runs inside an owner transaction')
    const final = await proxy.readCurrentSource({ workspaceId, projectId, purpose: 'final' })
    assert.equal(final.outputConsumption.seal.purpose, 'final')
    assert.notEqual(final.outputConsumption.sealHash, render.outputConsumption.sealHash, 'the purpose is part of the seal')
    const exact = await proxy.readImmutableSource({ workspaceId, projectId, projectVersionId: directed.versions.directed,
      editPlanSnapshotId: headRow.editPlanSnapshotId, ...sourceRef })
    assert.equal(exact.outputConsumption.sealHash, render.outputConsumption.sealHash)
    assert.equal(await finalRepository.readApprovedCurrentSource({ workspaceId, projectId, projectVersionId: directed.versions.directed,
      projectVersionHash: head.version.baseHash }), null, 'allowed by the verdict, then no approval (a Director run alone approves nothing)')
    assert.notEqual(projectProxyRenderInputHash({ source: render, colorPipelineBindings: [] }), projectProxyRenderInputHash({ source: final, colorPipelineBindings: [] }))

    // 4. Several outputs, an unknown variant, an empty project.
    const second = await seedSealedProject(db, { workspaceId, actor, prefix: 'w66cpf-two', ids: { project: `w66cpf-${run}-two` }, name: 'Two outputs' })
    let variantAllocations = 0
    await createProjectOutputVariantService({ repository: operational, clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => `w66cpf-${run}-variant-${kind}-${++variantAllocations}` })({ ...variantBodyFor({ aspectRatio: '1:1' }), workspaceId, projectId: second.projectId,
      baseVersionId: second.head.version.id, baseHash: second.head.version.baseHash, actor, idempotencyKey: `w66cpf-${run}-second-variant` })
    for (const purpose of ['render', 'final']) {
      await assert.rejects(proxy.readCurrentSource({ workspaceId, projectId: second.projectId, purpose }), refusal('output-variant-required', purpose))
      await assert.rejects(proxy.readCurrentSource({ workspaceId, projectId: second.projectId, purpose, variantId: 'w66cpf-no-such-variant' }), refusal('output-variant-unknown'))
      await assert.rejects(proxy.readCurrentSource({ workspaceId, projectId: second.projectId, purpose, variantId: second.variantId }), refusal('empty-project', purpose),
        'a named variant with nothing materialized is an empty project')
    }
    const lone = await seedSealedProject(db, { workspaceId, actor, prefix: 'w66cpf-one', ids: { project: `w66cpf-${run}-one` }, name: 'Empty output' })
    for (const purpose of ['render', 'final']) {
      await assert.rejects(proxy.readCurrentSource({ workspaceId, projectId: lone.projectId, purpose }), refusal('empty-project', purpose))
    }

    // 5. A real enqueue seals the State; the head moving makes the sealed worker refuse before it renders anything.
    await registerColorPipeline(db, { workspaceId, projectId, actor, artifactId: directed.source.artifactId, manifestId: directed.source.manifestId })
    let allocations = 0
    const colorPipelines = new PrismaColorPipelineCompilationRepository(db)
    const queued = await enqueueProjectProxyRenderService({ projects: proxy, operations, colorPipelines, clock: () => new Date(),
      createId: (kind) => `w66cpf-${run}-real-${kind}-${++allocations}` })({
      workspaceId, projectId, expectedProjectVersionId: directed.versions.directed, actor, idempotencyKey: `w66cpf-${run}-real-enqueue` })
    const detail = await db.v2ProjectProxyRenderOperation.findUniqueOrThrow({ where: { operationId: queued.operation.id } })
    assert.equal(detail.projectVersionId, directed.versions.directed)
    const bindings = JSON.parse(detail.colorPipelineBindingsJson)
    assert.equal(detail.inputHash, projectProxyRenderInputHash({ source: exact, colorPipelineBindings: bindings }), 'the stored input hash is the one over the sealed consumption')
    assert.notEqual(detail.inputHash, projectProxyRenderInputHash({ source: { ...exact, outputConsumption: {
      seal: { ...exact.outputConsumption.seal, outputSpecRevisionId: 'another-revision' }, sealHash: sha('another-revision') } }, colorPipelineBindings: bindings }))

    let renders = 0
    const worker = runNextProjectProxyRenderOperationService({
      operations, projects: proxy, colorPipelines, colorPlans: new PrismaProjectColorPlanRepository(db),
      artifacts: { async persistOrReplay() { throw new Error('nothing may be persisted') } },
      storage: { async promoteDerived() { throw new Error('nothing may be promoted') } },
      renderer: { async render() { renders += 1; throw new Error('W66_RENDER_REACHED') }, async cleanup() {} },
      renderElementMaps: { async persistOrReplay() { throw new Error('nothing may be mapped') } },
      perceptionTimelines: { async findLatest() { return null } },
      // The worker refuses a grade other than the one its source was read with (W70 readiness R2, 8e63d11a): the materialization this test stands in for
      // is the REAL effective LUT selection of the Version (the explicit 'none' the seeded chain carries), read the way the materializer reads it.
      luts: {
        async materialize(input) {
          const effective = await new PrismaProjectLutSelectionRepository(db).readEffectiveForVersion(input)
          assert.ok(effective, 'the seeded chain carries an explicit project LUT selection')
          return { selectionId: effective.selection.id, selectionHash: effective.selection.selectionHash, lutPaths: {} }
        },
        async cleanup() {},
      },
      sources: { async materialize(input) { return { path: `${process.cwd()}/.w66cpf-not-read/${input.artifactKey}`, sha256: input.sha256, byteSize: input.byteSize } }, async cleanup() {} },
      clock: () => new Date(), leaseDurationMs: 60_000, heartbeatIntervalMs: 5_000, retryBaseDelayMs: 1, retryMaxDelayMs: 1,
    })
    const target = { workspaceId, operationId: queued.operation.id }
    const reached = await worker(`w66cpf-${run}-worker-1`, target)
    assert.equal(reached.status, 'retrying', 'while the head is the sealed Version the worker passes the verdict and the input hash and reaches the renderer')
    assert.equal(renders, 1)

    // The final repository agrees about the same Version while it is the head (no approval exists, so no source) ...
    const immutableFinal = { workspaceId, projectId, projectVersionId: directed.versions.directed, projectVersionHash: head.version.baseHash,
      editPlanSnapshotId: headRow.editPlanSnapshotId, directorRunId: directed.director.runId, qualitySnapshotId: directed.director.qualitySnapshotId,
      qualitySnapshotHash: directed.director.qualitySnapshotHash, proxyReviewId: 'none', proxyReviewHash: sha('none'), proxyArtifactId: 'none', ...sourceRef,
      requireCurrent: true }
    assert.equal(await finalRepository.readImmutableApprovedSource(immutableFinal), null)

    // ... then the head moves: a child Command commits a newer Version (a new State).
    const moved = await selectLut({ workspaceId, projectId, baseVersionId: head.version.id, baseHash: head.version.baseHash, selection: { mode: 'none' }, actor,
      idempotencyKey: `w66cpf-${run}-moved`, reason: 'A newer Version moves the head.' })
    assert.equal((await db.v2Project.findUniqueOrThrow({ where: { id: projectId } })).currentVersionId, moved.version.id)
    const newer = await proxy.readCurrentSource({ workspaceId, projectId })
    assert.equal(newer.projectVersionId, moved.version.id)
    assert.notEqual(newer.outputConsumption.seal.outputStateId, render.outputConsumption.seal.outputStateId)
    assert.notEqual(newer.outputConsumption.seal.outputStateHash, render.outputConsumption.seal.outputStateHash)
    assert.notEqual(newer.outputConsumption.sealHash, render.outputConsumption.sealHash)
    assert.notEqual(projectProxyRenderInputHash({ source: newer, colorPipelineBindings: bindings }), detail.inputHash, 'the new head is another input')
    const old = await proxy.readImmutableSource({ workspaceId, projectId, projectVersionId: directed.versions.directed,
      editPlanSnapshotId: headRow.editPlanSnapshotId, ...sourceRef })
    assert.equal(old.outputConsumption.sealHash, render.outputConsumption.sealHash, 'the old Version still reads its own State')
    await assert.rejects(proxy.readImmutableSource({ workspaceId, projectId, projectVersionId: directed.versions.directed,
      editPlanSnapshotId: headRow.editPlanSnapshotId, ...sourceRef, requireCurrent: true }), (error) => error.code === 'PERSISTENCE_CONFLICT')
    await assert.rejects(finalRepository.readImmutableApprovedSource(immutableFinal), (error) => error.code === 'PERSISTENCE_CONFLICT')

    await new Promise((resolve) => setTimeout(resolve, 50))
    const stale = await worker(`w66cpf-${run}-worker-2`, target)
    assert.equal(stale.status, 'failed', 'the operation sealed to the old State is refused')
    assert.equal(renders, 1, 'nothing was rendered for the stale State')
    const failed = await db.v2PublicOperation.findUniqueOrThrow({ where: { id: queued.operation.id } })
    assert.equal(failed.status, 'failed')
    assert.equal(failed.errorCode, 'persistence_conflict')
    assert.equal(await db.v2ProjectMediaAsset.count({ where: { workspaceId, projectId, role: 'editorial-proxy' } }), 0, 'nothing was published')
  } finally { await db.$disconnect() }
})
