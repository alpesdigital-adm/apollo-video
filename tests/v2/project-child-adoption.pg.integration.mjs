/**
 * W66 child Commands that adopt the persisted observed receipts of the project's other recordings, against a real
 * PostgreSQL. Code for a SUPERVISED run (it has not been executed by its author): isolated schema, migrated and
 * generated by the owner, reset only after every client disconnects. Sealed rows are append-only and every identity
 * is unique to this invocation, so nothing is cleaned up.
 *
 * What it proves, in order:
 *   1. A child Version whose plan consumes two recordings the parent State observes none of is sealed over the
 *      receipts their own ingests persisted, and survives the deferred database guard and a factual read-back.
 *   2. A later child adopts only the recording its parent does not already observe.
 *   3. Everything fail-closed: a receipt that was never persisted, rights that moved between seal and commit, rights
 *      that deny the use, and an origin that lies about its adoptions (refused by the guard itself) leave no residue.
 */
const enabled = process.env.APOLLO_RUN_W66_CHILD_ADOPTION_PG === '1'
const transactionOptions = { maxWait: 5000, timeout: 60_000 }

test('W66 PostgreSQL child Commands adopt persisted observed receipts of other recordings and refuse everything else', { skip: !enabled, timeout: 300_000 }, async () => {
  const runId = randomUUID().replaceAll('-', '').slice(0, 12)
  const workspaceId = `w66ad-${runId}-workspace`, projectId = `w66ad-${runId}-project`, clientId = `w66ad-${runId}-client`
  const createdAt = new Date().toISOString()
  const scope = { workspaceId, projectId }
  const db = new PrismaClient()
  try {
    await db.v2Workspace.create({ data: { id: workspaceId, slug: `w66ad-${runId}`, name: 'W66 child adoption PG', createdAt: new Date(createdAt), updatedAt: new Date(createdAt) } })
    await db.v2ApiClient.create({ data: { id: clientId, workspaceId, name: 'Child adoption actor', allowedEnvironmentsJson: '["sandbox"]',
      scopeGrantsJson: '["projects:write","media:write"]', createdBy: clientId, createdAt: new Date(createdAt) } })
    const auditContext = createExternalAuditContext({ workspaceId, clientId, credentialId: `w66ad-${runId}-credential`, environment: 'sandbox' })
    const actor = Object.freeze({ ...auditContext, auditContext, scopes: new Set(['projects:write']), authenticationKind: 'bearer',
      clientKillSwitchEngaged: false, workspaceKillSwitchEngaged: false, clientAccessStatus: 'active', workspaceAccessStatus: 'active' })
    const audit = materializeActorAuditContext(actor)

    // The project: root and one explicit output variant, through the production services and repositories.
    const world = await seedSealedProject(db, { workspaceId, actor, prefix: `w66ad-${runId}`, ids: { project: projectId } })
    assert.equal(world.head.version.outputContractVersion, 3)

    // ---- the recordings: what each ingest persisted (artifacts, manifests, links, operation, receipt) and their rights
    const artifacts = new PrismaMediaArtifactRepository(db)
    const rights = async (artifactId, label, status = 'approved', sequence = 1) => {
      const snapshot = createAssetRightsSnapshot({ id: `w66ad-${runId}-rights-${label}-${sequence}`, workspaceId, artifactId, sequence,
        draft: { status, allowedUses: status === 'approved' ? ['rendering', 'editorial-reuse'] : [], prohibitedUses: [], sourceNote: `${label}-${sequence}`, consent: { status: 'not-required', allowedUses: [] } },
        createdBy: { type: 'api-client', id: clientId }, createdAt })
      await persistCurrentRights(db, snapshot)
      return snapshot
    }
    const persistRecording = async (label, { status = 'approved', persistReceipt = true } = {}) => {
      const slug = `w66ad-${runId}-${label}`, names = recordingNames(slug)
      const receipt = controlledNormalization(projectId, scope, { slug, createdAt, nativeFps: 30, durationFrames: 60 })
      const d = receipt.document
      if (persistReceipt) {
        for (const [fact, lineageIds] of [[d.source, []], [d.derivative, [d.source.artifactId]]]) {
          await artifacts.persistOrReplay({ workspaceId, artifactId: fact.artifactId, manifestId: fact.manifestId, lineageIds, manifest: fact.manifest, createdAt })
        }
        for (const [fact, role] of [[d.source, 'source-master'], [d.derivative, 'editing-proxy']]) {
          await db.v2ProjectMediaAsset.create({ data: { id: randomUUID(), workspaceId, projectId, artifactId: fact.artifactId, role,
            originalFileName: `${label}-${role}.mp4`, createdAt: new Date(createdAt) } })
        }
        const queued = createQueuedPublicOperation({ ...scope, id: d.operationId, clientId, type: 'media-ingest',
          target: { type: 'media-artifact', id: d.source.artifactId, manifestId: d.source.manifestId }, createdAt })
        const operation = succeedPublicOperation(advancePublicOperationPhase(startPublicOperationAttempt(queued, createdAt), 'persisting', createdAt), createdAt)
        await db.v2PublicOperation.create({ data: { ...scope, id: operation.id, clientId, ...externalActorAuditData(audit, workspaceId, clientId),
          type: operation.type, status: operation.status, phase: operation.phase, targetType: operation.target.type, targetId: operation.target.id,
          progressCompleted: operation.progress.completed, progressTotal: operation.progress.total, progressUnit: operation.progress.unit,
          cancelable: operation.cancelable, retryable: operation.retryable, attempt: operation.attempt, maxAttempts: operation.maxAttempts,
          idempotencyKey: `w66ad-${runId}-${label}-ingest`, requestFingerprint: calculateCanonicalHash({ ingest: slug }),
          resultJson: stableSerialize(operation.result), createdAt: new Date(operation.createdAt), updatedAt: new Date(operation.updatedAt),
          startedAt: new Date(operation.startedAt), completedAt: new Date(operation.completedAt) } })
        await db.v2OutputNormalizationReceipt.create({ data: { id: d.id, workspaceId, projectId, operationId: d.operationId,
          sourceArtifactId: d.source.artifactId, sourceManifestId: d.source.manifestId, sourceManifestHash: d.source.manifest.manifestHash,
          derivativeArtifactId: d.derivative.artifactId, derivativeManifestId: d.derivative.manifestId,
          derivativeManifestHash: d.derivative.manifest.manifestHash, receiptJson: serializeOutputCanonicalJson(d), receiptHash: receipt.receiptHash,
          createdAt: new Date(d.createdAt) } })
        // The source and its proxy are each rendered under their own approved grant.
        const sourceRights = await rights(d.source.artifactId, `${label}-source`, status)
        await rights(d.derivative.artifactId, `${label}-proxy`)
        return { slug, names, receipt, sourceRights }
      }
      return { slug, names, receipt, sourceRights: null }
    }

    // ---- a plan that cuts to `labels` (each recording's own audio), compiled from a real initial plan
    const planOver = (parent, labels, recordings, versionId) => {
      const transcript = createMediaTranscript({ language: 'pt-BR', text: 'Fonte controlada.', words: [{ word: 'Fonte', start: 0, end: 1 }, { word: 'controlada.', start: 1, end: 2 }],
        segments: [{ id: 0, start: 0, end: 2, text: 'Fonte controlada.' }], provider: 'controlled', model: 'explicit-domain-fixture' })
      const first = recordings[labels[0]]
      const base = compileInitialSourceEditPlan({ id: `edit-plan-${versionId}`, projectVersionId: versionId, transcriptId: `w66ad-${runId}-transcript`, transcript,
        sourceArtifactId: first.names.sourceArtifactId, sourceDurationSeconds: 2, fps: 30, createdAt: new Date(Date.parse(parent.version.createdAt) + 5000).toISOString() })
      const clips = labels.map((label, index) => ({ id: `clip-adopt-${index + 1}`, sourceArtifactId: recordings[label].names.sourceArtifactId,
        sourceInFrame: index * 30, sourceOutFrame: index * 30 + 30, timelineInFrame: index * 30, timelineOutFrame: index * 30 + 30, rate: 1 }))
      const ids = labels.map((label) => recordings[label].names.sourceArtifactId)
      return { ...JSON.parse(stableSerialize(base)), durationFrames: clips.length * 30, videoTracks: [{ ...base.videoTracks[0], clips }], subtitleTracks: [],
        sources: ids.map((id) => ({ id, artifactId: id, kind: 'video', durationSeconds: 2 })), lineageRefs: ids }
    }
    let ordinal = 0
    const sealChild = async (label, labels, recordings, { offered } = {}) => {
      ordinal += 1
      const head = await db.v2Project.findUniqueOrThrow({ where: { id: projectId } })
      const parent = await readPersistedOperationalOutputBundleV3(db, { ...scope, versionId: head.currentVersionId })
      const versionId = `w66ad-${runId}-version-${label}`, at = new Date(Date.parse(parent.version.createdAt) + 10_000).toISOString()
      const plan = { ...planOver(parent, labels, recordings, versionId), createdAt: at }
      const command = createEditCommand({ ...scope, id: `w66ad-${runId}-command-${label}`, baseVersionId: parent.version.id, baseHash: parent.version.baseHash,
        author: { type: 'api-client', id: clientId }, type: 'apply-review-patch', scope: { project: true }, payload: { schemaVersion: 1 },
        idempotencyKey: `w66ad-${runId}-key-${label}`, createdAt: at })
      const base = operationalBundlePlanV3(parent)
      const editPlanSnapshot = createProjectSnapshot({ ...scope, id: `w66ad-${runId}-snapshot-${label}`, kind: 'edit-plan', contentSchemaVersion: base.contentSchemaVersion,
        contentJson: stableSerialize(plan), contentHash: calculateCanonicalHash(plan), createdAt: at })
      const missing = labels.map((item) => recordings[item].names.sourceArtifactId)
      const adoptable = offered ?? await readAdoptableObservationsV3(db, { ...scope, sourceArtifactIds: missing })
      let counter = 0
      const bundle = transitionProjectOutputState({ parent, command, audit, requestFingerprint: calculateCanonicalHash({ child: label }), editPlanSnapshot,
        allocation: { ...scope, resultVersionId: versionId, stateId: `w66ad-${runId}-state-${label}`, parentVersionId: parent.version.id, sequence: parent.version.sequence + 1,
          createdBy: clientId, createdAt: at },
        createMaterializationId: () => `w66ad-${runId}-materialization-${label}-${++counter}`, adoptable })
      return { parent, bundle }
    }
    // The Version row first (the head points at it), then the head, compare-and-swap on the parent.
    const commit = (parent, bundle) => db.$transaction(async (tx) => {
      await commitProjectVersionWithOutputState(tx, bundle)
      const moved = await tx.v2Project.updateMany({ where: { id: projectId, workspaceId, currentVersionId: parent.version.id }, data: { currentVersionId: bundle.version.id } })
      assert.equal(moved.count, 1)
      await settleDeferredOutputGuards(tx)
    }, transactionOptions)
    const residue = async (bundle) => ({
      versions: await db.v2ProjectVersion.count({ where: { id: bundle.version.id } }),
      commands: await db.v2EditCommand.count({ where: { id: bundle.origin.command.id } }),
      head: (await db.v2Project.findUniqueOrThrow({ where: { id: projectId } })).currentVersionId,
    })

    const recordings = {}
    for (const label of ['cam-a', 'cam-b', 'cam-c']) recordings[label] = await persistRecording(label)

    // ---- 1. two recordings the parent State observes none of
    const first = await sealChild('first', ['cam-a', 'cam-b'], recordings)
    assert.deepEqual(first.bundle.origin.adoptions.map((a) => a.sourceArtifactId), [recordings['cam-a'].names.sourceArtifactId, recordings['cam-b'].names.sourceArtifactId].sort())
    for (const adoption of first.bundle.origin.adoptions) {
      const recording = Object.values(recordings).find((item) => item.names.sourceArtifactId === adoption.sourceArtifactId)
      assert.equal(adoption.receiptHash, recording.receipt.receiptHash)
      assert.equal(adoption.rights.snapshotId, recording.sourceRights.id)
    }
    await commit(first.parent, first.bundle)
    const stored = await readPersistedOperationalOutputBundleV3(db, { ...scope, versionId: first.bundle.version.id })
    assert.equal(stored.version.baseHash, first.bundle.version.baseHash)
    assert.deepEqual(stored.origin.adoptions, first.bundle.origin.adoptions)
    const [{ n: joined }] = await db.$queryRawUnsafe('SELECT count(*)::int AS n FROM output_materialization_normalizations WHERE "materializationId" IN (SELECT id FROM output_materializations WHERE "resultVersionId"=$1)', first.bundle.version.id)
    assert.equal(joined, 2, 'the materialization joins both adopted receipts')

    // ---- 2. a later child adopts only the recording its parent does not already observe
    const second = await sealChild('second', ['cam-a', 'cam-c'], recordings)
    assert.deepEqual(second.bundle.origin.adoptions.map((a) => a.sourceArtifactId), [recordings['cam-c'].names.sourceArtifactId])
    await commit(second.parent, second.bundle)
    assert.equal((await db.v2Project.findUniqueOrThrow({ where: { id: projectId } })).currentVersionId, second.bundle.version.id)

    // ---- 3. fail-closed (each leaves no version, no Command and the head where it was)
    const guarded = await sealChild('guard', ['cam-a', 'cam-b'], recordings)
    const before = await residue(guarded.bundle)

    // 3a. a receipt that was never persisted cannot be adopted
    const ghost = await persistRecording('ghost', { persistReceipt: false })
    const unpersisted = await sealChild('unpersisted', ['cam-a', 'ghost'], { ...recordings, ghost },
      { offered: [{ normalization: ghost.receipt, rights: { snapshotId: 'rights-ghost', snapshotHash: 'e'.repeat(64), revision: 1 } }] })
    const unpersistedBefore = await residue(unpersisted.bundle)
    await assert.rejects(() => commit(unpersisted.parent, unpersisted.bundle), (error) => error.code === 'PERSISTENCE_CONFLICT')
    assert.deepEqual(await residue(unpersisted.bundle), unpersistedBefore)

    // 3b. rights that moved between seal and commit make the Command stale
    const stale = await sealChild('stale', ['cam-a', 'cam-b'], recordings)
    await rights(recordings['cam-b'].names.sourceArtifactId, 'cam-b-source-again', 'approved', 2)
    const staleBefore = await residue(stale.bundle)
    await assert.rejects(() => commit(stale.parent, stale.bundle), (error) => error.code === 'VERSION_CONFLICT')
    assert.deepEqual(await residue(stale.bundle), staleBefore)

    // 3c. rights that deny the use at commit
    const denied = await persistRecording('denied', { status: 'revoked' })
    const refused = await sealChild('refused', ['cam-a', 'denied'], { ...recordings, denied })
    await assert.rejects(() => commit(refused.parent, refused.bundle), (error) => error.code === 'ASSET_RIGHTS_BLOCKED')

    // 3d. the database guard refuses an origin that lies about its adoptions, whatever the application did
    const lying = await sealChild('lying', ['cam-a', 'cam-b'], recordings)
    const lyingBefore = await residue(lying.bundle)
    for (const [label, lie] of [
      ['drops its adoptions', (origin) => ({ ...origin, adoptions: [] })],
      ['moves the rights revision', (origin) => ({ ...origin, adoptions: origin.adoptions.map((a) => ({ ...a, rights: { ...a.rights, revision: a.rights.revision + 1 } })) })],
      ['names another receipt hash', (origin) => ({ ...origin, adoptions: origin.adoptions.map((a, i) => (i === 0 ? { ...a, receiptHash: 'f'.repeat(64) } : a)) })],
    ]) {
      const forged = new Proxy(db, { get(target, key) {
        if (key !== '$transaction') { const value = Reflect.get(target, key); return typeof value === 'function' ? value.bind(target) : value }
        return (action, options) => target.$transaction(async (tx) => action(new Proxy(tx, { get(transaction, property) {
          if (property === '$executeRawUnsafe') return (query, ...values) => {
            if (query.startsWith('INSERT INTO "output_operational_bundles" (')) {
              const columns = query.slice(query.indexOf('(') + 1, query.indexOf(')')).split(',').map((name) => name.replaceAll('"', ''))
              // A consistent lie: the origin is rewritten in its own column and in the bundle, and every seal recomputed, so
              // the table's own checks pass and only the State guard can see that the adoptions do not hold.
              const sha = (text) => createHash('sha256').update(text, 'utf8').digest('hex')
              const at = (name) => columns.indexOf(name)
              const origin = lie(JSON.parse(values[at('originJson')]))
              values[at('originJson')] = serializeOutputCanonicalJson(origin)
              values[at('originHash')] = sha(values[at('originJson')])
              const bundle = JSON.parse(values[at('bundleJson')])
              values[at('bundleJson')] = serializeOutputCanonicalJson({ ...bundle, origin })
              values[at('bundleHash')] = sha(values[at('bundleJson')])
            }
            return transaction.$executeRawUnsafe(query, ...values)
          }
          const value = Reflect.get(transaction, property)
          return typeof value === 'function' ? value.bind(transaction) : value
        } })), options)
      } })
      await assert.rejects(() => forged.$transaction(async (tx) => {
        await commitProjectVersionWithOutputState(tx, lying.bundle)
        await tx.v2Project.updateMany({ where: { id: projectId, workspaceId, currentVersionId: lying.parent.version.id }, data: { currentVersionId: lying.bundle.version.id } })
        await settleDeferredOutputGuards(tx)
      }, transactionOptions), (error) => String(error.meta?.message ?? error.message).includes('W66v3'), label)
      assert.deepEqual(await residue(lying.bundle), lyingBefore, label)
    }
    assert.deepEqual(await residue(guarded.bundle), before, 'the guard cases left the head and the history where they were')
  } finally {
    await db.$disconnect()
  }
})
