import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import test from 'node:test'

import { PrismaClient } from '../../generated/prisma-v2/index.js'
import { enqueueProjectProxyRenderAfterCommandService, enqueueProjectProxyRenderService } from '../../src/v2/application/enqueue-project-proxy-render.ts'
import { PrismaColorPipelineCompilationRepository } from '../../src/v2/infrastructure/prisma/color-pipeline-compilation-repository.ts'
import { PrismaProjectProxyRenderRepository } from '../../src/v2/infrastructure/prisma/project-proxy-render-repository.ts'
import { PrismaPublicOperationRepository } from '../../src/v2/infrastructure/prisma/public-operation-repository.ts'
import { seedTwoOutputIngestedProject } from './helpers/multi-output-pg-world.mjs'
import { seedIngestedProject, testActor } from './helpers/pg-output-world.mjs'
import { registerColorPipeline } from './helpers/review-edit-world.mjs'

/**
 * The proxy a project-wide Command asks for after it committed (W70 rehearsal defect), against a real PostgreSQL. Code for a SUPERVISED
 * run (isolated database, migrated and generated by the owner); every identity is unique to this invocation and nothing is cleaned up.
 *
 *   1. A project with TWO outputs: the answer after the Command's commit is "per output", listing both stable variant ids with their
 *      aspect ratio, read from the State the Command sealed. It consumes no render source, writes no operation, moves no head, and asking
 *      again answers the same. Each listed output's proxy is then requested with its variantId and is admitted (the answer is true).
 *   2. A project with ONE output keeps its contract: the proxy is enqueued, and the same request replays the same operation.
 */
const enabled = process.env.APOLLO_RUN_W66_MULTI_OUTPUT_COMMAND_PROXY_PG === '1'

test('W66 PostgreSQL a Command on a project with two outputs defers the per-output proxies instead of refusing after its commit', { skip: !enabled, timeout: 280_000 }, async () => {
  const run = randomUUID().replaceAll('-', '').slice(0, 10)
  const workspaceId = `w66cp-${run}-ws`, clientId = `w66cp-${run}-client`
  const actor = testActor({ workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production', scopes: ['projects:write', 'projects:read', 'media:write'] })
  const db = new PrismaClient()
  try {
    const proxy = new PrismaProjectProxyRenderRepository(db)
    const operations = new PrismaPublicOperationRepository(db)
    const colorPipelines = new PrismaColorPipelineCompilationRepository(db)
    let allocations = 0
    const dependencies = { projects: proxy, operations, colorPipelines, clock: () => new Date(), createId: (kind) => `w66cp-${run}-${kind}-${++allocations}` }
    const afterCommand = enqueueProjectProxyRenderAfterCommandService(dependencies)
    const plain = enqueueProjectProxyRenderService(dependencies)
    const state = async (projectId) => ({
      operations: await db.v2PublicOperation.count({ where: { workspaceId, projectId, type: 'project-proxy-render' } }),
      details: await db.v2ProjectProxyRenderOperation.count({ where: { workspaceId, projectId } }),
      versions: await db.v2ProjectVersion.count({ where: { workspaceId, projectId } }),
      head: (await db.v2Project.findUniqueOrThrow({ where: { id: projectId } })).currentVersionId,
    })

    // ---- 1. two outputs
    const two = await seedTwoOutputIngestedProject(db, { workspaceId, actor, prefix: 'w66cp', ids: { project: `w66cp-${run}-two` } })
    const scope = { workspaceId, projectId: two.projectId }
    await registerColorPipeline(db, { ...scope, actor, artifactId: two.recording.names.sourceArtifactId, manifestId: two.recording.names.sourceManifestId })
    const ask = (key, extra = {}) => afterCommand({ ...scope, expectedProjectVersionId: two.head.version.id, actor, idempotencyKey: `w66cp-${run}-${key}`, ...extra })
    // The plain enqueue is what the routes used to call right after the commit: with two outputs it refused, and the Command was already in.
    await assert.rejects(plain({ ...scope, expectedProjectVersionId: two.head.version.id, actor, idempotencyKey: `w66cp-${run}-plain` }),
      (error) => error?.code === 'PRECONDITION_REQUIRED' && error.details?.reason === 'output-variant-required')
    const before = await state(two.projectId)
    const first = await ask('defer-1')
    assert.equal(first.status, 'per-output-request-required')
    assert.equal(first.reason, 'output-variant-required')
    const expected = [[two.verticalVariantId, '9:16'], [two.wideVariantId, '16:9']].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    assert.deepEqual(first.outputs.map((output) => [output.variantId, output.aspectRatio]), expected, 'both outputs of the sealed State, with their aspect ratios')
    assert.deepEqual(await state(two.projectId), before, 'the deferral wrote nothing and moved no head')
    assert.deepEqual(await ask('defer-2'), first, 'asking again answers the same')
    assert.deepEqual(await state(two.projectId), before)

    // Each output's proxy is requested by name and admitted: what the answer promised is true.
    const queued = []
    for (const [variantId] of expected) {
      queued.push(await plain({ ...scope, expectedProjectVersionId: two.head.version.id, variantId, actor, idempotencyKey: `w66cp-${run}-proxy-${variantId}` }))
    }
    assert.equal(new Set(queued.map((item) => item.operation.id)).size, 2)
    assert.equal((await state(two.projectId)).operations, 2)
    assert.deepEqual(await ask('defer-3'), first, 'the answer after the proxies were requested is still the per-output one (the Command does not choose)')
    // A caller that names the output (a manual edit's view) is enqueued for it, replaying the request already admitted.
    const named = await afterCommand({ ...scope, expectedProjectVersionId: two.head.version.id, variantId: expected[0][0], actor, idempotencyKey: `w66cp-${run}-proxy-${expected[0][0]}` })
    assert.equal(named.status, 'enqueued')
    assert.equal(named.operation.id, queued[0].operation.id)
    assert.equal((await state(two.projectId)).operations, 2, 'no third operation')

    // ---- 2. one output
    const one = await seedIngestedProject(db, { workspaceId, actor, prefix: 'w66cp1', ids: { project: `w66cp-${run}-one` } })
    const oneScope = { workspaceId, projectId: one.projectId }
    const source = one.recordings.source.names
    await registerColorPipeline(db, { ...oneScope, actor, artifactId: source.sourceArtifactId, manifestId: source.sourceManifestId })
    const askOne = () => afterCommand({ ...oneScope, expectedProjectVersionId: one.head.version.id, actor, idempotencyKey: `w66cp-${run}-one-proxy` })
    const enqueued = await askOne()
    assert.equal(enqueued.status, 'enqueued')
    assert.equal(enqueued.replayed, false)
    const replayed = await askOne()
    assert.equal(replayed.status, 'enqueued')
    assert.equal(replayed.replayed, true)
    assert.equal(replayed.operation.id, enqueued.operation.id)
    assert.equal((await state(one.projectId)).operations, 1)
  } finally {
    await db.$disconnect()
  }
})
