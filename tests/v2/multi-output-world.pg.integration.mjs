import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import test from 'node:test'

import { PrismaClient } from '../../generated/prisma-v2/index.js'
import { renderOperationVariantId, renderOutputReferences } from '../../src/v2/domain/output-variant-references.ts'
import { requirePersistedOutputConsumptionV3, readStoredOutputStateV3 } from '../../src/v2/infrastructure/prisma/output-state-consumption.ts'
import { insertControlledProxyRender, seedTwoOutputIngestedProject } from './helpers/multi-output-pg-world.mjs'
import { testActor } from './helpers/pg-output-world.mjs'

/**
 * Multi-output foundations against a real PostgreSQL (slice S3, multi-output): a project with a 9:16 and a 16:9 output over one
 * recording. Code for a SUPERVISED run (isolated database, migrated and generated by the owner; the `outputVariantId` columns of
 * migration 20261017160000 must exist); every identity is unique to this invocation and nothing is cleaned up.
 *
 * It proves:
 *   1. The world is what the product builds: two State entries, one per output, distinct aspect ratios, both materialized from the
 *      same plan, and the stored State is the one the Version seals.
 *   2. The consumption verdict resolves each output apart by its stable variant (the aspect ratio of the 9:16 output is 9:16, of the
 *      16:9 output 16:9), refuses a caller that names none (`output-variant-required`) and one that names a stranger
 *      (`output-variant-unknown`), and the seals of the two outputs differ.
 *   3. A proxy render operation records the output it was made for (the composite FK keeps it inside the project), and the renders of
 *      the Version are attributed to their own outputs by `renderOutputReferences`; an operation naming a variant of another project
 *      is refused by the database.
 */
const enabled = process.env.APOLLO_RUN_W66_MULTI_OUTPUT_PG === '1'

test('W66 PostgreSQL a project with two outputs resolves, seals and attributes each output apart', { skip: !enabled, timeout: 240_000 }, async () => {
  const run = randomUUID().replaceAll('-', '').slice(0, 10)
  const workspaceId = `w66mo-${run}-ws`, clientId = `w66mo-${run}-client`
  const actor = testActor({ workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production', scopes: ['projects:write', 'projects:read', 'media:write'] })
  const db = new PrismaClient()
  try {
    const world = await seedTwoOutputIngestedProject(db, { workspaceId, actor, prefix: 'w66mo', ids: { project: `w66mo-${run}-project` } })
    const { projectId, head } = world
    const scope = { workspaceId, projectId }

    // 1. the world
    const entries = head.state.document.entries
    assert.equal(entries.length, 2)
    assert.deepEqual(entries.map((entry) => entry.variantId).toSorted(), [world.verticalVariantId, world.wideVariantId].toSorted())
    assert.ok(entries.every((entry) => entry.consumption.status === 'materialized'))
    const ratioOf = (variantId) => entries.find((entry) => entry.variantId === variantId).spec.output.aspectRatio
    assert.equal(ratioOf(world.verticalVariantId), '9:16')
    assert.equal(ratioOf(world.wideVariantId), '16:9')
    const stored = await readStoredOutputStateV3(db, { ...scope, versionId: head.version.id })
    assert.equal(stored.state.stateHash, head.state.stateHash)

    // 2. the verdict by variant
    const wide = await requirePersistedOutputConsumptionV3(db, { ...scope, versionId: head.version.id, variantId: world.wideVariantId, purpose: 'render' })
    const vertical = await requirePersistedOutputConsumptionV3(db, { ...scope, versionId: head.version.id, variantId: world.verticalVariantId, purpose: 'render' })
    assert.equal(wide.aspectRatio, '16:9')
    assert.equal(vertical.aspectRatio, '9:16')
    assert.notEqual(wide.sealHash, vertical.sealHash)
    assert.equal(wide.seal.variantId, world.wideVariantId)
    assert.equal(vertical.seal.outputStateHash, head.state.stateHash)
    const refusal = (reason) => (error) => error?.code === 'PRECONDITION_REQUIRED' && error.details?.reason === reason
    await assert.rejects(() => requirePersistedOutputConsumptionV3(db, { ...scope, versionId: head.version.id, purpose: 'render' }), refusal('output-variant-required'))
    await assert.rejects(() => requirePersistedOutputConsumptionV3(db, { ...scope, versionId: head.version.id, variantId: `${world.wideVariantId}-stranger`, purpose: 'render' }), refusal('output-variant-unknown'))

    // 3. the renders of the Version, each for its own output
    const headRow = await db.v2ProjectVersion.findUniqueOrThrow({ where: { id: head.version.id } })
    const source = { artifactId: world.recording.names.sourceArtifactId, manifestId: world.recording.names.sourceManifestId }
    const wideRender = await insertControlledProxyRender(db, { workspaceId, clientId, projectId, version: headRow, source, outputVariantId: world.wideVariantId, label: 'wide', run })
    const verticalRender = await insertControlledProxyRender(db, { workspaceId, clientId, projectId, version: headRow, source, outputVariantId: world.verticalVariantId, label: 'vertical', run })
    const rows = await db.v2ProjectProxyRenderOperation.findMany({ where: { ...scope, projectVersionId: head.version.id, operation: { status: 'succeeded', phase: 'completed' } },
      select: { operationId: true, outputArtifactId: true, outputVariantId: true } })
    assert.equal(rows.length, 2)
    const references = renderOutputReferences({ state: stored.state, sourceVersionId: head.version.id, proxies: rows, finals: [] })
    assert.deepEqual(references.map((reference) => [reference.artifactId, reference.variantId]).toSorted(),
      [[wideRender.artifactId, world.wideVariantId], [verticalRender.artifactId, world.verticalVariantId]].toSorted())
    for (const row of rows) assert.equal(renderOperationVariantId(stored.state, row), row.outputVariantId)

    // a render cannot name an output of another project: the composite FK refuses it
    const other = await seedTwoOutputIngestedProject(db, { workspaceId, actor, prefix: 'w66mo-other', ids: { project: `w66mo-${run}-other` } })
    await assert.rejects(() => insertControlledProxyRender(db, { workspaceId, clientId, projectId, version: headRow, source, outputVariantId: other.wideVariantId, label: 'stranger', run }),
      (error) => /foreign key|Foreign key/.test(String(error?.message)))
  } finally { await db.$disconnect() }
})
