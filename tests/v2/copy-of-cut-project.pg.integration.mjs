/**
 * The owner's correction of a finished project goes on a COPY of the cut project (W70 rehearsal, phase 7). Code for a SUPERVISED run
 * (isolated database, migrated and generated by the owner); every identity is unique to this invocation and nothing is cleaned up.
 *
 * A copy owns no authority until an editorial cut binds the original's observations to it, so on a copy of a project that was already cut:
 *   1. the copy already carries the cut (its EditPlan is the original's, retimed by the original's own cut) and the Director refuses to run
 *      on it with the reason an operator can act on (`copy-requires-editorial-cut`), never "project not found";
 *   2. the cut the copy asks for with the removals the request already names ADOPTS the applied cut: nothing is cut again, the clips and the
 *      duration stay, and the Version carries the editorial binding (the very authority a first cut of a copy binds: the Creation fork);
 *   3. a cut with a rule of its own removes ADDITIONAL speech from what is left (the speech is already retimed);
 *   4. the Director then runs on the copy, from the transcript the binding names, and the copy is admitted for a render.
 * Every Version reads back from PostgreSQL exactly as it was built.
 */
const enabled = process.env.APOLLO_RUN_W70_COPY_OF_CUT_PG === '1'

const WORDS = [
  { word: 'Primeira', start: 0.2, end: 0.7 }, { word: 'frase', start: 0.7, end: 1.1 },
  { word: 'termina', start: 1.1, end: 1.6 }, { word: 'aqui.', start: 1.6, end: 2.0 },
  { word: 'Segunda', start: 3.0, end: 3.5 }, { word: 'frase', start: 3.5, end: 3.9 },
  { word: 'continua', start: 3.9, end: 4.5 }, { word: 'ainda.', start: 4.5, end: 5.0 },
]

test('W70 PostgreSQL a copy of a cut project adopts the cut, takes additional cuts and then the Director', { skip: !enabled, timeout: 600_000 }, async () => {
  const run = randomUUID().replaceAll('-', '').slice(0, 10)
  const workspaceId = `w70cc-${run}-ws`, clientId = `w70cc-${run}-client`
  const actor = testActor({ workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production', scopes: ['projects:write', 'projects:read', 'media:write'] })
  const db = new PrismaClient()
  try {
    const world = await seedSealedProject(db, { workspaceId, actor, prefix: 'w70cc', ids: { project: `w70cc-${run}-project` }, name: 'Cut project' })
    const directed = await seedDirectedProject(db, { workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production',
      projectId: world.projectId, suffix: `w70cc${run}`, words: WORDS })
    const operational = new PrismaOperationalOutputBundleRepositoryV3(db)
    const head = await operational.read({ workspaceId, projectId: world.projectId, versionId: directed.versions.directed })
    const transcriptId = JSON.parse(head.editPlanSnapshot.contentJson).retimedTranscript.sourceTranscriptId

    let allocations = 0
    const cut = applyEditorialCutCommandService({ repository: new PrismaEditorialCommandRepository(db), clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => `w70cc-${run}-${kind}-${++allocations}` })
    const request = (projectId, base, label, rule, range) => ({ workspaceId, projectId, baseVersionId: base.version.id, baseHash: base.version.baseHash,
      sourceTranscriptId: transcriptId, variantId: base.state.document.entries[0].variantId,
      rules: [{ id: rule, label: rule, alternatives: [rule] }],
      exclusionOverrides: [{ sourceStartSeconds: range[0], sourceEndSeconds: range[1], ruleIds: [rule], reason: `The reviewer cuts "${rule}".` }],
      reason: `Cut ${label}.`, actor, idempotency: { clientId, key: `w70cc-${run}-cut-${label}` } })

    // The project is cut and then directed (as in the real journey: cut, Director, proxies, finals): the copy forks the Director's Version.
    const cutOwn = await cut(request(world.projectId, head, 'own', 'termina', [1.1, 2.0]))
    const directOwn = await runProjectDirectorService({ repository: new PrismaDirectorRunRepository(db), clock: () => new Date(), createEventId: randomUUID,
      compileBrief: createEvidenceBoundBriefCompiler(), createId: (kind) => `w70cc-${run}-own-dir-${kind}-${++allocations}` })({
      workspaceId, projectId: world.projectId, baseVersionId: cutOwn.version.id, baseHash: cutOwn.version.baseHash, actor, idempotency: { key: `w70cc-${run}-own-director` }, reason: 'Director over the cut project.' })
    // The project was delivered: a render of its plan is a media link of the project, and the copy carries every link (the owner states its rights).
    const directedRow = await db.v2ProjectVersion.findUniqueOrThrow({ where: { id: directOwn.version.id } })
    const observed = head.state.document.entries[0].consumption.materialization.document.normalizations[0].document.source
    const render = await insertControlledProxyRender(db, { workspaceId, clientId, projectId: world.projectId, version: directedRow,
      source: { artifactId: observed.artifactId, manifestId: observed.manifestId }, outputVariantId: head.state.document.entries[0].variantId, label: 'delivered', run })
    await persistCurrentRights(db, createAssetRightsSnapshot({ id: `rights-${render.artifactId}-1`, workspaceId, artifactId: render.artifactId, sequence: 1,
      draft: { status: 'approved', allowedUses: [...RECORDING_ALLOWED_USES], prohibitedUses: [], sourceNote: 'the owner states the rights of the delivered render', consent: { status: 'not-required', allowedUses: [] } },
      createdBy: { type: 'api-client', id: clientId }, createdAt: new Date().toISOString() }))
    const own = { version: directOwn.version, editPlan: JSON.parse(operationalBundlePlanV3(await operational.read({ workspaceId, projectId: world.projectId, versionId: directOwn.version.id })).contentJson) }
    const planOf = (bundle) => JSON.parse(operationalBundlePlanV3(bundle).contentJson)
    const clipsOf = (plan) => plan.videoTracks.flatMap((track) => track.clips.map((clip) => [clip.sourceInFrame, clip.sourceOutFrame, clip.timelineInFrame, clip.timelineOutFrame]))
    let copyAllocations = 0
    const copy = await duplicateProjectService({ repository: new PrismaProjectDuplicationRepository(db), clock: () => new Date(), createEventId: randomUUID,
      createId: (kind) => kind === 'project-media-asset' ? randomUUID() : `w70cc-${run}-copy-${kind}-${++copyAllocations}` })({
      workspaceId, projectId: world.projectId, expectedVersionId: own.version.id, expectedVersionHash: own.version.baseHash, name: 'Correction copy', actor,
      idempotency: { clientId, key: `w70cc-${run}-dup` } })
    const copyScope = { workspaceId, projectId: copy.project.id }
    const root = await operational.read({ ...copyScope, versionId: copy.version.id })
    assert.equal(forkAuthorityPendingV3(root), true)
    assert.equal(planOf(root).durationFrames, own.editPlan.durationFrames, 'the copy carries the original\'s cut plan')

    // 1. The Director refuses on the copy, with the reason it can be acted on.
    let directions = 0
    const direct = (base, key) => runProjectDirectorService({ repository: new PrismaDirectorRunRepository(db), clock: () => new Date(), createEventId: randomUUID,
      compileBrief: createEvidenceBoundBriefCompiler(), createId: (kind) => `w70cc-${run}-dir-${key}-${kind}-${++directions}` })({
      ...copyScope, baseVersionId: base.version.id, baseHash: base.version.baseHash, actor, idempotency: { key: `w70cc-${run}-${key}` }, reason: `Director ${key}.` })
    const versionsBefore = await db.v2ProjectVersion.count({ where: copyScope })
    await assert.rejects(direct(root, 'refused'), (error) => error.code === 'PRECONDITION_REQUIRED' && error.details?.reason === 'copy-requires-editorial-cut')
    assert.equal(await db.v2ProjectVersion.count({ where: copyScope }), versionsBefore, 'the refusal wrote nothing')

    // 2. The same removals adopt the applied cut: nothing is cut again.
    const adopted = await cut(request(copy.project.id, root, 'adopt', 'termina', [1.1, 2.0]))
    assert.equal(adopted.version.parentVersionId, copy.version.id)
    assert.equal(adopted.editPlan.durationFrames, own.editPlan.durationFrames, 'nothing more was removed')
    assert.deepEqual(clipsOf(adopted.editPlan), clipsOf(own.editPlan), 'the clips are the original\'s cut')
    const binding = editorialDerivedBindingV3(adopted.outputBundle)
    assert.equal(binding.document.authority.kind, 'fork-derivation3')
    assert.equal(binding.document.authority.forkRootVersionId, copy.version.id)
    assert.equal(forkAuthorityPendingV3(adopted.outputBundle), false)
    assert.equal(serializeOutputCanonicalJson(await operational.read({ ...copyScope, versionId: adopted.version.id })), serializeOutputCanonicalJson(adopted.outputBundle),
      'the adopting cut reads back exactly as it was built')
    assert.equal(await db.v2OutputNormalizationReceipt.count({ where: copyScope }), 0, 'the copy owns no receipt: it binds the original\'s')
    // On a project that is not a copy awaiting its authority, speech that is already removed is still refused (nothing to remove).
    await assert.rejects(cut(request(world.projectId, await operational.read({ workspaceId, projectId: world.projectId, versionId: own.version.id }), 'again', 'termina', [1.1, 2.0])),
      (error) => error.code === 'INVALID_COMMAND')

    // 3. A rule of its own removes ADDITIONAL speech from the speech that is left.
    const further = await cut(request(copy.project.id, adopted.outputBundle, 'further', 'continua', [3.9, 4.5]))
    assert.ok(further.editPlan.durationFrames < adopted.editPlan.durationFrames, 'additional speech left the timeline')
    assert.equal(serializeOutputCanonicalJson(await operational.read({ ...copyScope, versionId: further.version.id })), serializeOutputCanonicalJson(further.outputBundle))

    // 4. The Director runs on the copy, from the transcript its binding names, and the copy is admitted for a render.
    const rerun = await direct(further.outputBundle, 'rerun')
    assert.equal(rerun.run.baseVersionId, further.version.id)
    const stored = await operational.read({ ...copyScope, versionId: rerun.version.id })
    assert.equal(stored.origin.kind, 'child-command')
    assert.notEqual(editorialDerivedBindingV3(stored), null, 'the Director\'s Version carries the binding')
    assert.equal((await db.v2Project.findUnique({ where: { id: copy.project.id } })).currentVersionId, rerun.version.id)
    const verdict = await requirePersistedOutputConsumptionV3(db, { ...copyScope, versionId: rerun.version.id, purpose: 'render' })
    assert.ok(verdict, 'the copy is admitted for a render')
  } finally { await db.$disconnect() }
})
