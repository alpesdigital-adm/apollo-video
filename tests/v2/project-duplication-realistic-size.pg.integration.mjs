import assert from 'node:assert/strict'
import { randomUUID } from 'node:crypto'
import test from 'node:test'

import { PrismaClient } from '../../generated/prisma-v2/index.js'
import { duplicateProjectService } from '../../src/v2/application/duplicate-project.ts'
import { PrismaOperationalOutputBundleRepositoryV3 } from '../../src/v2/infrastructure/prisma/output-version-bundle-repository.ts'
import { PrismaProjectDuplicationRepository } from '../../src/v2/infrastructure/prisma/project-duplication-repository.ts'
import { seedTwoOutputIngestedProject } from './helpers/multi-output-pg-world.mjs'
import { testActor } from './helpers/pg-output-world.mjs'

/**
 * The duplication of a project whose State embeds the receipt of a real master (W70 rehearsal defect). Code for a SUPERVISED run (isolated
 * database, migrated and generated by the owner); every identity is unique to this invocation and nothing is cleaned up.
 *
 * The receipt of a 103 s master carries 3.085 frames of video and the State of two outputs plus its bundle weigh 8 MB. Duplicating such a
 * project used to exceed the fixed 30 s of the interactive transaction on every attempt (P2028), or the 10 s of the statement that settles
 * its deferred guards (57014). It proves, against the real repositories and the real database guards:
 *   1. the duplication commits, three times in a row, with neither limit raised and no guard weakened;
 *   2. the copy is a project of its own over the SAME sealed Version content: it names the original as its source, keeps both outputs under
 *      identities of its own, and its brief snapshot (the editorial request and what was read of it) is byte-identical - the duplication
 *      writes no request of its own;
 *   3. asking again with the same key answers the very same copy (replay) and writes nothing.
 * Durations are printed (wall time of each duplication) so a run on a given machine leaves its own evidence.
 */
const enabled = process.env.APOLLO_RUN_W70_DUPLICATION_PG === '1'

test('W70 PostgreSQL a project with the receipt of a real master is duplicated inside the transaction limits', { skip: !enabled, timeout: 900_000 }, async () => {
  const run = randomUUID().replaceAll('-', '').slice(0, 10)
  const workspaceId = `w70dup-${run}-ws`, clientId = `w70dup-${run}-client`
  const actor = testActor({ workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production', scopes: ['projects:write', 'projects:read', 'media:write'] })
  const db = new PrismaClient()
  try {
    const frames = Number(process.env.W70_DUPLICATION_FRAMES ?? 3085)
    const world = await seedTwoOutputIngestedProject(db, { workspaceId, actor, prefix: 'w70dup', ids: { project: `w70dup-${run}-project` }, recording: { slug: 'source', durationFrames: frames } })
    const head = world.head
    const [{ n }] = await db.$queryRawUnsafe('SELECT length("bundleJson") AS n FROM output_operational_bundles WHERE "versionId" = $1', head.version.id)
    assert.ok(Number(n) > 4_000_000, `the head bundle is of realistic size (${n} bytes)`)
    assert.equal(head.state.document.entries.length, 2)
    const operational = new PrismaOperationalOutputBundleRepositoryV3(db)

    const durations = []
    const copies = []
    for (let index = 1; index <= 3; index++) {
      let allocations = 0
      const duplicate = () => duplicateProjectService({ repository: new PrismaProjectDuplicationRepository(db), clock: () => new Date(), createEventId: randomUUID,
        createId: (kind) => kind === 'project-media-asset' ? randomUUID() : `w70dup-${run}-copy${index}-${kind}-${++allocations}` })({
        workspaceId, projectId: world.projectId, expectedVersionId: head.version.id, expectedVersionHash: head.version.baseHash, name: `Realistic copy ${index}`, actor,
        idempotency: { clientId, key: `w70dup-${run}-dup-${index}` } })
      const started = performance.now()
      const copy = await duplicate()
      durations.push(Math.round(performance.now() - started))
      copies.push(copy)
      assert.equal(copy.replayed, false)
      assert.equal(copy.project.duplicatedFromProjectId, world.projectId)
      assert.equal(copy.version.forkedFromProjectId, world.projectId)
      assert.equal(copy.version.forkedFromVersionId, head.version.id)

      // Replay: the same key answers the same copy and writes nothing.
      const before = await db.v2Project.count({ where: { workspaceId } })
      const again = await duplicate()
      assert.equal(again.replayed, true)
      assert.equal(again.project.id, copy.project.id)
      assert.equal(await db.v2Project.count({ where: { workspaceId } }), before)
    }
    console.log(`duplication of a ${(Number(n) / 1e6).toFixed(1)} MB head (${frames} frames, 2 outputs): ${durations.join('/')} ms (N=3)`)

    // The copy is the original's content under identities of its own; the editorial request is the original's, not a new one.
    const sourceSnapshots = await db.v2ProjectSnapshot.findMany({ where: { id: { in: Object.values(head.version.snapshotRefs) } }, orderBy: { kind: 'asc' } })
    for (const copy of copies) {
      const copyHead = await operational.read({ workspaceId, projectId: copy.project.id, versionId: copy.version.id })
      assert.equal(copyHead.state.document.entries.length, 2, 'both outputs are copied')
      const sourceVariants = new Set(head.state.document.entries.map((entry) => entry.variantId))
      assert.ok(copyHead.state.document.entries.every((entry) => !sourceVariants.has(entry.variantId)), 'the copy has identities of its own')
      const copySnapshots = await db.v2ProjectSnapshot.findMany({ where: { id: { in: Object.values(copy.version.snapshotRefs) } }, orderBy: { kind: 'asc' } })
      assert.equal(copySnapshots.length, sourceSnapshots.length)
      copySnapshots.forEach((snapshot, position) => {
        assert.equal(snapshot.kind, sourceSnapshots[position].kind)
        if (snapshot.kind === 'brief') {
          assert.equal(snapshot.contentJson, sourceSnapshots[position].contentJson, 'the brief (editorial request and its reading) is the original\'s, byte for byte')
          assert.equal(snapshot.contentHash, sourceSnapshots[position].contentHash)
        }
      })
    }
  } finally {
    await db.$disconnect()
  }
})
