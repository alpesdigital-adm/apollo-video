/**
 * ADR-160 F6 against a real PostgreSQL, through the published routes: a project is created with a briefing, the briefing is read by the
 * interpreter (the real OpenAI API adapter, pointed at a local stand-in that this suite scripts: no network, no credential, no real model; the Codex CLI adapter
 * - the primary provider - refuses to start on a machine whose system-wide Codex folder has hooks, so its proof is the unit suite with a stand-in executable),
 * and the Director plans from what was read.
 *
 *   1. The briefing of the project is a request nobody has read: the read says so, and the Director refuses it with the published reason.
 *   2. With no interpreter configured the revise Command fails closed (PRECONDITION_REQUIRED / brief-interpreter-unavailable) and writes nothing.
 *   3. A reading that raises a question blocks the Director with the question; a reading that cites words the briefing does not contain is
 *      refused and writes nothing; editing the briefing is read again and the question is gone.
 *   4. The Director plans from the reading: its run seals the request hash of the brief, and the cta policy names the briefing as its origin.
 *   5. A replay never calls the model again; a stale base is a conflict; the stored Version reads back through the routes.
 *
 * Code for a SUPERVISED run (isolated database, migrated and generated by the owner); every identity is unique to this invocation.
 */
const enabled = process.env.APOLLO_EDITORIAL_REQUEST_PG === '1'

const BRIEFING = 'alpha beta gamma delta'
const CONFIGURATION = ['APOLLO_V2_BRIEF_INTERPRETER_PROVIDER', 'APOLLO_V2_CODEX_BIN', 'APOLLO_V2_CODEX_HOME', 'APOLLO_V2_BRIEF_INTERPRETER_MODEL', 'OPENAI_API_KEY', 'APOLLO_V2_BRIEF_INTERPRETER_BASE_URL']

async function callRoute(NextRequest, module, { method, path, params = {}, body, authorization, idempotencyKey }) {
  const headers = new Headers()
  if (authorization) headers.set('authorization', authorization)
  if (idempotencyKey) headers.set('idempotency-key', idempotencyKey)
  const init = { method, headers }
  if (body !== undefined) { headers.set('content-type', 'application/json'); init.body = JSON.stringify(body) }
  const response = await module[method](new NextRequest(new URL(`http://apollo.invalid${path}`), init), { params: Promise.resolve(params) })
  const text = await response.text()
  return { status: response.status, payload: text.length > 0 ? JSON.parse(text) : null }
}

test('ADR-160 F6 a briefing is read by the interpreter through /v1 and the Director plans from what was read', { skip: !enabled, timeout: 600_000 }, async () => {
  const saved = Object.fromEntries(CONFIGURATION.map((name) => [name, process.env[name]]))
  for (const name of CONFIGURATION) delete process.env[name]
  const interpreter = await startBriefInterpreterStandIn({ fallback: undefined })
  const run = randomUUID().replaceAll('-', '').slice(0, 10)
  const workspaceId = `f6req-${run}-ws`, clientId = `f6req-${run}-client`
  const seedActor = testActor({ workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production', scopes: ['projects:write', 'projects:read', 'media:write'] })
  const db = new PrismaClient()
  try {
    const { NextRequest } = await import('next/server')
    const { createApiClientService } = await import('../../src/v2/application/create-api-client.ts')
    const { PrismaApiClientRepository } = await import('../../src/v2/infrastructure/prisma/api-client-repository.ts')
    const { nodeApiCredentialCrypto } = await import('../../src/v2/infrastructure/security/api-credential.ts')
    const { runProjectDirectorService } = await import('../../src/v2/application/run-project-director.ts')
    const { PrismaDirectorRunRepository } = await import('../../src/v2/infrastructure/prisma/director-run-repository.ts')
    const { createEvidenceBoundBriefCompiler } = await import('../../src/v2/infrastructure/brief/evidence-bound-brief-compiler-model.ts')
    const route = await import('../../src/app/v1/projects/[projectId]/editorial-request/route.ts')
    const projectsRoute = await import('../../src/app/v1/projects/route.ts')

    // The world: a project created WITH a briefing (the creation service the POST /v1/projects route calls), and the Version the Director directs.
    const world = await seedSealedProject(db, { workspaceId, actor: seedActor, prefix: 'f6req', name: 'Editorial request world', briefing: BRIEFING })
    const seeded = await seedDirectedProject(db, { workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production',
      projectId: world.projectId, suffix: `f6req${run}`, directed: false,
      words: [{ word: 'Primeira', start: 0.2, end: 0.7 }, { word: 'frase', start: 0.7, end: 1.1 }, { word: 'termina', start: 1.1, end: 1.6 }, { word: 'aqui.', start: 1.6, end: 2.0 }] })
    const projectId = world.projectId
    const issue = createApiClientService({ repository: new PrismaApiClientRepository(db), credentialCrypto: nodeApiCredentialCrypto, clock: () => new Date() })
    const caller = await issue({ id: `f6req-${run}-api`, workspaceId, name: 'editorial request journey', environment: process.env.APOLLO_API_ENVIRONMENT ?? 'sandbox', scopes: ['projects:read', 'projects:write'] })
    const authorization = `Bearer ${caller.token}`
    const path = `/v1/projects/${projectId}/editorial-request`
    const get = () => callRoute(NextRequest, route, { method: 'GET', path, params: { projectId }, authorization })
    const revise = (body, key) => callRoute(NextRequest, route, { method: 'POST', path, params: { projectId }, authorization, idempotencyKey: key, body })
    const headOf = async () => {
      const row = await db.v2ProjectVersion.findUniqueOrThrow({ where: { id: (await db.v2Project.findUniqueOrThrow({ where: { id: projectId } })).currentVersionId } })
      return { baseVersionId: row.id, baseHash: row.baseHash }
    }
    const versionCount = () => db.v2ProjectVersion.count({ where: { projectId } })
    const director = (head, key) => runProjectDirectorService({
      repository: new PrismaDirectorRunRepository(db), clock: () => new Date(), createEventId: randomUUID, compileBrief: createEvidenceBoundBriefCompiler(),
      createId: (kind) => `f6req-${run}-${key}-${kind}-${randomUUID().slice(0, 8)}`,
    })({ workspaceId, projectId, ...head, actor: seedActor, idempotency: { key: `f6req-${run}-${key}` }, reason: 'Director over the request.' })

    // The creation route takes a briefing as the editorial request: any non-empty text, no locale required.
    const created = await callRoute(NextRequest, projectsRoute, { method: 'POST', path: '/v1/projects', authorization, idempotencyKey: `f6req-${run}-create`,
      body: { name: 'Created through the route', objective: 'discovery', briefing: 'x' } })
    assert.equal(created.status, 201, JSON.stringify(created.payload))

    // 1. A briefing nobody has read.
    const unread = await get()
    assert.equal(unread.status, 200, JSON.stringify(unread.payload))
    assert.equal(unread.payload.data.state, 'awaiting-interpretation')
    assert.equal(unread.payload.data.blocksDirector, true)
    assert.equal(unread.payload.data.request.briefing.text, BRIEFING)
    assert.equal(unread.payload.data.interpretation, null)
    await assert.rejects(director(await headOf(), 'unread'), (error) => error.code === 'PRECONDITION_REQUIRED' && error.details.reason === 'brief-interpretation-required')

    // 2. No interpreter configured: fail closed, nothing written.
    const before = await versionCount()
    const unavailable = await revise({ ...(await headOf()), briefing: BRIEFING }, `f6req-${run}-unavailable`)
    assert.equal(unavailable.status, 428, JSON.stringify(unavailable.payload))
    assert.equal(unavailable.payload.error.code, 'PRECONDITION_REQUIRED')
    assert.deepEqual(unavailable.payload.error.details, { reason: 'brief-interpreter-unavailable' })
    assert.equal(await versionCount(), before)

    Object.assign(process.env, interpreter.environment)

    // 3a. A reading that cites words the briefing does not contain is refused whole; nothing is written.
    interpreter.script.set(BRIEFING, { directives: [{ kind: 'cta', value: 'none', param: null, quote: 'words that are nowhere in the briefing' }], unsupported: [], questions: [], coverage: [] })
    const invented = await revise({ ...(await headOf()), briefing: BRIEFING }, `f6req-${run}-invented`)
    assert.ok(invented.status >= 400, JSON.stringify(invented.payload))
    assert.equal(invented.payload.error.code, 'RENDER_OUTPUT_INVALID')
    assert.equal(await versionCount(), before)

    // 3b. A reading that raises a question blocks the Director, with the question.
    interpreter.script.set(BRIEFING, { directives: [], unsupported: [], questions: [{ question: 'Which of the two is meant?', quote: 'alpha' }], coverage: [{ topic: 'tone', quote: 'beta' }] })
    const asked = await revise({ ...(await headOf()), briefing: BRIEFING, reason: 'Read the briefing.' }, `f6req-${run}-asked`)
    assert.equal(asked.status, 201, JSON.stringify(asked.payload))
    assert.equal(asked.payload.data.command.type, 'revise-editorial-request')
    assert.equal(asked.payload.data.interpreted, true)
    assert.equal(asked.payload.data.state, 'interpreted')
    assert.equal(asked.payload.data.blocksDirector, true)
    assert.deepEqual(asked.payload.data.openQuestions.map((question) => [question.id, question.excerpt]), [['q1', 'alpha']])
    assert.equal(asked.payload.data.interpretationAudit.provider, 'openai')
    assert.equal(asked.payload.data.interpretationAudit.resolvedModel, 'stand-in-resolved')
    assert.equal(asked.payload.data.interpretationAudit.costBasis, 'api-metered')
    assert.equal(asked.payload.data.interpretationAudit.costMinorUnits, null)
    assert.match(asked.payload.data.interpretationAudit.modelInputHash, /^[a-f0-9]{64}$/)
    assert.deepEqual(asked.payload.data.interpretationAudit.usage, { inputTokens: 100, outputTokens: 20 })
    assert.equal(asked.payload.data.impact.renderBlockedUntilDirectorRun, true)
    assert.equal(interpreter.calls.length >= 1 && interpreter.calls.every((call) => call.authorized && call.path === '/v1/chat/completions'), true)
    assert.ok(interpreter.calls.every((call) => call.body.messages[0].role === 'system' && !call.body.messages[0].content.includes(BRIEFING)), 'the briefing never reaches the standing instruction')
    const readAfter = await get()
    assert.equal(readAfter.payload.data.hashes.requestHash, asked.payload.data.hashes.requestHash)
    assert.equal(readAfter.payload.data.hashes.briefSnapshotId, asked.payload.data.hashes.briefSnapshotId)
    await assert.rejects(director(await headOf(), 'question'), (error) =>
      error.code === 'PRECONDITION_REQUIRED' && error.details.reason === 'editorial-request-blocked' && error.details.openQuestions[0].id === 'q1')

    // 3c. Answering is revising: the briefing is edited, read again, and the old question goes with the old text.
    const edited = `${BRIEFING} epsilon`
    interpreter.script.set(edited, { directives: [{ kind: 'cta', value: 'none', param: null, quote: 'epsilon' }], unsupported: [], questions: [], coverage: [] })
    const callsBefore = interpreter.calls.length
    const answered = await revise({ ...(await headOf()), briefing: edited }, `f6req-${run}-edited`)
    assert.equal(answered.status, 201, JSON.stringify(answered.payload))
    assert.equal(interpreter.calls.length, callsBefore + 1)
    assert.equal(answered.payload.data.blocksDirector, false)
    assert.deepEqual(answered.payload.data.openQuestions, [])
    assert.equal(answered.payload.data.change.briefing, 'replaced')

    // 5a. A replay never calls the model again; a different body under the same key is refused; a stale base is a conflict.
    const replayed = await revise({ baseVersionId: answered.payload.data.command.baseVersionId, baseHash: (await db.v2ProjectVersion.findFirstOrThrow({ where: { id: answered.payload.data.command.baseVersionId } })).baseHash, briefing: edited }, `f6req-${run}-edited`)
    assert.equal(replayed.status, 200, JSON.stringify(replayed.payload))
    assert.equal(replayed.payload.data.replayed, true)
    assert.equal(interpreter.calls.length, callsBefore + 1)
    const mismatch = await revise({ baseVersionId: answered.payload.data.command.baseVersionId, baseHash: (await db.v2ProjectVersion.findFirstOrThrow({ where: { id: answered.payload.data.command.baseVersionId } })).baseHash, briefing: `${edited}!` }, `f6req-${run}-edited`)
    assert.equal(mismatch.payload.error.code, 'IDEMPOTENCY_PAYLOAD_MISMATCH')
    const stale = await revise({ baseVersionId: answered.payload.data.command.baseVersionId, baseHash: 'f'.repeat(64), briefing: `${edited} again` }, `f6req-${run}-stale`)
    assert.equal(stale.payload.error.code, 'VERSION_CONFLICT')
    assert.equal(interpreter.calls.length, callsBefore + 1)

    // 4. The Director plans from the reading.
    const directed = await director(await headOf(), 'directed')
    const stored = await get()
    assert.equal(directed.run.requestHash, stored.payload.data.hashes.requestHash, 'the run seals the request the API shows')
    // The cta policy follows the desired action; the overlay is the policy the briefing's directive decides, and it names the briefing as its origin.
    assert.equal(directed.run.policyResolution.policies.ctaOverlay.origin, 'request-briefing')
    assert.equal(directed.run.policyResolution.policies.ctaOverlay.value.mode, 'none')
    assert.equal(stored.payload.data.state, 'interpreted')
    assert.equal(stored.payload.data.interpretation.directives[0].excerpt.text, 'epsilon')
    assert.equal(seeded.versions.base !== directed.version.id, true)

    // 6. Rendering is blocked until a new Director run: after the request is revised, the report the Director sealed no longer admits the final.
    const { admitDirectorQualityForFinal } = await import('../../src/v2/domain/final-caption-certification.ts')
    const { deriveEditorialRequestFromBrief } = await import('../../src/v2/domain/editorial-request.ts')
    const briefOfHead = async () => {
      const row = await db.v2ProjectVersion.findUniqueOrThrow({ where: { id: (await db.v2Project.findUniqueOrThrow({ where: { id: projectId } })).currentVersionId }, include: { briefSnapshot: true } })
      return JSON.parse(row.briefSnapshot.contentJson)
    }
    const binding = async () => ({ currentRequestHash: deriveEditorialRequestFromBrief(await briefOfHead()).requestHash, sealedRequestHash: directed.run.requestHash,
      sealedPolicyResolutionHash: directed.run.policyResolution.policyResolutionHash })
    assert.equal(admitDirectorQualityForFinal(directed.run.qualityReport, await binding()).admitted, true, 'the report the run sealed admits the final of the request it judged')
    const revised = await revise({ ...(await headOf()), directives: [{ id: 'f6-after', kind: 'movement', value: 'none' }] }, `f6req-${run}-after`)
    assert.equal(revised.status, 201, JSON.stringify(revised.payload))
    assert.equal(revised.payload.data.impact.renderBlockedUntilDirectorRun, true)
    assert.equal(revised.payload.data.impact.renderSemanticsChanged, true)
    const refusal = admitDirectorQualityForFinal(directed.run.qualityReport, await binding())
    assert.equal(refusal.admitted, false)
    assert.match(refusal.reason, /editorial request changed after this Director run/)
    // ... and a new Director run over the revised request is admitted again.
    const redirected = await director(await headOf(), 'redirected')
    assert.equal(redirected.run.requestHash, revised.payload.data.hashes.requestHash)
    assert.equal(admitDirectorQualityForFinal(redirected.run.qualityReport, { currentRequestHash: redirected.run.requestHash, sealedRequestHash: redirected.run.requestHash, sealedPolicyResolutionHash: redirected.run.policyResolution.policyResolutionHash }).admitted, true)

    // 6b. The reading of a briefing belongs to the text, not to a render: a project is read WHEN IT IS CREATED (the reading is sealed in the brief the
    // creation Command carries), with no output and no montage to speak of. With no interpreter the briefing is kept unread (step 1 above: the first project).
    interpreter.script.set(BRIEFING, { directives: [{ kind: 'layout', value: 'source-native', param: null, quote: 'alpha' }], unsupported: [], questions: [{ question: 'Which of the two is meant?', quote: 'beta' }], coverage: [{ topic: 'tone', quote: 'gamma' }] })
    const rootCallsBefore = interpreter.calls.length
    const rootCreated = await callRoute(NextRequest, projectsRoute, { method: 'POST', path: '/v1/projects', authorization, idempotencyKey: `f6req-${run}-create-root`,
      body: { name: 'Root read at creation', objective: 'discovery', briefing: BRIEFING } })
    assert.equal(rootCreated.status, 201, JSON.stringify(rootCreated.payload))
    assert.equal(interpreter.calls.length, rootCallsBefore + 1, 'the briefing was read once, at creation')
    const rootId = rootCreated.payload.data.projectAtCreation.id
    const rootPath = `/v1/projects/${rootId}/editorial-request`
    const rootGet = () => callRoute(NextRequest, route, { method: 'GET', path: rootPath, params: { projectId: rootId }, authorization })
    const rootRead = await rootGet()
    assert.equal(rootRead.status, 200, JSON.stringify(rootRead.payload))
    assert.equal(rootRead.payload.data.state, 'interpreted', 'a project just created has its briefing read')
    assert.equal(rootRead.payload.data.blocksDirector, true)
    assert.deepEqual(rootRead.payload.data.openQuestions.map((question) => [question.id, question.excerpt]), [['q1', 'beta']])
    assert.equal(rootRead.payload.data.interpretation.directives[0].excerpt.text, 'alpha')
    assert.equal(rootRead.payload.data.interpretationAudit.provider, 'openai')
    // Revising it needs an output (a revision is a child Command): its own published reason says so, and nothing is written.
    const rootRow = await db.v2ProjectVersion.findFirstOrThrow({ where: { projectId: rootId } })
    const refused = await callRoute(NextRequest, route, { method: 'POST', path: rootPath, params: { projectId: rootId }, authorization, idempotencyKey: `f6req-${run}-root-revise`,
      body: { baseVersionId: rootRow.id, baseHash: rootRow.baseHash, answers: [{ questionId: 'q1', answer: 'The first.' }] } })
    assert.equal(refused.status, 428, JSON.stringify(refused.payload))
    assert.deepEqual(refused.payload.error.details, { reason: 'editorial-request-needs-output' })
    assert.equal(await db.v2ProjectVersion.count({ where: { projectId: rootId } }), 1)
    // A replay of the creation never gives another reading to the project.
    const replay = await callRoute(NextRequest, projectsRoute, { method: 'POST', path: '/v1/projects', authorization, idempotencyKey: `f6req-${run}-create-root`,
      body: { name: 'Root read at creation', objective: 'discovery', briefing: BRIEFING } })
    assert.equal(replay.status, 200, JSON.stringify(replay.payload))
    assert.equal(replay.payload.data.projectAtCreation.id, rootId)

    // 7. A project that states no language (no locale is assumed) is read by the repositories that judge rights under the undetermined locale; none
    // of them stops on the missing one any more, and none answers with another error for it.
    const { UNDETERMINED_LOCALE } = await import('../../src/v2/domain/asset-rights.ts')
    const { PrismaAssetSelectionRepository } = await import('../../src/v2/infrastructure/prisma/asset-selection-repository.ts')
    const { PrismaQualityIterationRepository } = await import('../../src/v2/infrastructure/prisma/quality-iteration-repository.ts')
    const { PrismaMusicAnalysisRunRepository } = await import('../../src/v2/infrastructure/prisma/music-analysis-run-repository.ts')
    const silent = await seedSealedProject(db, { workspaceId, actor: seedActor, prefix: 'f6nolocale', name: 'A project with no language', locale: null })
    assert.equal((await db.v2Project.findUniqueOrThrow({ where: { id: silent.projectId } })).locale, null)
    const selection = await new PrismaAssetSelectionRepository(db).readProjectContext({ workspaceId, projectId: silent.projectId })
    assert.equal(selection.locale, UNDETERMINED_LOCALE)
    const iteration = await new PrismaQualityIterationRepository(db).readContext({ workspaceId, projectId: silent.projectId, projectVersionId: silent.head.version.id, proxyReviewId: 'f6-no-such-review', assetSelectionIds: [] })
    assert.equal(iteration, null, 'the missing proxy review is the only thing it can say')
    const music = new PrismaMusicAnalysisRunRepository(db)
    const authority = (extra) => music.resolveRequestAuthority({ workspaceId, projectId: silent.projectId, projectVersionId: silent.head.version.id, artifactId: 'f6-no-such-artifact', at: new Date().toISOString(), ...extra })
    await assert.rejects(authority({}), (error) => error.code === 'ASSET_NOT_USABLE' && !/localized/.test(error.message))
    // A version that is no longer the current one is a conflict (409); only a project that does not exist is "not found".
    await assert.rejects(authority({ projectVersionId: 'f6-an-old-version' }), (error) => error.code === 'VERSION_CONFLICT')
    await assert.rejects(authority({ projectId: 'f6-no-such-project' }), (error) => error.code === 'PROJECT_NOT_FOUND')

    // 8. A project made without an objective: the Director waits for one (published reason), the owner gives it in a revision (closed catalog, a new
    // Version, projects.objective written in the same transaction), and the Director then runs; a second Director run closes the revision path.
    const bare = await seedSealedProject(db, { workspaceId, actor: seedActor, prefix: 'f6bare', name: 'A project with no objective', objective: null })
    await seedDirectedProject(db, { workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production', projectId: bare.projectId, suffix: `f6bare${run}`, directed: false,
      words: [{ word: 'Segunda', start: 0.2, end: 0.7 }, { word: 'fala', start: 0.7, end: 1.1 }, { word: 'sem', start: 1.1, end: 1.4 }, { word: 'objetivo.', start: 1.4, end: 2.0 }] })
    assert.equal((await db.v2Project.findUniqueOrThrow({ where: { id: bare.projectId } })).objective, null)
    const barePath = `/v1/projects/${bare.projectId}/editorial-request`
    const bareHead = async () => {
      const row = await db.v2ProjectVersion.findUniqueOrThrow({ where: { id: (await db.v2Project.findUniqueOrThrow({ where: { id: bare.projectId } })).currentVersionId } })
      return { baseVersionId: row.id, baseHash: row.baseHash }
    }
    const bareRevise = async (body, key) => callRoute(NextRequest, route, { method: 'POST', path: barePath, params: { projectId: bare.projectId }, authorization, idempotencyKey: `f6req-${run}-${key}`, body: { ...(await bareHead()), ...body } })
    const bareDirector = async (key) => runProjectDirectorService({
      repository: new PrismaDirectorRunRepository(db), clock: () => new Date(), createEventId: randomUUID, compileBrief: createEvidenceBoundBriefCompiler(),
      createId: (kind) => `f6req-${run}-${key}-${kind}-${randomUUID().slice(0, 8)}`,
    })({ workspaceId, projectId: bare.projectId, ...(await bareHead()), actor: seedActor, idempotency: { key: `f6req-${run}-${key}` }, reason: 'Director over a project that gets its objective.' })
    await assert.rejects(bareDirector('bare-before'), (error) => error.code === 'PRECONDITION_REQUIRED' && error.details?.reason === 'director-objective-required')
    const versionsBefore = await db.v2ProjectVersion.count({ where: { projectId: bare.projectId } })
    const unknownObjective = await bareRevise({ objective: 'content-distribution' }, 'bare-unknown')
    assert.equal(unknownObjective.status, 422, JSON.stringify(unknownObjective.payload))
    assert.equal(await db.v2ProjectVersion.count({ where: { projectId: bare.projectId } }), versionsBefore, 'a refused objective writes nothing')
    const defined = await bareRevise({ objective: 'awareness', reason: 'O dono escolheu o objetivo.' }, 'bare-define')
    assert.equal(defined.status, 201, JSON.stringify(defined.payload))
    assert.equal(defined.payload.data.change.objective, 'set')
    assert.equal(defined.payload.data.request.objective, 'awareness')
    assert.equal((await db.v2Project.findUniqueOrThrow({ where: { id: bare.projectId } })).objective, 'awareness', 'the project row carries the objective the revision set')
    assert.equal(await db.v2ProjectVersion.count({ where: { projectId: bare.projectId } }), versionsBefore + 1, 'a new Version, the old one kept')
    const bareRead = await callRoute(NextRequest, route, { method: 'GET', path: barePath, params: { projectId: bare.projectId }, authorization })
    assert.equal(bareRead.payload.data.request.objective, 'awareness')
    const same = await bareRevise({ objective: 'awareness' }, 'bare-same')
    assert.equal(same.status, 422, 'the project already has this objective')
    const bareDirected = await bareDirector('bare-after')
    assert.equal(bareDirected.run.objective, 'awareness', 'the Director judges against the objective the owner gave')
    const afterDirector = await bareRevise({ objective: 'warming' }, 'bare-after-director')
    assert.equal(afterDirector.status, 422, JSON.stringify(afterDirector.payload))
    assert.equal((await db.v2Project.findUniqueOrThrow({ where: { id: bare.projectId } })).objective, 'awareness')

    // 9. A subject spoken in PASSAGES (ADR-160): the Director asks to confirm the stretches of speech that talk about the subject; the person is shown a sealed proposal, may
    // keep one passage on purpose and move where another starts; a confirmation of something else than what was shown, or outside the limits, writes nothing; the
    // confirmation is a remove-spoken-content Command that records what was cut, what was kept and the seal in the database, and the Director reads it back.
    {
    const CUT_BRIEFING = 'tire o trecho sobre vender'
    const sentences = [
      [0, 1, 'Bem-vindos ao curso.'], [1, 2, 'Vamos vender bem.'], [2, 3, 'Tudo começa pela escuta.'], [3, 4, 'Depois vem a confiança.'], [4, 5, 'Em seguida o preço.'],
      [5, 6, 'Também o prazo.'], [6, 7, 'E o suporte.'], [7, 8, 'O produto foi vendido ontem.'], [8, 9, 'Foi um sucesso.'], [9, 10, 'Agora vamos ao conteúdo.'],
    ]
    const cutWords = sentences.flatMap(([start, end, text]) => {
      const spoken = text.replace(/[.,]/gu, '').split(' ')
      const step = (end - start) / spoken.length
      return spoken.map((word, index) => ({ word, start: Math.round((start + index * step) * 1000) / 1000, end: Math.round((start + (index + 1) * step - 0.02) * 1000) / 1000 }))
    })
    const cutSegments = sentences.map(([start, end, text], id) => ({ id, start, end, text }))
    const cutWorld = await seedSealedProject(db, { workspaceId, actor: seedActor, prefix: 'f6cut', name: 'Passages to cut', briefing: CUT_BRIEFING })
    await seedDirectedProject(db, { workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production', projectId: cutWorld.projectId, suffix: `f6cut${run}`, directed: false, words: cutWords, segments: cutSegments })
    const cutProjectId = cutWorld.projectId
    const cutHead = async () => {
      const row = await db.v2ProjectVersion.findUniqueOrThrow({ where: { id: (await db.v2Project.findUniqueOrThrow({ where: { id: cutProjectId } })).currentVersionId } })
      return { baseVersionId: row.id, baseHash: row.baseHash }
    }
    const cutVersions = () => db.v2ProjectVersion.count({ where: { projectId: cutProjectId } })
    const cutCommands = () => db.v2EditCommand.count({ where: { projectId: cutProjectId, type: 'remove-spoken-content' } })
    const cutDirector = async (key) => runProjectDirectorService({
      repository: new PrismaDirectorRunRepository(db), clock: () => new Date(), createEventId: randomUUID, compileBrief: createEvidenceBoundBriefCompiler(),
      createId: (kind) => `f6req-${run}-${key}-${kind}-${randomUUID().slice(0, 8)}`,
    })({ workspaceId, projectId: cutProjectId, ...(await cutHead()), actor: seedActor, idempotency: { key: `f6req-${run}-${key}` }, reason: 'Director over a subject spoken in passages.' })
    interpreter.script.set(CUT_BRIEFING, { directives: [{ kind: 'remove-speech', value: 'about', param: 'vender', quote: 'tire o trecho sobre vender' }], unsupported: [], questions: [], coverage: [] })
    const read = await callRoute(NextRequest, route, { method: 'POST', path: `/v1/projects/${cutProjectId}/editorial-request`, params: { projectId: cutProjectId }, authorization,
      idempotencyKey: `f6req-${run}-cut-read`, body: { ...(await cutHead()), briefing: CUT_BRIEFING, reason: 'Read the briefing.' } })
    assert.equal(read.status, 201, JSON.stringify(read.payload))
    const blocked = await cutDirector('cut-blocked').then(() => null, (error) => error)
    assert.equal(blocked?.code, 'PRECONDITION_REQUIRED', String(blocked?.message))
    assert.equal(blocked.details.reason, 'editorial-request-blocked')
    const removal = blocked.details.openQuestions.find((question) => question.removal)?.removal
    // The two mentions are five sentences apart: two passages, each with its own limits.
    assert.equal(removal.passages.length, 2)
    const [first, second] = removal.passages
    assert.deepEqual([first.startSeconds, first.endSeconds, second.startSeconds, second.endSeconds], [1, 2, 7, 8])
    assert.equal(first.text, 'Vamos vender bem.')
    assert.deepEqual(second.mentions.map((mention) => mention.text), ['vendido'])
    assert.equal(removal.search.matching, 'stem')
    assert.match(removal.proposalHash, /^[a-f0-9]{64}$/)
    assert.equal(removal.confirmed, undefined, 'nothing is confirmed until a person confirms')
    assert.equal(await cutCommands(), 0, 'nothing is cut')

    const { confirmSpeechRemovalService } = await import('../../src/v2/application/confirm-speech-removal.ts')
    const factory = await import('../../src/v2/infrastructure/repository-factory.ts')
    const granted = testActor({ workspaceId, clientId, credentialId: `${clientId}-cred`, environment: 'production', scopes: ['projects:write', 'speech-removals:confirm'] })
    const confirm = confirmSpeechRemovalService({
      requests: factory.createEditorialRequestRepository(), cuts: factory.createEditorialCommandRepository(), clock: () => new Date(),
      createId: (kind) => `f6cut-${run}-${kind}-${randomUUID().slice(0, 8)}`, createEventId: randomUUID,
    })
    const cutRequest = async (key, extra = {}) => ({
      workspaceId, projectId: cutProjectId, ...(await cutHead()), sourceTranscriptId: removal.sourceTranscriptId, variantId: cutWorld.variantId, subject: 'vender',
      proposalHash: removal.proposalHash, actor: granted, idempotency: { clientId, key: `f6req-${run}-${key}` }, ...extra,
    })
    // Refused whole, writing nothing: a seal that is not the one of what was shown; an adjustment off the boundaries or the limits or leaving the mention out; nothing to cut;
    // a kept passage that is also adjusted.
    const versionsBeforeCut = await cutVersions()
    await assert.rejects(confirm(await cutRequest('cut-seal', { proposalHash: 'a'.repeat(64) })), (error) => error.code === 'VERSION_CONFLICT' && error.details?.reason === 'speech-removal-proposal-changed')
    for (const [label, extra] of [
      ['off a boundary', { adjustments: [{ passageId: first.id, startSeconds: 0.5, endSeconds: 2 }] }],
      ['beyond the limit of the neighbour', { adjustments: [{ passageId: first.id, startSeconds: 1, endSeconds: 8 }] }],
      ['leaving the mention out', { adjustments: [{ passageId: second.id, startSeconds: 8, endSeconds: 9 }] }],
      ['nothing left to cut', { discardedPassageIds: [first.id, second.id] }],
      ['a kept passage adjusted', { discardedPassageIds: [first.id], adjustments: [{ passageId: first.id, startSeconds: 0, endSeconds: 2 }] }],
      ['a passage of nowhere', { discardedPassageIds: ['passage-0000000000'] }],
    ]) {
      await assert.rejects(confirm(await cutRequest(`cut-refused-${label.replaceAll(' ', '-')}`, extra)), (error) => error.code === 'INVALID_ARGUMENT', label)
    }
    assert.equal(await cutVersions(), versionsBeforeCut)
    assert.equal(await cutCommands(), 0)
    // The person keeps the first passage on purpose and starts the second one sentence earlier (the start of a segment, inside its limits).
    const cut = await confirm(await cutRequest('cut-confirmed', { discardedPassageIds: [first.id], adjustments: [{ passageId: second.id, startSeconds: 6, endSeconds: 8 }] }))
    assert.deepEqual(cut.exclusions.map((range) => [range.sourceStartSeconds, range.sourceEndSeconds]), [[6, 8]])
    const storedCut = JSON.parse((await db.v2EditCommand.findFirstOrThrow({ where: { projectId: cutProjectId, type: 'remove-spoken-content' } })).payloadJson)
    assert.equal(storedCut.confirmation.medium, 'api-key-scope')
    assert.deepEqual(storedCut.confirmation.passages.map(({ id, ...rest }) => rest), [{ startSeconds: 6, endSeconds: 8, proposedStartSeconds: 7, proposedEndSeconds: 8, adjusted: true }])
    assert.deepEqual(storedCut.confirmation.discarded, [{ id: first.id, startSeconds: 1, endSeconds: 2 }], 'what was kept on purpose is recorded')
    assert.equal(storedCut.confirmation.search.policy.name, 'speech-passage-adjacency/v2')
    assert.deepEqual(storedCut.exclusionOverrides.map((override) => [override.sourceStartSeconds, override.sourceEndSeconds]), [[6, 8]])
    // The Director reads the confirmation back from the stored Command: the question is answered, although the subject is still said in the passage that was kept.
    const answered = await cutDirector('cut-answered')
    assert.ok(answered.run.policyResolution.satisfied.some((item) => item.kind === 'remove-speech' && item.how === 'confirmed-removal'))

    // The shape of the confirmation the database accepts: a missing or null value is a refusal, never a pass.
    const accepts = async (confirmation) => (await db.$queryRawUnsafe('SELECT w66_editorial_confirmation_v1($1::jsonb) AS ok', JSON.stringify(confirmation)))[0].ok
    const policy = { name: 'p', maxGapSeconds: 1, maxGapSentences: 1, maxSentenceSeconds: 1, maxPassageSeconds: 1, maxMentions: 1 }
    const search = { matching: 'stem', language: 'pt', lexicon: null, policy }
    const passage = { id: 'passage-1', startSeconds: 1, endSeconds: 2, proposedStartSeconds: 1, proposedEndSeconds: 2, adjusted: false }
    const valid = { subject: 'x', medium: 'ui-session', passages: [passage], search }
    assert.equal(await accepts(valid), true)
    assert.equal(await accepts({ subject: 'x', medium: 'api-key-scope' }), true)
    assert.equal(await accepts({ ...valid, discarded: [{ id: 'passage-2', startSeconds: 3, endSeconds: 4 }] }), true)
    for (const [label, bad] of [
      ['medium null', { ...valid, medium: null }], ['medium unknown', { ...valid, medium: 'anonymous' }], ['matching null', { ...valid, search: { ...search, matching: null } }],
      ['matching unknown', { ...valid, search: { ...search, matching: 'magic' } }], ['id empty', { ...valid, passages: [{ ...passage, id: '' }] }], ['id null', { ...valid, passages: [{ ...passage, id: null }] }],
      ['subject empty', { ...valid, subject: '' }], ['adjusted lies', { ...valid, passages: [{ ...passage, adjusted: true }] }], ['end before start', { ...valid, passages: [{ ...passage, endSeconds: 0.5, proposedEndSeconds: 0.5 }] }],
      ['passages empty', { ...valid, passages: [] }], ['search missing', { subject: 'x', medium: 'ui-session', passages: [passage] }], ['key too many', { ...valid, extra: 1 }],
      ['policy short', { ...valid, search: { ...search, policy: { name: 'p' } } }], ['discarded id empty', { ...valid, discarded: [{ id: '', startSeconds: 3, endSeconds: 4 }] }],
      ['discarded without passages', { subject: 'x', medium: 'ui-session', discarded: [{ id: 'a', startSeconds: 3, endSeconds: 4 }] }], ['lexicon number', { ...valid, search: { ...search, lexicon: 3 } }],
    ]) {
      assert.equal(await accepts(bad), false, label)
    }
    }
  } finally {
    await interpreter.close()
    for (const name of CONFIGURATION) {
      if (saved[name] === undefined) delete process.env[name]
      else process.env[name] = saved[name]
    }
    await db.$disconnect()
  }
})
