const execFileAsync = promisify(execFile)
const FFMPEG = ffmpegStatic ?? 'ffmpeg'

/**
 * F4.010 — the detectors against real recordings with a known offset.
 *
 * Every fixture is generated by FFmpeg at test time rather than committed, so
 * nothing large lives in the repository and the inputs are reproducible from
 * the code that describes them.
 *
 * The measurement that matters: the marker is planted at a *known* offset in a
 * recording that also contains unrelated content, and the detectors have to
 * find it. A detector that is handed the answer proves nothing, which is
 * exactly what the code this replaces did.
 */

const MARKER = createSyncMarker({
  markerId: 'marker-detect-1',
  workspaceId: 'workspace-1',
  sessionId: 'capture-session-detect',
  kind: 'audiovisual',
  position: 'start',
  sequence: 1,
  emittedAt: '2029-04-01T09:00:00.000Z',
})

/**
 * A recording with the marker planted `offsetMs` in.
 *
 * Before the marker: mid-grey frames and a spoken-frequency tone, so the
 * detector has to reject plausible content rather than a silent black gap.
 */
async function buildRecording(input) {
  const { workRoot, name, offsetMs, markerPath, totalMs = 3_000, noise = false, falseFlash = false } = input
  const output = join(workRoot, `${name}.mp4`)
  const leadMs = offsetMs
  const tailMs = Math.max(0, totalMs - offsetMs - 167)

  // Filler audio: a 300 Hz tone, in the range speech occupies, plus optional
  // white noise. Silence would make the correlation trivially easy.
  const fillerPcm = join(workRoot, `${name}-filler.pcm`)
  const sampleRate = 48_000
  const fillerSamples = Math.round((totalMs / 1_000) * sampleRate)
  const filler = Buffer.alloc(fillerSamples * 2)
  for (let index = 0; index < fillerSamples; index += 1) {
    const t = index / sampleRate
    let value = Math.sin(2 * Math.PI * 300 * t) * 0.25
    if (noise) value += (Math.sin(index * 12.9898) * 43758.5453 % 1) * 0.25
    filler.writeInt16LE(Math.max(-32768, Math.min(32767, Math.round(value * 32767))), index * 2)
  }
  await writeFile(fillerPcm, filler)

  const videoFilter = falseFlash
    // A single bright frame a second in: exactly the thing one flash would be
    // mistaken for, and what the three-frame alternation exists to survive.
    ? `color=c=gray:s=640x360:r=30:d=${(totalMs / 1000).toFixed(3)},`
      + `geq=lum='if(eq(N\\,30)\\,255\\,128)':cb=128:cr=128`
    : `color=c=gray:s=640x360:r=30:d=${(totalMs / 1000).toFixed(3)}`

  await execFileAsync(FFMPEG, [
    '-hide_banner', '-nostdin', '-y',
    '-f', 'lavfi', '-i', videoFilter,
    '-f', 's16le', '-ar', String(sampleRate), '-ac', '1', '-i', fillerPcm,
    '-i', markerPath,
    '-filter_complex', [
      `[2:v]setpts=PTS-STARTPTS+${(leadMs / 1000).toFixed(4)}/TB[mk]`,
      `[0:v][mk]overlay=enable='between(t,${(leadMs / 1000).toFixed(4)},${((leadMs + 167) / 1000).toFixed(4)})'[v]`,
      `[2:a]adelay=${leadMs}|${leadMs}[ma]`,
      `[1:a][ma]amix=inputs=2:duration=first:normalize=0[a]`,
    ].join(';'),
    '-map', '[v]', '-map', '[a]',
    '-c:v', 'libx264', '-preset', 'ultrafast', '-pix_fmt', 'yuv420p',
    '-c:a', 'aac', '-ar', String(sampleRate),
    '-t', (totalMs / 1000).toFixed(3),
    output,
  ], { maxBuffer: 64 * 1024 * 1024, timeout: 180_000 })
  void tailMs
  return output
}

test('T-FR-148 both detectors find a planted marker at its known offset', async (t) => {
  const workRoot = await mkdtemp(join(tmpdir(), 'apollo-detect-'))
  t.after(async () => { await rm(workRoot, { recursive: true, force: true }) })

  const renderer = new FfmpegSyncMarkerRenderer({ workRoot })
  const artifact = await renderer.render(MARKER)
  const OFFSET_MS = 800
  const recording = await buildRecording({
    workRoot, name: 'clean', offsetMs: OFFSET_MS, markerPath: artifact.filePath,
  })

  const options = { workRoot }
  // Run them separately and never pass one result to the other. Two detectors
  // that agree because one was told the answer are one detector in disguise.
  const visual = await detectVisualMarker({
    marker: MARKER, mediaPath: recording, trackId: 'track-a',
    observationId: 'obs-v-1', options,
  })
  const audio = await detectAudioMarker({
    marker: MARKER, mediaPath: recording, trackId: 'track-a',
    observationId: 'obs-a-1', options,
  })

  assert.ok(visual, 'the visual detector found nothing')
  assert.ok(audio, 'the audio detector found nothing')

  console.log(
    `visual: at ${visual.atMs} ms (+-${visual.errorMs}), pattern ${visual.patternScore.toFixed(2)}, `
    + `code ${visual.decodedPayload ? 'decoded' : 'unreadable'} | `
    + `audio: at ${audio.atMs.toFixed(1)} ms, peak ${audio.correlationPeak.toFixed(3)} vs ${audio.secondPeak.toFixed(3)}`,
  )

  // Within a frame of where it was planted. The frame grid is the floor of
  // what frame extraction can resolve, so anything tighter would be luck.
  assert.ok(
    Math.abs(visual.atMs - OFFSET_MS) <= 34,
    `visual found ${visual.atMs} ms, expected about ${OFFSET_MS}`,
  )
  assert.ok(
    Math.abs(audio.atMs - OFFSET_MS) <= 34,
    `audio found ${audio.atMs} ms, expected about ${OFFSET_MS}`,
  )
  // The chirp beats the 300 Hz filler by a wide margin; that separation is
  // what makes the reading a measurement rather than a guess.
  assert.ok(
    audio.correlationPeak > audio.secondPeak * 3,
    `audio peak ${audio.correlationPeak} is not clearly above its runner-up ${audio.secondPeak}`,
  )

  const fused = fuseMarkerDetections({
    marker: MARKER, trackId: 'track-a', mode: 'both-channels', visual, audio,
  })
  assert.equal(fused.outcome, 'confirmed')
  assert.ok(Math.abs(fused.atMs - OFFSET_MS) <= 34)
})

test('T-FR-148 a lone bright frame does not pass for the marker', async (t) => {
  const workRoot = await mkdtemp(join(tmpdir(), 'apollo-false-flash-'))
  t.after(async () => { await rm(workRoot, { recursive: true, force: true }) })

  const renderer = new FfmpegSyncMarkerRenderer({ workRoot })
  const artifact = await renderer.render(MARKER)
  // The marker is present at 1800 ms; a single bright frame sits at 1000 ms.
  // The alternation has to win over the impostor.
  const recording = await buildRecording({
    workRoot, name: 'false-flash', offsetMs: 1_800, markerPath: artifact.filePath, falseFlash: true,
  })

  const visual = await detectVisualMarker({
    marker: MARKER, mediaPath: recording, trackId: 'track-a',
    observationId: 'obs-v-2', options: { workRoot },
  })
  assert.ok(visual)
  console.log(`false-flash fixture: visual settled at ${visual.atMs} ms with score ${visual.patternScore.toFixed(2)}`)
  assert.ok(
    Math.abs(visual.atMs - 1_800) <= 34,
    `the single bright frame at 1000 ms won: detector returned ${visual.atMs} ms`,
  )
})

test('T-FR-148 a chirp under noise is still found, and a foreign chirp is not this marker', async (t) => {
  const workRoot = await mkdtemp(join(tmpdir(), 'apollo-noise-'))
  t.after(async () => { await rm(workRoot, { recursive: true, force: true }) })

  const renderer = new FfmpegSyncMarkerRenderer({ workRoot })
  const artifact = await renderer.render(MARKER)
  const recording = await buildRecording({
    workRoot, name: 'noisy', offsetMs: 1_200, markerPath: artifact.filePath, noise: true,
  })

  const audio = await detectAudioMarker({
    marker: MARKER, mediaPath: recording, trackId: 'track-a',
    observationId: 'obs-a-3', options: { workRoot },
  })
  assert.ok(audio, 'the chirp was lost in noise')
  console.log(`noisy fixture: audio at ${audio.atMs.toFixed(1)} ms, peak ${audio.correlationPeak.toFixed(3)}`)
  assert.ok(Math.abs(audio.atMs - 1_200) <= 34, `audio found ${audio.atMs} ms, expected about 1200`)

  // A chirp with a different sweep is a different signal. Correlating the
  // wrong reference must not produce a confident hit at the same place.
  const foreign = createSyncMarker({
    markerId: 'marker-foreign', workspaceId: 'workspace-1',
    sessionId: 'capture-session-other', kind: 'audiovisual', position: 'start',
    sequence: 1, emittedAt: '2029-04-01T09:00:00.000Z',
    audio: { startHz: 6_000, endHz: 9_000, durationMs: 200, sampleRate: 48_000 },
  })
  const wrongReference = await detectAudioMarker({
    marker: foreign, mediaPath: recording, trackId: 'track-a',
    observationId: 'obs-a-4', options: { workRoot },
  })
  assert.ok(wrongReference)
  console.log(`foreign chirp: peak ${wrongReference.correlationPeak.toFixed(3)} vs ${wrongReference.secondPeak.toFixed(3)}`)
  assert.ok(
    wrongReference.correlationPeak < audio.correlationPeak,
    'a chirp the recording never contained correlated as well as the one it did',
  )
})

test('T-FR-148 the synthesized chirp sweeps at the rate it claims', () => {
  // Guards the phase-integration bug directly: evaluating sin(2*PI*f(t)*t)
  // instead of integrating gives roughly double the intended sweep, which no
  // amount of downstream correlation would reveal as wrong.
  const pcm = synthesizeChirp({ startHz: 1_000, endHz: 4_000, durationMs: 200, sampleRate: 48_000 })
  const samples = new Float64Array(pcm.length / 2)
  for (let index = 0; index < samples.length; index += 1) samples[index] = pcm.readInt16LE(index * 2) / 32_768

  const crossingsIn = (from, to) => {
    let count = 0
    for (let index = from + 1; index < to; index += 1) {
      if ((samples[index - 1] < 0 && samples[index] >= 0) || (samples[index - 1] >= 0 && samples[index] < 0)) count += 1
    }
    // Two zero crossings per cycle, over the window's duration.
    return (count / 2) / ((to - from) / 48_000)
  }
  // Measured away from the fades, which suppress amplitude near the edges.
  const early = crossingsIn(600, 1_800)
  const late = crossingsIn(7_800, 9_000)
  console.log(`chirp: ~${early.toFixed(0)} Hz early, ~${late.toFixed(0)} Hz late`)
  assert.ok(early > 900 && early < 2_000, `early frequency ${early.toFixed(0)} Hz is not near the 1 kHz start`)
  assert.ok(late > 3_000 && late < 4_400, `late frequency ${late.toFixed(0)} Hz is not near the 4 kHz end`)
})
