/**
 * PLAN-EDITING Commands against a real PostgreSQL on projects with two outputs and with one (slice S3, multi-output, workstream 1b).
 *
 * A manual edit, a review patch (single or batch), an editorial cut and a manual restore/undo change the ONE EditPlan every output of a
 * project re-materializes from. The `variantId` of a manual edit or of a cut is the VIEW it was made on (a stable State variant); the
 * impact lists the renders of EVERY output, each under its own stable variant, and so do the invalidation rows. The database guards that
 * re-derive the impact of a restore and of a cut derive it the same way (migration 20261018100000).
 *
 * Code for a SUPERVISED run (isolated database, migrated and generated by the owner; the `outputVariantId` columns of migration
 * 20261017160000 and the guards of 20261018100000 must exist); every identity is unique to this invocation and nothing is cleaned up.
 *
 * It proves, on the two-output world (a controlled proxy render is seeded for EACH output of the head Version before each Command):
 *   1. A manual edit made on the vertical output commits, its impact lists both outputs and both renders, the invalidation rows exist for
 *      both, and the child carries both entries untouched; an unknown view, the aspect ratio in its place and a missing view are refused
 *      with their reason (output-variant-unknown / INVALID_ARGUMENT) and write nothing.
 *   2. A review patch whose annotation names ONE format commits with the renders of both outputs stale; an annotation naming a format the
 *      State does not carry is refused as output-variant-unknown at proposal time and writes nothing. A review batch does the same.
 *   3. A render-free selection commits without any invalidation; a restore and an undo over Versions with the proxies of both outputs
 *      commit (the database guard accepts the all-output impact) with one invalidation per render; a render that appears between the
 *      admission and the commit refuses the restore. A proxy written before the column existed cannot be attributed in a Version with two
 *      outputs: the Command is refused with PERSISTENCE_CONFLICT.
 *   4. An editorial cut over a Version with the proxies of both outputs commits, with the invalidations of each render, and reads back as
 *      it was built.
 *   5. A project with ONE output behaves as it always did: a cut, a manual edit and an undo over a proxy written before the column existed
 *      commit with one invalidation.
 * Published final exports are attributed with the same function; their persistence needs director runs and quality snapshots no
 * controlled world seeds, so they are proved at the unit level (manual-edit-multi-output.test.mjs, review-patch-multi-output.test.mjs).
 */
