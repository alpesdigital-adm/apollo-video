    assert.deepEqual(await k.snapshot(), beforeStranger)
    // 2b. an annotation scoped to the VERTICAL format only
    const scoped = await seedAnnotation({ base: v1, formatIds: [VERTICAL], proxy: verticalProxy, operation: layout('subtitle:cue-1', { anchor: 'center' }, [400, 800]), tag: 'vertical' })
    const patched = await applyReviewPatchService(reviewDeps)({ ...k.scope, proposalId: scoped.proposalId, confirmed: true, actor, idempotencyKey: `w66plan-${run}-patch` })
    assert.equal(patched.impact.commandType, 'apply-review-patch')
    await assertPlanWide(db, k, patched, { base: v1, renders: r1, variants })
    assert.equal(patched.editPlan.subtitleTracks[0].cues[0].anchor, 'center')

    // 2c. a review batch of two annotations, one per format
    const v2 = await k.headBase()
    assert.equal(v2.id, patched.version.id)
    const r2 = await k.seedRenders(v2, 'v2', outputs)
    const proxy2 = r2.find((render) => render.key === 'wide')
    const one = await seedAnnotation({ base: v2, formatIds: [VERTICAL], proxy: proxy2, operation: layout('subtitle:cue-1', { anchor: 'top' }, [400, 800]), tag: 'batch-one' })
    const two = await seedAnnotation({ base: v2, formatIds: [WIDE], proxy: proxy2, operation: { op: 'update-text', targetId: 'subtitle:cue-2', value: { text: 'Segunda revisada' }, rangeMs: [1200, 1700] }, tag: 'batch-two' })
