    assert.deepEqual(await k.snapshot(), beforeBatchRefusal)
    const batch = (await proposeBatch([one.proposalId, two.proposalId], `w66plan-${run}-batch`)).batch
    assert.equal(batch.status, 'ready')
    const batched = await applyReviewPatchBatchService({ repository: batchRepository, clock: () => new Date(), createId: allocate('a-batch'), createEventId: randomUUID })({
      ...k.scope, batchId: batch.id, confirmed: true, actor, idempotencyKey: `w66plan-${run}-batch-apply` })
    assert.equal(batched.impact.commandType, 'apply-review-patch-batch')
    await assertPlanWide(db, k, batched, { base: v2, renders: r2, variants })
    assert.deepEqual([batched.editPlan.subtitleTracks[0].cues[0].anchor, batched.editPlan.subtitleTracks[0].cues[1].text], ['top', 'Segunda revisada'])

    // 3a. A render-free selection (made on the WIDE view) commits and invalidates nothing, though both outputs have renders.
    const v3 = await k.headBase()
    assert.equal(v3.id, batched.version.id)
    await k.seedRenders(v3, 'v3', outputs)
    const selected = await k.manual(k.manualRequest(v3, { action: 'apply', variantId: WIDE, targetId: clipId, operation: { kind: 'select', clipId }, idempotencyKey: `w66plan-${run}-select` }))
