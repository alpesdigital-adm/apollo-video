export type CapabilityExposure = 'public' | 'workspace-admin' | 'internal-only'
export type CapabilityOperationKind = 'query' | 'command' | 'preflight' | 'job'
export type CapabilityCostClass = 'free' | 'low' | 'medium' | 'high' | 'variable'
export type CapabilityConfirmation = 'none' | 'preflight-token' | 'human-approval'
export type HttpMethod = 'GET' | 'POST' | 'PUT' | 'PATCH' | 'DELETE'
export type CapabilityAuthMode = 'none' | 'optional' | 'required'
export type CapabilityAuthScheme = 'none' | 'bearer' | 'ui-session' | 'signed-token'
export type CapabilityIdempotency = 'not-applicable' | 'required' | 'natural'
export type CapabilityPrecondition = 'if-match' | 'signed-intent'
export type CapabilitySuccessStatus = 200 | 201 | 202 | 204 | 206

export interface CapabilityQueryParameter {
  name: string
  description: string
  required: boolean
  schema: Readonly<{
    type: 'string' | 'integer' | 'number' | 'boolean'
    minimum?: number
    maximum?: number
    minLength?: number
    maxLength?: number
    enum?: readonly (string | number | boolean)[]
    default?: string | number | boolean
  }>
}

export interface PublicCapability {
  id: string
  version: string
  title: string
  description: string
  exposure: CapabilityExposure
  internalOnlySurfaceId?: string
  operationKind: CapabilityOperationKind
  authMode: CapabilityAuthMode
  authScheme?: CapabilityAuthScheme
  requiredScopes: readonly ApiScope[]
  inputSchemaRef?: string
  outputSchemaRef: string
  endpoint?: Readonly<{ method: HttpMethod; path: string }>
  toolName?: string
  supportsDryRun: boolean
  costClass: CapabilityCostClass
  confirmation: CapabilityConfirmation
  successStatuses: readonly CapabilitySuccessStatus[]
  idempotency: CapabilityIdempotency
  precondition?: CapabilityPrecondition
  responseEtag?: boolean
  queryParameters?: readonly CapabilityQueryParameter[]
  requestBodyRequired?: boolean
  requestMediaType?: 'application/json' | 'application/octet-stream'
  responseMediaType?: 'application/json' | 'application/schema+json' | 'application/octet-stream'
  availableIn?: readonly ApiEnvironment[]
}

export interface CapabilityAccessActor {
  clientId: string
  workspaceId: string
  environment: ApiEnvironment
  scopes: ReadonlySet<string>
}

export interface CapabilityAccessPolicy {
  disabled: readonly string[]
  byEnvironment: Readonly<Record<string, readonly string[]>>
  byWorkspace: Readonly<Record<string, readonly string[]>>
  byClient: Readonly<Record<string, readonly string[]>>
}

